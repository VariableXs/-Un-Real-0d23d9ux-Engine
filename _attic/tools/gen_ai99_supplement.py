def distribute(rows_anchor):
    """20条合计6000：锚条=anchor，末条收官印=s，其余均分余量。"""
    n_std = 19  # 锚+19条，其中末4条是标准件
    rest = 6000 - rows_anchor
    base = rest // n_std
    extra = rest - base * n_std
    rows = [rows_anchor] + [base] * n_std
    # 从第2条起前 extra 条各 +1
    for i in range(1, 1 + extra):
        rows[i] += 1
    assert sum(rows) == 6000
    return rows

