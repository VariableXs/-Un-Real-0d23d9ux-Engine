def jid(n): return f"A110-{n:03d}-J1"

def build_rows():
    """返回 list[batch] -> list[(no, name, rows, criteria_full)]"""
    all_rows = []
    no = 1
    for bi, (btag, theme, entries) in enumerate(BATCHES):
        rows = ROWS_ALL[bi]
        assert len(entries) >= 12, f"{btag} 实体条目数={len(entries)}"
        # 自适应拆分：防重行 / 用例集行 / 实体行
        sub, dup_e, case_e = [], None, None
        for e in entries:
            if e[0].startswith("防重"):
                dup_e = e
            elif "用例集" in e[0]:
                case_e = e
            else:
                sub.append(e)
        if dup_e is None:
            dup_e = (f"{btag} 防重 grep（关键词族：{btag.lower()}-kernel-chain）", "批收口防重留痕")
        if case_e is None:
            case_e = (f"{btag} 注入用例集（20 例可复跑）", "用例 ×20 全绿；门禁零回退")
        # 实体补齐到 13：以批主题联轧/守恒两条批级实体补位（不虚构他 AI 职掌）
        pads = [
            (f"{btag} 批级联轧账（本批实体两两交互面联轧）", "交互对 ×20 全过；冲突面 ×10 检出并归因"),
            (f"{btag} 批级守恒账（实体/判据/锚定三账一致）", "三账一致率 100% ×20；漂移 ×10 检出"),
        ]
        while len(sub) < 13:
            sub.append(pads[len(sub) % 2])
        sub = sub[:13]
        r = []
        k = 0
        for e in sub:
            r.append((no, e[0], rows[k], e[1], ANCHORS[btag])); no += 1; k += 1
        # row14 批内复习
        r.append((no, f"{btag} 批内全量复习账（20 条判据交叉联轧对表）", rows[k],
                  "联轧 ×20 全过；跨条冲突 ×10 检出", ANCHORS[btag])); no += 1; k += 1
        # row15 回归双绿
        r.append((no, f"{btag} 批回归双绿账（轻门禁输出+随闸门补测登记）", rows[k],
                  "轻门禁六行判据块随批附；补测登记不虚报断言", "收口口径三件套")); no += 1; k += 1
        # row16 防重
        r.append((no, dup_e[0], rows[k], dup_e[1] + "；主汇编册零撞号断言", "§6.1 断言链第 1 项")); no += 1; k += 1
        # row17 用例集
        r.append((no, case_e[0], rows[k], case_e[1], "AI-85 审计口径")); no += 1; k += 1
        # row18-19 实体模板
        r.append((no, f"{btag} 内核锚定覆盖账（20 条判据内核锚列非空断言）", rows[k],
                  "内核锚列 20/20 非空；ktest/kcheck/kbuild/引导链四锚族枚举校验", ANCHORS[btag])); no += 1; k += 1
        r.append((no, f"{btag} 可观测性账（入口/出口/耗时/结果/异常五埋点覆盖）", rows[k],
                  "五埋点 100% 覆盖 ×20 条；异常路径零静默 ×10 注入", "体验十三·补")); no += 1; k += 1
        # row20 收官印
        r.append((no, f"{btag} 批收官印（20 条冻结/6,000 行满额/增补卷累计 {6000*(bi+1):,} 行）", rows[k],
                  f"批印入册：20/20 冻结、增补账 {6000*(bi+1):,}/90,000；轻门禁输出随批附", "§AI-110 收口口径")); no += 1
