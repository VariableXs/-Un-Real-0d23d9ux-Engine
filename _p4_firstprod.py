        brows = 0
        for i, (name, rows, crit) in enumerate(items):
            if rows is None:
                rows = rows_last
            assert crit.startswith(f"UNX-F{fid:05d}-J1"), (fid, crit[:20])
            lines.append(f"| UNX-F{fid:05d} | {name} | {rows} | 增补 | {crit} |")
