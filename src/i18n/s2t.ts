/** 逐字符简→繁转换（未收录字符原样保留）。 */
export function s2t(s: string): string {
  let out = "";
  for (const ch of s) {
    out += S2T[ch] ?? ch;
  }
  return out;
}

/** 词典级转换：把简体词典映射为繁体词典。 */
export function convertDict(dict: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(dict)) {
    out[k] = s2t(v);
  }
  return out;
}
