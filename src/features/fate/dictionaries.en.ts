export function enName(kind: "personality" | "character" | "ideology" | "random" | "event", id: string): EnEntry | undefined {
  const table = kind === "personality" ? PERSONALITIES
    : kind === "character" ? CHARACTERS
      : kind === "ideology" ? IDEOLOGIES
        : kind === "random" ? RANDOMS
          : kind === "event" ? EVENTS : undefined;
  return table ? table[id] : undefined;
}

export function tagLabel(tag: string, lang: "zh" | "en"): string {
  return lang === "en" ? TAG_EN[tag] ?? tag : tag;
}
