// 行为树词典（FTPE 行为树引擎）：描述"性格如何驱动决策"的节点类型库。
// 每个条目 = 一类行为树节点：composite（组合）/ decorator（装饰）/ leaf（叶）。
// bias 是该行为倾向对事件标签的概率乘子参考表，与 buff/特质模型同一量纲。
// 全部为抽象自构概念，无现实模板；用户可在词典空间继续增删。
// 配套执行器见 ./behaviorTree.ts（tick 语义、确定性可重现）。
// ---------------------------------------------------------------------------

export type BehaviorTreeNodeKind = "composite" | "decorator" | "leaf";

export interface BehaviorTreeNode {
  id: string;
  name: string;
  nameEn: string;
  kind: BehaviorTreeNodeKind;
  /** 通俗解释：这个节点在行为树里负责什么。 */
  desc: string;
  descEn: string;
  /** 挂到该行为上的标签概率乘子（1 = 无影响）。 */
  bias: Partial<Record<FateTag, number>>;
}

const BT = (
  rows: Array<[string, string, BehaviorTreeNodeKind, string, string, Partial<Record<FateTag, number>>]>,
): BehaviorTreeNode[] =>
  rows.map(([name, nameEn, kind, desc, descEn, bias], i) => ({
    id: `bt${String(i + 1).padStart(3, "0")}`,
    name, nameEn, kind, desc, descEn, bias,
  }));

