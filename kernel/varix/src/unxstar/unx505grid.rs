/// 段位守卫：全部诊断码必须落在本段 [0x6480, 0x648f]。
pub const fn t505_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t505Code::ALL.len() {
        let c = t505Code::ALL[i].code();
        if c < 0x6480 || c > 0x648f {
            ok = false;
        }
        i += 1;
    }
    ok
}

