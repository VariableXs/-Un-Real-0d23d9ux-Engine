/// 段位守卫：全部诊断码落在本模块段内。
fn t505_guard_seg() -> bool {
    t505_segment_guard()
}

/// 大表 unx505grid 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t505_grid() -> bool {
    let mut ok = unx505grid_COUNT == 1024;
    if ok {
        ok = unx505grid_get("5050000") == Some(0) && unx505grid_get("5051023") == Some(1023);
    }
    if ok {
        ok = unx505grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t505_sum() -> bool {
    unx505grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t505_checks() -> CheckSet {
    let mut set = CheckSet::new("T505");
    set.add(
        "t505-seg-guard",
        t505_guard_seg(),
        if t505_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t505-c1-grid",
        check_c1_t505_grid(),
        if check_c1_t505_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t505-c2-grid-sum",
        check_c2_t505_sum(),
        if check_c2_t505_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

