/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u2581mx_unique() -> bool {
    let mut i = 0usize;
    while i < u2581mx_COUNT {
        let mut j = i + 1;
        while j < u2581mx_COUNT {
            if u2581mx[i].0 == u2581mx[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

