/// 毫秒粒度（1 = 1ms）。
pub const MS_GRANULARITY: u64 = 1;

/// 计时器（单调毫秒计数 + 回绕安全比较）。
#[derive(Clone, Copy, Debug)]
pub struct MsTimer {
    /// 当前毫秒计数。
    pub now_ms: u64,
    /// 累计溢出回绕次数。
    pub wraps: u64,
    /// 已接管时基（ns per tick 的毫秒换算）。
    pub ns_per_tick: u64,
}

impl MsTimer {
    /// 构造（100Hz 基础 tick = 10ms/tick；接管后 1000Hz = 1ms/tick）。
    pub const fn new() -> Self {
        Self { now_ms: 0, wraps: 0, ns_per_tick: 1_000_000 }
    }

    /// 推进一 tick（按 ns_per_tick 换算成毫秒；不足 1ms 累计进位）。
    pub fn tick(&mut self) -> u64 {
        let advance = self.ns_per_tick / 1_000_000;
        if advance == 0 {
            return 0;
        }
        let next = self.now_ms.wrapping_add(advance);
        if next < self.now_ms {
            self.wraps += 1;
        }
        self.now_ms = next;
        advance
    }

    /// 推进指定毫秒（供测试/仿真注入）。
    pub fn advance_ms(&mut self, ms: u64) {
        let next = self.now_ms.wrapping_add(ms);
        if next < self.now_ms {
            self.wraps += 1;
        }
        self.now_ms = next;
    }

    /// 距截止的剩余毫秒（已过则为 0）。
    pub fn remaining_ms(&self, deadline_ms: u64) -> u64 {
        if self.now_ms >= deadline_ms {
            0
        } else {
            deadline_ms - self.now_ms
        }
    }

    /// 是否已超时（毫秒级判据）。
    pub fn expired(&self, deadline_ms: u64) -> bool {
        self.now_ms >= deadline_ms
    }
}

/// 阶段窗口（起止毫秒对）。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StageWindow {
    /// 起始毫秒。
    pub start_ms: u64,
    /// 时限毫秒（独立上限）。
    pub limit_ms: u64,
    /// 实际耗时毫秒。
    pub used_ms: u64,
}

impl StageWindow {
    /// 开窗（记录起点）。
    pub const fn open(now_ms: u64, limit_ms: u64) -> Self {
        Self { start_ms: now_ms, limit_ms, used_ms: 0 }
    }

    /// 关窗（结算耗时 + 判定是否超时限）。
    pub fn close(&mut self, now_ms: u64) -> bool {
        self.used_ms = now_ms.saturating_sub(self.start_ms);
        self.used_ms <= self.limit_ms
    }

    /// 剩余毫秒（超时为 0）。
    pub fn left_ms(&self, now_ms: u64) -> u64 {
        let elapsed = now_ms.saturating_sub(self.start_ms);
        if elapsed >= self.limit_ms {
            0
        } else {
            self.limit_ms - elapsed
        }
    }
}

