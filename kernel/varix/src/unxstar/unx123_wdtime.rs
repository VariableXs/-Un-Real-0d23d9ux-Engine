/// 段位守卫：全部诊断码必须落在本段 [0x4b10, 0x4b1f]。
pub const fn t123_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t123Code::ALL.len() {
        let c = t123Code::ALL[i].code();
        if c < 0x4b10 || c > 0x4b1f {
            ok = false;
        }
        i += 1;
    }
    ok
}

