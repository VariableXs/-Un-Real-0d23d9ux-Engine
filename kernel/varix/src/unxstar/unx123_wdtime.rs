/// 段位守卫：全部诊断码落在本模块段内。
fn t123_guard_seg() -> bool {
    t123_segment_guard()
}

/// 表 msgrid 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t123_msgrid_guard() -> bool {
    let mut ok = msgrid_COUNT == 512;
    if ok {
        ok = msgrid_scan() == 0;
    }
    if ok {
        ok = msgrid_unique();
    }
    ok
}

/// 毫秒引擎（tick 换算 + 窗口关账 + 零超时红线）。
fn check_c2_ms_engine() -> bool {
    let mut t = MsTimer::new();
    let mut i = 0;
    while i < 1000 {
        t.tick();
        i += 1;
    }
    let mut ok = t.now_ms == 1000 && t.wraps == 0;
    if ok {
        let mut w = StageWindow::open(0, 2000);
        ok = w.close(1500) && w.used_ms == 1500 && w.left_ms(1000) == 1000;
    }
    if ok {
        let mut w2 = StageWindow::open(0, 1000);
        ok = !w2.close(1001) && w2.left_ms(2000) == 0;
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t123_checks() -> CheckSet {
    let mut set = CheckSet::new("T123");
    set.add(
        "t123-seg-guard",
        t123_guard_seg(),
        if t123_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t123-c1-ms-guard",
        check_t123_msgrid_guard(),
        if check_t123_msgrid_guard() { "" } else { "table msgrid guard mismatch" },
    );
    set.add(
        "t123-c2-ms-engine",
        check_c2_ms_engine(),
        if check_c2_ms_engine() { "" } else { "ms timer engine mismatch" },
    );
    set
}

