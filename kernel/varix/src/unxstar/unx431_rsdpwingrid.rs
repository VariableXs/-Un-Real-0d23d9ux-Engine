// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4380, 0x438f]。
pub const fn t431_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t431Code::ALL.len() {
        let c = t431Code::ALL[i].code();
        if c < 0x4380 || c > 0x438f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t431_guard_seg() -> bool {
    t431_segment_guard()
}

/// 大表 rsdp_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t431_grid() -> bool {
    let mut ok = rsdp_cell_COUNT == 1024;
    if ok {
        ok = rsdp_cell_get("RC0000") == Some(0) && rsdp_cell_get("RC1023") == Some(1023);
    }
    if ok {
        ok = rsdp_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t431_sum() -> bool {
    rsdp_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t431_checks() -> CheckSet {
    let mut set = CheckSet::new("T431");
    set.add(
        "t431-seg-guard",
        t431_guard_seg(),
        if t431_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t431-c1-grid",
        check_c1_t431_grid(),
        if check_c1_t431_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t431-c2-grid-sum",
        check_c2_t431_sum(),
        if check_c2_t431_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

