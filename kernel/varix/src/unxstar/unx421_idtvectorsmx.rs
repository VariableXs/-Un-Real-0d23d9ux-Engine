// --------------------------------------------------------------------------
// 诊断码（t421 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// IDT 域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t421Code {
    /// 0x4290 矩阵行重复。
    RowDup,
    /// 0x4291 矩阵断档。
    RowGap,
    /// 0x4292 行守卫破缺（逐行校验失败）。
    GuardBreak,
    /// 0x4293 矩阵累计漂移。
    SumDrift,
    /// 0x4294 索引错位。
    IndexMisaligned,
    /// 0x4295 矩阵账破缺。
    LedgerBreak,
    /// 0x4296 矩阵序断档。
    OrderBreak,
    /// 0x4297 守卫触发。
    GuardTripped,
    /// 0x4298 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4299 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x429a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x429b 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x429c 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x429d 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

