// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t421_guard_seg() -> bool {
    t421_segment_guard()
}

/// 表 idt_matrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t421_idt_matrix_guard() -> bool {
    let mut ok = idt_matrix_COUNT == 1024;
    if ok {
        ok = idt_matrix_scan() == 0;
    }
    if ok {
        ok = idt_matrix_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t421_mxsum() -> bool {
    idt_matrix_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t421_checks() -> CheckSet {
    let mut set = CheckSet::new("T421");
    set.add(
        "t421-seg-guard",
        t421_guard_seg(),
        if t421_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t421-c1-mx-guard",
        check_t421_idt_matrix_guard(),
        if check_t421_idt_matrix_guard() { "" } else { "table idt_matrix guard mismatch" },
    );
    set.add(
        "t421-c2-mx-sum",
        check_c2_t421_mxsum(),
        if check_c2_t421_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

