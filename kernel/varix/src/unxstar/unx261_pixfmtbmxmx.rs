// --------------------------------------------------------------------------
// 诊断码（t261 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 帧簿域矩阵诊断码。
/// 码值连续十六进制（0x3ab0..0x3abd），与声明序恒等；段位守卫据此验收。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t261Code {
    /// 0x3ab0 矩阵行重复。
    RowDup = 0x3ab0,
    /// 0x3ab1 矩阵断档。
    RowGap = 0x3ab1,
    /// 0x3ab2 行守卫破缺（逐行校验失败）。
    GuardBreak = 0x3ab2,
    /// 0x3ab3 矩阵累计漂移。
    SumDrift = 0x3ab3,
    /// 0x3ab4 索引错位。
    IndexMisaligned = 0x3ab4,
    /// 0x3ab5 矩阵账破缺。
    LedgerBreak = 0x3ab5,
    /// 0x3ab6 矩阵序断档。
    OrderBreak = 0x3ab6,
    /// 0x3ab7 守卫触发。
    GuardTripped = 0x3ab7,
    /// 0x3ab8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x3ab8,
    /// 0x3ab9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x3ab9,
    /// 0x3aba 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x3aba,
    /// 0x3abb 条目重复（同键双写）。
    DuplicateEntry = 0x3abb,
    /// 0x3abc 次序违例（依赖序/时序破缺）。
    OrderViolated = 0x3abc,
    /// 0x3abd 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x3abd,
}

impl t261Code {
    /// 全量闭集（与判据原文 14 枚互斥诊断一一对应，顺序即码值升序）。
    pub const ALL: [t261Code; 14] = [
        t261Code::RowDup,
        t261Code::RowGap,
        t261Code::GuardBreak,
        t261Code::SumDrift,
        t261Code::IndexMisaligned,
        t261Code::LedgerBreak,
        t261Code::OrderBreak,
        t261Code::GuardTripped,
        t261Code::LedgerBroken,
        t261Code::SnapshotFingerprint,
        t261Code::TableBroken,
        t261Code::DuplicateEntry,
        t261Code::OrderViolated,
        t261Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值，0x3ab0..0x3abd 连续且与声明序恒等；
    /// as 直达与原 14 臂 match 逐变体码值对拍全等，零分支零 panic 路径）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：14 臂派发单点归并于 code()，名称表序与 ALL/码值连续段恒等）。
    pub const fn name(self) -> &'static str {
        T261_NAMES[(self.code() - T261_SEG_BASE) as usize]
    }

    /// 可操作修复建议（每条诊断都必须带下一步动作；查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        T261_SUGGESTIONS[(self.code() - T261_SEG_BASE) as usize]
    }
}

