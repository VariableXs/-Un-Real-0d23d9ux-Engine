//! unxt261_pixfmtbmxmx —— 帧簿域深编矩阵（pix_matrixb × 1024 逐行守卫）。
//! 判据原文（CoRun Unxreal 主册 UNX-A1-B09）：UNX-F0261 · 帧簿双头显
//! · 组件：pix_matrixb 1024 行守卫矩阵（match 全枚举查找 + 逐行守卫扫描 + 键唯一）
//! · 深化口径：逐行守卫矩阵与主表同源对拍
//! 纯功能线：no_std + alloc，无 unwrap/expect/panic，u64 算术，
//! 逐条定制数据结构/状态机/错误路径，零模板复述，零死代码。
//!
//! 查表化不变量：第 i 行键恰为 "PM" + i 的 4 位零填充十进制、值恒等 i，
//! 故键序号 == 行序号 == 值；原 1024 键全枚举 match 查找可等价替换为
//! 键序号解析直达路径。等价性依据：解析成功 ⇔ 键 ∈ 1024 键空间 ⇔
//! 原 match 收录该键，两路对同一键的返回值逐项恒等；失败路径
//! （长度/前缀/非数字/越界）与原未收录分支同样恒等返回 None。
//! 查找/守卫/求和/唯一性共用同一条解析口径，无重复判定逻辑。
//! 数据排版：1024 项由每行一项压缩为每行 8 项以控文件长度，键值逐字节不变。

