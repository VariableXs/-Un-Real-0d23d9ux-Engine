/// 段位守卫：全部诊断码必须落在本段 [0x3ab0, 0x3abf]。
pub const fn t261_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t261Code::ALL.len() {
        let c = t261Code::ALL[i].code();
        if c < 0x3ab0 || c > 0x3abf {
            ok = false;
        }
        i += 1;
    }
    ok
}

