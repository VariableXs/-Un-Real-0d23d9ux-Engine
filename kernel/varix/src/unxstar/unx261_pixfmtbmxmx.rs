/// 键序号解析："PM" + 4 位零填充十进制 → 行序号（全模块唯一解析口径，
/// 查找/守卫共用，不设第二套判定）。失败路径（长度≠6 / 前缀≠"PM" /
/// 含非数字 / 序号 ≥1024）一律 None，与原全枚举 match 未收录分支恒等；
/// 4 位数字上界 9999 < usize 上界，无溢出路径。
fn pix_matrixb_key_index(key: &str) -> Option<usize> {
    let b = key.as_bytes();
    if b.len() != 6 || b[0] != b'P' || b[1] != b'M' {
        return None;
    }
    let mut n = 0usize;
    let mut i = 2usize;
    while i < 6 {
        let d = b[i];
        if d < b'0' || d > b'9' {
            return None;
        }
        n = n * 10 + (d - b'0') as usize;
        i += 1;
    }
    if n < pix_matrixb_COUNT {
        Some(n)
    } else {
        None
    }
}

/// O(1) 语义查找：键序号直读表行值。
/// 行为保持：与原 1024 键全枚举查找恒等——收录键返回表值，其余 None；
/// `.get` 直达第 i 行（解析已保证 i < 1024，越界不可达），无 panic 路径。
pub fn pix_matrixb_get(key: &str) -> Option<u64> {
    // 显式 let 绑定查找结果：先解析序号，再经 .get 限幅取表行值；
    // 解析已保证 i < 1024（表定长），越界不可达，无 panic 路径。
    let hit = pix_matrixb_key_index(key).and_then(|i| {
        let row = pix_matrixb.get(i);
        row.map(|entry| entry.1)
    });
    hit
}

/// 逐行守卫扫描（返回违例行数；0 = 全绿，守卫判据出口）。
/// 行守卫判据：行键可解析出序号 idx，且 idx == 行序号（键位对拍无错位）、
/// 行值 == 行序号（值对拍无漂移）；任一破缺该行计 1 次违例。
/// 等价性依据：冻结表第 i 行键解析必得 idx == i，故本判据与原
/// 「键序号 == 值」逐行守卫在同一表数据上违例行数逐项恒等。
pub fn pix_matrixb_scan() -> usize {
    let mut bad = 0usize;
    let mut i = 0usize;
    while i < pix_matrixb_COUNT {
        let (k, v) = pix_matrixb[i];
        // 行守卫：键可解析且键位/值双对拍通过，否则该行计违例。
        let ok = match pix_matrixb_key_index(k) {
            Some(idx) => idx == i && v == i as u64,
            None => false,
        };
        if !ok {
            bad += 1;
        }
        i += 1;
    }
    bad
}

/// 累计求和（守恒对账用：与判据 sum == 523776 配对）。
/// 1024 项值恰为 0..1023 全集，u64 累计无溢出路径，wrapping_add
/// 与逐项普通加法在此数据域上返回值恒等。
pub fn pix_matrixb_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < pix_matrixb_COUNT {
        s = s.wrapping_add(pix_matrixb[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键即破缺）。
/// 双层全对扫描 O(n²)（n=1024 冻结规模，无动态分配）；键由解析口径
/// 闭集生成理论必唯一，此处为运行期对拍复核，供判据与门使用。
pub fn pix_matrixb_unique() -> bool {
    let mut i = 0usize;
    while i < pix_matrixb_COUNT {
        let mut j = i + 1;
        while j < pix_matrixb_COUNT {
            if pix_matrixb[i].0 == pix_matrixb[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

