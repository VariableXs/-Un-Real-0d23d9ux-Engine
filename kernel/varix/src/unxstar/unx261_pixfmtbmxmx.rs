// --------------------------------------------------------------------------
// 诊断码（t261 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 帧簿域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t261Code {
    /// 0x3ab0 矩阵行重复。
    RowDup,
    /// 0x3ab1 矩阵断档。
    RowGap,
    /// 0x3ab2 行守卫破缺（逐行校验失败）。
    GuardBreak,
    /// 0x3ab3 矩阵累计漂移。
    SumDrift,
    /// 0x3ab4 索引错位。
    IndexMisaligned,
    /// 0x3ab5 矩阵账破缺。
    LedgerBreak,
    /// 0x3ab6 矩阵序断档。
    OrderBreak,
    /// 0x3ab7 守卫触发。
    GuardTripped,
    /// 0x3ab8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x3ab9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x3aba 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x3abb 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x3abc 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x3abd 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

