// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t261_guard_seg() -> bool {
    t261_segment_guard()
}

/// 表 pix_matrixb 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t261_pix_matrixb_guard() -> bool {
    let mut ok = pix_matrixb_COUNT == 1024;
    if ok {
        ok = pix_matrixb_scan() == 0;
    }
    if ok {
        ok = pix_matrixb_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t261_mxsum() -> bool {
    pix_matrixb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t261_checks() -> CheckSet {
    let mut set = CheckSet::new("T261");
    set.add(
        "t261-seg-guard",
        t261_guard_seg(),
        if t261_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t261-c1-mx-guard",
        check_t261_pix_matrixb_guard(),
        if check_t261_pix_matrixb_guard() { "" } else { "table pix_matrixb guard mismatch" },
    );
    set.add(
        "t261-c2-mx-sum",
        check_c2_t261_mxsum(),
        if check_c2_t261_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

