// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x3ab0, 0x3abf]；任一码越段即判红。
/// 码值与段基址同源（0x3ab0..0x3abd 连续），理论恒绿，此处为防串段复核。
pub const fn t261_segment_guard() -> bool {
    let mut i = 0usize;
    while i < t261Code::ALL.len() {
        let c = t261Code::ALL[i].code();
        if c < 0x3ab0 || c > 0x3abf {
            return false;
        }
        i += 1;
    }
    true
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 表 pix_matrixb 逐行守卫全绿（行数/守卫/唯一性三判据与门）。
fn check_t261_pix_matrixb_guard() -> bool {
    // 判据一（失败路径）：行数必须恰为 1024——矩阵规模冻结，缺行/冗行即破缺。
    if pix_matrixb_COUNT != 1024 {
        return false;
    }
    // 判据二（失败路径）：逐行守卫扫描必须零违例——任一行键值对拍失败即判红。
    if pix_matrixb_scan() != 0 {
        return false;
    }
    // 判据三（失败路径）：键唯一——同键双写即条目重复破缺。
    pix_matrixb_unique()
}

/// 矩阵累计守恒（Rust 记法 1..1024 之和 = 523776）。
fn check_c2_t261_mxsum() -> bool {
    pix_matrixb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门；三项检查与诊断段一一对应）。
pub fn run_t261_checks() -> CheckSet {
    let mut set = CheckSet::new("T261");
    let seg_ok = t261_segment_guard();
    set.add(
        "t261-seg-guard",
        seg_ok,
        if seg_ok { "" } else { "diagnostic code outside segment" },
    );
    let mx_guard_ok = check_t261_pix_matrixb_guard();
    set.add(
        "t261-c1-mx-guard",
        mx_guard_ok,
        if mx_guard_ok { "" } else { "table pix_matrixb guard mismatch" },
    );
    let mx_sum_ok = check_c2_t261_mxsum();
    set.add(
        "t261-c2-mx-sum",
        mx_sum_ok,
        if mx_sum_ok { "" } else { "matrix sum mismatch" },
    );
    set
}

