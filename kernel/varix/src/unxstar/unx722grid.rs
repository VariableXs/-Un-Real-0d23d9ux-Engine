/// 段位守卫：全部诊断码落在本模块段内。
fn t722_guard_seg() -> bool {
    t722_segment_guard()
}

/// 大表 unx722grid 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t722_grid() -> bool {
    let mut ok = unx722grid_COUNT == 1024;
    if ok {
        ok = unx722grid_get("7220000") == Some(0) && unx722grid_get("7221023") == Some(1023);
    }
    if ok {
        ok = unx722grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t722_sum() -> bool {
    unx722grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t722_checks() -> CheckSet {
    let mut set = CheckSet::new("T722");
    set.add(
        "t722-seg-guard",
        t722_guard_seg(),
        if t722_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t722-c1-grid",
        check_c1_t722_grid(),
        if check_c1_t722_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t722-c2-grid-sum",
        check_c2_t722_sum(),
        if check_c2_t722_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

