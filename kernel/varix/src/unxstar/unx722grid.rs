/// 段位守卫：全部诊断码必须落在本段 [0x50c0, 0x50cf]。
pub const fn t722_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t722Code::ALL.len() {
        let c = t722Code::ALL[i].code();
        if c < 0x50c0 || c > 0x50cf {
            ok = false;
        }
        i += 1;
    }
    ok
}

