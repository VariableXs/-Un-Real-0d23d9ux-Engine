/// 段位守卫：全部诊断码落在本模块段内。
fn u3301_guard_seg() -> bool {
    u3301_segment_guard()
}

/// UNX-F3301 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u3301_grid_count() -> bool {
    let mut ok = u3301grid_COUNT == 1024;
    if ok { ok = u3301grid_get("RD0000") == Some(0) && u3301grid_get("CPU1023") == Some(10); }
    if ok { ok = u3301grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3301 grid 累计守恒（理论值 49061）。
fn check_u3301_grid_sum() -> bool {
    u3301grid_sum() == 49061
}

/// UNX-F3301 grid 逐行守卫与唯一性全绿。
fn check_u3301_grid_guard() -> bool {
    u3301grid_scan() == 0 && u3301grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3301_checks() -> CheckSet {
    let mut set = CheckSet::new("U3301");
    set.add(
        "u3301-seg-guard",
        u3301_guard_seg(),
        if u3301_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3301-grid-count",
        check_u3301_grid_count(),
        if check_u3301_grid_count() { "" } else { "UNX-F3301 grid count mismatch" },
    );
    set.add(
        "u3301-grid-sum",
        check_u3301_grid_sum(),
        if check_u3301_grid_sum() { "" } else { "UNX-F3301 grid sum mismatch" },
    );
    set.add(
        "u3301-grid-guard",
        check_u3301_grid_guard(),
        if check_u3301_grid_guard() { "" } else { "UNX-F3301 grid guard mismatch" },
    );
    set
}

