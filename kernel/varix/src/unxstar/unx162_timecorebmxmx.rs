// --------------------------------------------------------------------------
// 诊断码（t162 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 时间域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t162Code {
    /// 0x37b0 矩阵行重复。
    RowDup,
    /// 0x37b1 矩阵断档。
    RowGap,
    /// 0x37b2 行守卫破缺（逐行校验失败）。
    GuardBreak,
    /// 0x37b3 矩阵累计漂移。
    SumDrift,
    /// 0x37b4 索引错位。
    IndexMisaligned,
    /// 0x37b5 矩阵账破缺。
    LedgerBreak,
    /// 0x37b6 矩阵序断档。
    OrderBreak,
    /// 0x37b7 守卫触发。
    GuardTripped,
    /// 0x37b8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x37b9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x37ba 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x37bb 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x37bc 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x37bd 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

