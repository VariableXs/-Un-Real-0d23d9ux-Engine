// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t162_guard_seg() -> bool {
    t162_segment_guard()
}

/// 表 time_matrixb 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t162_time_matrixb_guard() -> bool {
    let mut ok = time_matrixb_COUNT == 512;
    if ok {
        ok = time_matrixb_scan() == 0;
    }
    if ok {
        ok = time_matrixb_unique();
    }
    ok
}

/// 矩阵累计守恒（1..512 = 130816）。
fn check_c2_t162_mxsum() -> bool {
    time_matrixb_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t162_checks() -> CheckSet {
    let mut set = CheckSet::new("T162");
    set.add(
        "t162-seg-guard",
        t162_guard_seg(),
        if t162_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t162-c1-mx-guard",
        check_t162_time_matrixb_guard(),
        if check_t162_time_matrixb_guard() { "" } else { "table time_matrixb guard mismatch" },
    );
    set.add(
        "t162-c2-mx-sum",
        check_c2_t162_mxsum(),
        if check_c2_t162_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

