/// 段位守卫：全部诊断码必须落在本段 [0xa6a0, 0xa6af]。
pub const fn u2561_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2561Code::ALL.len() {
        let c = u2561Code::ALL[i].code();
        if c < 0xa6a0 || c > 0xa6af {
            ok = false;
        }
        i += 1;
    }
    ok
}

