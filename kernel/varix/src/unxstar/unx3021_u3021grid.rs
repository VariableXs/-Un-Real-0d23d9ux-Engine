/// 段位守卫：全部诊断码必须落在本段 [0xe2e0, 0xe2ef]。
pub const fn u3021_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u3021Code::ALL.len() {
        let c = u3021Code::ALL[i].code();
        if c < 0xe2e0 || c > 0xe2ef {
            ok = false;
        }
        i += 1;
    }
    ok
}

