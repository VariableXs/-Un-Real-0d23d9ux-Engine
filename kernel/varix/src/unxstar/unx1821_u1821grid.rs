pub const U1821_SEG_BASE: u16 = 0x5dc0;

// --------------------------------------------------------------------------

// 诊断码（U1821_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U1821_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1821Code {
    /// 0x5dc0 单元格重复（布局越界 同键双占）。
    CellDup = 0x5dc0,
    /// 0x5dc1 单元格断档（对齐破坏 序号不连续）。
    CellGap = 0x5dc1,
    /// 0x5dc2 索引越界（约定失锚）。
    IndexOob = 0x5dc2,
    /// 0x5dc3 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5dc3,
    /// 0x5dc4 表序断档。
    OrderBreak = 0x5dc4,
    /// 0x5dc5 累计漂移（求和≠理论值）。
    SumDrift = 0x5dc5,
    /// 0x5dc6 掩码非法。
    MaskBad = 0x5dc6,
    /// 0x5dc7 守卫触发。
    GuardTripped = 0x5dc7,
    /// 0x5dc8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5dc8,
    /// 0x5dc9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5dc9,
    /// 0x5dca 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5dca,
    /// 0x5dcb 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5dcb,
}

impl u1821Code {
    /// 全量闭集。
    pub const ALL: [u1821Code; 12] = [
        u1821Code::CellDup,
        u1821Code::CellGap,
        u1821Code::IndexOob,
        u1821Code::LedgerBreak,
        u1821Code::OrderBreak,
        u1821Code::SumDrift,
        u1821Code::MaskBad,
        u1821Code::GuardTripped,
        u1821Code::LedgerBroken,
        u1821Code::SnapshotFingerprint,
        u1821Code::TableBroken,
        u1821Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U1821CODE_NAMES[(self.code() - U1821_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U1821CODE_SUGGESTIONS[(self.code() - U1821_SEG_BASE) as usize]
    }
}

