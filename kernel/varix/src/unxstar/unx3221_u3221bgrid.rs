/// 段位守卫：全部诊断码落在本模块段内。
fn u3221_guard_seg() -> bool {
    u3221_segment_guard()
}

/// UNX-F3221 bgrid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u3221_bgrid_count() -> bool {
    let mut ok = u3221bgrid_COUNT == 1024;
    if ok { ok = u3221bgrid_get("ND0000") == Some(0) && u3221bgrid_get("NX1023") == Some(41); }
    if ok { ok = u3221bgrid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3221 bgrid 累计守恒（理论值 44933）。
fn check_u3221_bgrid_sum() -> bool {
    u3221bgrid_sum() == 44933
}

/// UNX-F3221 bgrid 逐行守卫与唯一性全绿。
fn check_u3221_bgrid_guard() -> bool {
    u3221bgrid_scan() == 0 && u3221bgrid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3221_checks() -> CheckSet {
    let mut set = CheckSet::new("U3221");
    set.add(
        "u3221-seg-guard",
        u3221_guard_seg(),
        if u3221_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3221-bgrid-count",
        check_u3221_bgrid_count(),
        if check_u3221_bgrid_count() { "" } else { "UNX-F3221 bgrid count mismatch" },
    );
    set.add(
        "u3221-bgrid-sum",
        check_u3221_bgrid_sum(),
        if check_u3221_bgrid_sum() { "" } else { "UNX-F3221 bgrid sum mismatch" },
    );
    set.add(
        "u3221-bgrid-guard",
        check_u3221_bgrid_guard(),
        if check_u3221_bgrid_guard() { "" } else { "UNX-F3221 bgrid guard mismatch" },
    );
    set
}

