// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u3321_guard_seg() -> bool {
    u3321_segment_guard()
}

/// UNX-F3321 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u3321_mx_count() -> bool {
    let mut ok = u3321mx_COUNT == 512;
    if ok { ok = u3321mx_get("MTX0000") == Some(0) && u3321mx_get("CTX0511") == Some(47); }
    if ok { ok = u3321mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3321 mx 累计守恒（理论值 24448）。
fn check_u3321_mx_sum() -> bool {
    u3321mx_sum() == 24448
}

/// UNX-F3321 mx 逐行守卫与唯一性全绿。
fn check_u3321_mx_guard() -> bool {
    u3321mx_scan() == 0 && u3321mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3321_checks() -> CheckSet {
    let mut set = CheckSet::new("U3321");
    set.add(
        "u3321-seg-guard",
        u3321_guard_seg(),
        if u3321_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3321-mx-count",
        check_u3321_mx_count(),
        if check_u3321_mx_count() { "" } else { "UNX-F3321 mx count mismatch" },
    );
    set.add(
        "u3321-mx-sum",
        check_u3321_mx_sum(),
        if check_u3321_mx_sum() { "" } else { "UNX-F3321 mx sum mismatch" },
    );
    set.add(
        "u3321-mx-guard",
        check_u3321_mx_guard(),
        if check_u3321_mx_guard() { "" } else { "UNX-F3321 mx guard mismatch" },
    );
    set
}

