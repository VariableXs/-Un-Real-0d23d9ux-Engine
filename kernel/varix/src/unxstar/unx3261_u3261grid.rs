/// UNX-F3261 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u3261_grid_count() -> bool {
    let mut ok = u3261grid_COUNT == 1024;
    if ok { ok = u3261grid_get("ST0000") == Some(0) && u3261grid_get("WQ1023") == Some(10); }
    if ok { ok = u3261grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3261 grid 累计守恒（理论值 49061）。
fn check_u3261_grid_sum() -> bool {
    u3261grid_sum() == 49061
}

/// UNX-F3261 grid 逐行守卫与唯一性全绿。
fn check_u3261_grid_guard() -> bool {
    u3261grid_scan() == 0 && u3261grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3261_checks() -> CheckSet {
    let mut set = CheckSet::new("U3261");
    set.add(
        "u3261-seg-guard",
        u3261_guard_seg(),
        if u3261_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3261-grid-count",
        check_u3261_grid_count(),
        if check_u3261_grid_count() { "" } else { "UNX-F3261 grid count mismatch" },
    );
    set.add(
        "u3261-grid-sum",
        check_u3261_grid_sum(),
        if check_u3261_grid_sum() { "" } else { "UNX-F3261 grid sum mismatch" },
    );
    set.add(
        "u3261-grid-guard",
        check_u3261_grid_guard(),
        if check_u3261_grid_guard() { "" } else { "UNX-F3261 grid guard mismatch" },
    );
    set
}

