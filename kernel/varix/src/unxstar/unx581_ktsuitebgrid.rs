// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t581_guard_seg() -> bool {
    t581_segment_guard()
}

/// 大表 kt_cellb 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t581_grid() -> bool {
    let mut ok = kt_cellb_COUNT == 1024;
    if ok {
        ok = kt_cellb_get("KC0000") == Some(0) && kt_cellb_get("KC1023") == Some(1023);
    }
    if ok {
        ok = kt_cellb_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t581_sum() -> bool {
    kt_cellb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t581_checks() -> CheckSet {
    let mut set = CheckSet::new("T581");
    set.add(
        "t581-seg-guard",
        t581_guard_seg(),
        if t581_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t581-c1-grid",
        check_c1_t581_grid(),
        if check_c1_t581_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t581-c2-grid-sum",
        check_c2_t581_sum(),
        if check_c2_t581_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

