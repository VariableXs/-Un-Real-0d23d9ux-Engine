/// 段位守卫：全部诊断码必须落在本段 [0x47a0, 0x47af]。
pub const fn t581_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t581Code::ALL.len() {
        let c = t581Code::ALL[i].code();
        if c < 0x47a0 || c > 0x47af {
            ok = false;
        }
        i += 1;
    }
    ok
}

