// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x3b80, 0x3b8f]。
pub const fn t281_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t281Code::ALL.len() {
        let c = t281Code::ALL[i].code();
        if c < 0x3b80 || c > 0x3b8f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t281_guard_seg() -> bool {
    t281_segment_guard()
}

/// 大表 panic_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t281_grid() -> bool {
    let mut ok = panic_cell_COUNT == 1024;
    if ok {
        ok = panic_cell_get("PC0000") == Some(0) && panic_cell_get("PC1023") == Some(1023);
    }
    if ok {
        ok = panic_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t281_sum() -> bool {
    panic_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t281_checks() -> CheckSet {
    let mut set = CheckSet::new("T281");
    set.add(
        "t281-seg-guard",
        t281_guard_seg(),
        if t281_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t281-c1-grid",
        check_c1_t281_grid(),
        if check_c1_t281_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t281-c2-grid-sum",
        check_c2_t281_sum(),
        if check_c2_t281_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

