/// 段位守卫：全部诊断码必须落在本段 [0xa380, 0xa38f]。
pub const fn u2481_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2481Code::ALL.len() {
        let c = u2481Code::ALL[i].code();
        if c < 0xa380 || c > 0xa38f {
            ok = false;
        }
        i += 1;
    }
    ok
}

