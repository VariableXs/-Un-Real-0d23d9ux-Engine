// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0xa9b0, 0xa9bf]。
pub const fn u2641_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2641Code::ALL.len() {
        let c = u2641Code::ALL[i].code();
        if c < 0xa9b0 || c > 0xa9bf {
            ok = false;
        }
        i += 1;
    }
    ok
}

