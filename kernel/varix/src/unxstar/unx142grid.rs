// --------------------------------------------------------------------------
/// GPT/ESP 镜像域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t142Code {
    /// 0x4d80 格重复（同键双占）。
    CellDup,
    /// 0x4d81 格断档（序号不连续）。
    CellGap,
    /// 0x4d82 索引越界（≥1024）。
    IndexOob,
    /// 0x4d83 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x4d84 表序断档。
    OrderBreak,
    /// 0x4d85 累计漂移（求和≠523776）。
    SumDrift,
    /// 0x4d86 掩码非法。
    MaskBad,
    /// 0x4d87 守卫触发。
    GuardTripped,
    /// 0x4d88 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4d89 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x4d8a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x4d8b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x4d8c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x4d8d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x4d8e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

