// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4d80, 0x4d8f]。
pub const fn t142_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t142Code::ALL.len() {
        let c = t142Code::ALL[i].code();
        if c < 0x4d80 || c > 0x4d8f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t142_guard_seg() -> bool {
    t142_segment_guard()
}

/// 大表 imggrid 1024 行齐备 + 边界锚点。
fn check_c1_t142_grid() -> bool {
    let mut ok = imggrid_COUNT == 1024;
    if ok {
        ok = imggrid_get("IG0000") == Some(0) && imggrid_get("IG1023") == Some(1023);
    }
    if ok {
        ok = imggrid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t142_sum() -> bool {
    imggrid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t142_checks() -> CheckSet {
    let mut set = CheckSet::new("T142");
    set.add(
        "t142-seg-guard",
        t142_guard_seg(),
        if t142_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t142-c1-grid",
        check_c1_t142_grid(),
        if check_c1_t142_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t142-c2-grid-sum",
        check_c2_t142_sum(),
        if check_c2_t142_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

