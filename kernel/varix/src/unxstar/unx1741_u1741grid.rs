// --------------------------------------------------------------------------

// 诊断码（U1741_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U1741_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1741Code {
    /// 0x5ac0 单元格重复（非法转换 同键双占）。
    CellDup = 0x5ac0,
    /// 0x5ac1 单元格断档（账实漂移 序号不连续）。
    CellGap = 0x5ac1,
    /// 0x5ac2 索引越界（唤醒丢失）。
    IndexOob = 0x5ac2,
    /// 0x5ac3 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5ac3,
    /// 0x5ac4 表序断档。
    OrderBreak = 0x5ac4,
    /// 0x5ac5 累计漂移（求和≠理论值）。
    SumDrift = 0x5ac5,
    /// 0x5ac6 掩码非法。
    MaskBad = 0x5ac6,
    /// 0x5ac7 守卫触发。
    GuardTripped = 0x5ac7,
    /// 0x5ac8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5ac8,
    /// 0x5ac9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5ac9,
    /// 0x5aca 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5aca,
    /// 0x5acb 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5acb,
}

impl u1741Code {
    /// 全量闭集。
    pub const ALL: [u1741Code; 12] = [
        u1741Code::CellDup,
        u1741Code::CellGap,
        u1741Code::IndexOob,
        u1741Code::LedgerBreak,
        u1741Code::OrderBreak,
        u1741Code::SumDrift,
        u1741Code::MaskBad,
        u1741Code::GuardTripped,
        u1741Code::LedgerBroken,
        u1741Code::SnapshotFingerprint,
        u1741Code::TableBroken,
        u1741Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U1741CODE_NAMES[(self.code() - U1741_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U1741CODE_SUGGESTIONS[(self.code() - U1741_SEG_BASE) as usize]
    }
}

