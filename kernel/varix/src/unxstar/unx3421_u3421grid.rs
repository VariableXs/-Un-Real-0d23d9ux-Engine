/// 累计求和（守恒对账用）。
pub fn u3421grid_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < u3421grid_COUNT {
        s = s.wrapping_add(u3421grid[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u3421grid_unique() -> bool {
    let mut i = 0usize;
    while i < u3421grid_COUNT {
        let mut j = i + 1;
        while j < u3421grid_COUNT {
            if u3421grid[i].0 == u3421grid[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

