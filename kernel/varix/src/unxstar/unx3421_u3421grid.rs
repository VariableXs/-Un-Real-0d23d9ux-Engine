// --------------------------------------------------------------------------
/// 双后端抽象 grid 面诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u3421Code {
    /// 0xe100 单元格重复（双后端 同键双占）。
    CellDup,
    /// 0xe101 单元格断档（抽象 序号不连续）。
    CellGap,
    /// 0xe102 索引越界（QEMU）。
    IndexOob,
    /// 0xe103 大表账破缺（行数≠登记值）。
    LedgerBreak,
    /// 0xe104 表序断档。
    OrderBreak,
    /// 0xe105 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0xe106 掩码非法。
    MaskBad,
    /// 0xe107 守卫触发。
    GuardTripped,
    /// 0xe108 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0xe109 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0xe10a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0xe10b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

