/// 段位守卫：全部诊断码落在本模块段内。
fn u3421_guard_seg() -> bool {
    u3421_segment_guard()
}

/// UNX-F3421 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u3421_grid_count() -> bool {
    let mut ok = u3421grid_COUNT == 1024;
    if ok { ok = u3421grid_get("BE0000") == Some(0) && u3421grid_get("ABI1023") == Some(10); }
    if ok { ok = u3421grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3421 grid 累计守恒（理论值 49061）。
fn check_u3421_grid_sum() -> bool {
    u3421grid_sum() == 49061
}

/// UNX-F3421 grid 逐行守卫与唯一性全绿。
fn check_u3421_grid_guard() -> bool {
    u3421grid_scan() == 0 && u3421grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3421_checks() -> CheckSet {
    let mut set = CheckSet::new("U3421");
    set.add(
        "u3421-seg-guard",
        u3421_guard_seg(),
        if u3421_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3421-grid-count",
        check_u3421_grid_count(),
        if check_u3421_grid_count() { "" } else { "UNX-F3421 grid count mismatch" },
    );
    set.add(
        "u3421-grid-sum",
        check_u3421_grid_sum(),
        if check_u3421_grid_sum() { "" } else { "UNX-F3421 grid sum mismatch" },
    );
    set.add(
        "u3421-grid-guard",
        check_u3421_grid_guard(),
        if check_u3421_grid_guard() { "" } else { "UNX-F3421 grid guard mismatch" },
    );
    set
}

