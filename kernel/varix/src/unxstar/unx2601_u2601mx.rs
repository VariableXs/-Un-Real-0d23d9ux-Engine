/// 段位守卫：全部诊断码落在本模块段内。
fn u2601_guard_seg() -> bool {
    u2601_segment_guard()
}

/// UNX-F2601 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u2601_mx_count() -> bool {
    let mut ok = u2601mx_COUNT == 512;
    if ok { ok = u2601mx_get("PF0000") == Some(0) && u2601mx_get("MG0511") == Some(47); }
    if ok { ok = u2601mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2601 mx 累计守恒（理论值 24448）。
fn check_u2601_mx_sum() -> bool {
    u2601mx_sum() == 24448
}

/// UNX-F2601 mx 逐行守卫与唯一性全绿。
fn check_u2601_mx_guard() -> bool {
    u2601mx_scan() == 0 && u2601mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2601_checks() -> CheckSet {
    let mut set = CheckSet::new("U2601");
    set.add(
        "u2601-seg-guard",
        u2601_guard_seg(),
        if u2601_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2601-mx-count",
        check_u2601_mx_count(),
        if check_u2601_mx_count() { "" } else { "UNX-F2601 mx count mismatch" },
    );
    set.add(
        "u2601-mx-sum",
        check_u2601_mx_sum(),
        if check_u2601_mx_sum() { "" } else { "UNX-F2601 mx sum mismatch" },
    );
    set.add(
        "u2601-mx-guard",
        check_u2601_mx_guard(),
        if check_u2601_mx_guard() { "" } else { "UNX-F2601 mx guard mismatch" },
    );
    set
}

