pub const T302_SEG_BASE: u16 = 0x3c10;

// --------------------------------------------------------------------------
// 诊断码（t302 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 槽映射诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t302Code {
    /// 0x3c10 槽位重复（同索引双占）。
    SlotDup,
    /// 0x3c11 槽位断档（索引不连续）。
    SlotGap,
    /// 0x3c12 索引越界（≥512）。
    IndexOob,
    /// 0x3c13 双射破缺（索引↔位片非一一）。
    BijectionBreak,
    /// 0x3c14 槽位账破缺。
    LedgerBreak,
    /// 0x3c15 掩码非法。
    MaskBad,
    /// 0x3c16 槽序断档。
    OrderBreak,
    /// 0x3c17 守卫触发。
    GuardTripped,
    /// 0x3c18 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x3c19 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x3c1a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x3c1b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x3c1c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x3c1d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x3c1e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

