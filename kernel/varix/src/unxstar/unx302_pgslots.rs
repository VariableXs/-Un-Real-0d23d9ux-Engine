// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t302_guard_seg() -> bool {
    t302_segment_guard()
}

/// 表 pgslots 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t302_pgslots_guard() -> bool {
    let mut ok = pgslots_COUNT == 512;
    if ok {
        ok = pgslots_scan() == 0;
    }
    if ok {
        ok = pgslots_unique();
    }
    ok
}

/// 槽位双射（首末槽 + 求和守恒）。
fn check_c2_slot_bijection() -> bool {
    let mut ok = pgslots_COUNT == 512 && pgslots_unique();
    if ok {
        ok = pgslots_get("SLOT000") == Some(0) && pgslots_get("SLOT511") == Some(511);
    }
    if ok {
        // 0..511 求和 = 130816。
        ok = pgslots_sum() == 130816;
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t302_checks() -> CheckSet {
    let mut set = CheckSet::new("T302");
    set.add(
        "t302-seg-guard",
        t302_guard_seg(),
        if t302_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t302-c1-slot-guard",
        check_t302_pgslots_guard(),
        if check_t302_pgslots_guard() { "" } else { "table pgslots guard mismatch" },
    );
    set.add(
        "t302-c2-slot-bijection",
        check_c2_slot_bijection(),
        if check_c2_slot_bijection() { "" } else { "slot bijection mismatch" },
    );
    set
}

