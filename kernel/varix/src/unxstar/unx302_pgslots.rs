/// 段位守卫：全部诊断码必须落在本段 [0x3c10, 0x3c1f]。
pub const fn t302_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t302Code::ALL.len() {
        let c = t302Code::ALL[i].code();
        if c < 0x3c10 || c > 0x3c1f {
            ok = false;
        }
        i += 1;
    }
    ok
}

