pub fn unx702grid_get(key: &'static str) -> Option<u64> {
    let mut i = 0usize;
    while i < unx702grid_COUNT {
        if unx702grid[i].0 == key {
            return Some(unx702grid[i].1);
        }
        i += 1;
    }
    None
}

/// 累计求和（用于守恒对账）。
pub fn unx702grid_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < unx702grid_COUNT {
        s = s.wrapping_add(unx702grid[i].1 as u64);
        i += 1;
    }
    s
}

