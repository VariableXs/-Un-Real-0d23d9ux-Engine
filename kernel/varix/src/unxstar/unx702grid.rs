/// 段位守卫：全部诊断码落在本模块段内。
fn t702_guard_seg() -> bool {
    t702_segment_guard()
}

/// 大表 unx702grid 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t702_grid() -> bool {
    let mut ok = unx702grid_COUNT == 1024;
    if ok {
        ok = unx702grid_get("7020000") == Some(0) && unx702grid_get("7021023") == Some(1023);
    }
    if ok {
        ok = unx702grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t702_sum() -> bool {
    unx702grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t702_checks() -> CheckSet {
    let mut set = CheckSet::new("T702");
    set.add(
        "t702-seg-guard",
        t702_guard_seg(),
        if t702_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t702-c1-grid",
        check_c1_t702_grid(),
        if check_c1_t702_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t702-c2-grid-sum",
        check_c2_t702_sum(),
        if check_c2_t702_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

