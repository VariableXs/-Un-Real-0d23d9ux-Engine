/// 段位守卫：全部诊断码必须落在本段 [0x50b0, 0x50bf]。
pub const fn t702_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t702Code::ALL.len() {
        let c = t702Code::ALL[i].code();
        if c < 0x50b0 || c > 0x50bf {
            ok = false;
        }
        i += 1;
    }
    ok
}

