/// 段位守卫：全部诊断码必须落在本段 [0x4580, 0x458f]。
pub const fn t561_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t561Code::ALL.len() {
        let c = t561Code::ALL[i].code();
        if c < 0x4580 || c > 0x458f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t561_guard_seg() -> bool {
    t561_segment_guard()
}

/// 大表 fb_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t561_grid() -> bool {
    let mut ok = fb_cell_COUNT == 1024;
    if ok {
        ok = fb_cell_get("FC0000") == Some(0) && fb_cell_get("FC1023") == Some(1023);
    }
    if ok {
        ok = fb_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t561_sum() -> bool {
    fb_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t561_checks() -> CheckSet {
    let mut set = CheckSet::new("T561");
    set.add(
        "t561-seg-guard",
        t561_guard_seg(),
        if t561_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t561-c1-grid",
        check_c1_t561_grid(),
        if check_c1_t561_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t561-c2-grid-sum",
        check_c2_t561_sum(),
        if check_c2_t561_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

