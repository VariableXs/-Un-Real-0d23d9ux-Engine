/// EBDA 扫描槽表守卫（64 槽）。
fn check_c1_ebdascan() -> bool {
    let mut ok = ebdascan_COUNT == 64 && ebdascan_scan() == 0;
    if ok {
        ok = ebdascan_unique();
    }
    ok
}

/// 表 biosscan 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t432_biosscan_guard() -> bool {
    let mut ok = biosscan_COUNT == 512;
    if ok {
        ok = biosscan_scan() == 0;
    }
    if ok {
        ok = biosscan_unique();
    }
    ok
}

/// 扫描边界槽在位（EBDA 首末 + BIOS 窗首末）。
fn check_c3_scan_edges() -> bool {
    let mut ok = ebdascan_get("SLOT000") == Some(0x9FC00);
    if ok {
        ok = ebdascan_get("SLOT063") == Some(0x9FFF0);
    }
    if ok {
        ok = biosscan_get("WIN000") == Some(0xE0000) && biosscan_get("WIN511") == Some(0xFFF00);
    }
    ok
}

/// 扫描引擎（8256 步全覆盖 + 单调 + 末步 0xFFF0）。
fn check_c4_scan_engine() -> bool {
    let mut ok = RSDP_TOTAL_STEPS == 8256;
    if ok {
        ok = rsdp_step_addr(0) == 0x9FC00 && rsdp_step_addr(63) == 0x9FFF0;
    }
    if ok {
        ok = rsdp_step_addr(64) == 0xE0000 && rsdp_step_addr(8255) == 0xFFFF0;
    }
    if ok {
        ok = rsdp_scan_monotone();
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t432_checks() -> CheckSet {
    let mut set = CheckSet::new("T432");
    set.add(
        "t432-seg-guard",
        t432_guard_seg(),
        if t432_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t432-c1-ebdascan",
        check_c1_ebdascan(),
        if check_c1_ebdascan() { "" } else { "ebda scan guard mismatch" },
    );
    set.add(
        "t432-c2-bios-scan-guard",
        check_t432_biosscan_guard(),
        if check_t432_biosscan_guard() { "" } else { "table biosscan guard mismatch" },
    );
    set.add(
        "t432-c3-scan-edges",
        check_c3_scan_edges(),
        if check_c3_scan_edges() { "" } else { "scan slot edges mismatch" },
    );
    set.add(
        "t432-c4-scan-engine",
        check_c4_scan_engine(),
        if check_c4_scan_engine() { "" } else { "scan engine coverage mismatch" },
    );
    set
}

