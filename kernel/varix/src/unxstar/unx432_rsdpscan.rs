/// 签名扫描诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t432Code {
    /// 0x4310 槽位越界（≥512）。
    SlotOob,
    /// 0x4311 扫描断档（槽序不连续）。
    ScanGap,
    /// 0x4312 签名漏检（存在未扫到）。
    SigMiss,
    /// 0x4313 校验和失败（命中项无效）。
    ChecksumFail,
    /// 0x4314 命中丢失（已命中未入账）。
    HitLost,
    /// 0x4315 扫描序断档。
    OrderBreak,
    /// 0x4316 扫描账破缺。
    LedgerBreak,
    /// 0x4317 守卫触发。
    GuardTripped,
    /// 0x4318 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4319 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x431a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x431b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x431c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x431d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x431e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

