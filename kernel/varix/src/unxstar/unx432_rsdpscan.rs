/// 累计求和（守恒对账用）。
pub fn biosscan_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < biosscan_COUNT {
        s = s.wrapping_add(biosscan[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn biosscan_unique() -> bool {
    let mut i = 0usize;
    while i < biosscan_COUNT {
        let mut j = i + 1;
        while j < biosscan_COUNT {
            if biosscan[i].0 == biosscan[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

// ---------------------------------------------------------------------------
// 双窗扫描引擎（EBDA 64 槽直扫 + BIOS 窗内 16 槽 16 字节步进）
// ---------------------------------------------------------------------------

/// BIOS 窗长（256 字节）。
pub const BIOS_WIN_LEN: u64 = 256;

/// BIOS 窗内槽数（256/16 = 16）。
pub const BIOS_WIN_SLOTS: u64 = 16;

/// 双窗扫描总步数（EBDA 64 + BIOS 512×16 = 8256，16 字节粒度全覆盖）。
pub const RSDP_TOTAL_STEPS: u64 = 64 + 512 * BIOS_WIN_SLOTS;

/// 扫描步 → 物理地址（EBDA 段直算；BIOS 段先定位窗再算窗内偏移）。
pub const fn rsdp_step_addr(step: u64) -> u64 {
    if step < 64 {
        return 0x9FC00 + step * 16;
    }
    let b = step - 64;
    let win = b / BIOS_WIN_SLOTS;
    let off = (b % BIOS_WIN_SLOTS) * 16;
    0xE0000 + win * BIOS_WIN_LEN + off
}

/// 扫描序列单调性（每步地址严格递增，覆盖双窗无回退）。
pub const fn rsdp_scan_monotone() -> bool {
    let mut i = 1u64;
    while i < RSDP_TOTAL_STEPS {
        if rsdp_step_addr(i) <= rsdp_step_addr(i - 1) {
            return false;
        }
        i += 1;
    }
    true
}

/// 扫描边界守卫（首步 EBDA 头 + 末步 BIOS ROM 末 16 字节，均不越界）。
pub const fn rsdp_scan_bounds_ok() -> bool {
    rsdp_step_addr(0) == 0x9FC00 && rsdp_step_addr(RSDP_TOTAL_STEPS - 1) == 0xFFFF0
}

// ---------------------------------------------------------------------------
// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4310, 0x431f]。
pub const fn t432_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t432Code::ALL.len() {
        let c = t432Code::ALL[i].code();
        if c < 0x4310 || c > 0x431f {
            ok = false;
        }
        i += 1;
    }
    ok
}

