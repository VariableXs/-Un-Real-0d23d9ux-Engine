/// 段位守卫：全部诊断码落在本模块段内。
fn tb02_guard_seg() -> bool {
    tb02_segment_guard()
}

/// 表 cmdpos 逐行守卫全绿（行数/守卫/唯一性）。
fn check_tb02_cmdpos_guard() -> bool {
    let mut ok = cmdpos_COUNT == 512;
    if ok {
        ok = cmdpos_scan() == 0;
    }
    if ok {
        ok = cmdpos_unique();
    }
    ok
}

/// 位置求和守恒（0..511 = 130816）。
fn check_c2_pos_sum() -> bool {
    let mut ok = cmdpos_sum() == 130816;
    if ok {
        ok = cmdpos_get("POS000") == Some(0) && cmdpos_get("POS255") == Some(255) && cmdpos_get("POS256") == Some(256);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_tb02_checks() -> CheckSet {
    let mut set = CheckSet::new("TB02");
    set.add(
        "tb02-seg-guard",
        tb02_guard_seg(),
        if tb02_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "tb02-c1-pos-guard",
        check_tb02_cmdpos_guard(),
        if check_tb02_cmdpos_guard() { "" } else { "table cmdpos guard mismatch" },
    );
    set.add(
        "tb02-c2-pos-sum",
        check_c2_pos_sum(),
        if check_c2_pos_sum() { "" } else { "guard position sum mismatch" },
    );
    set
}

