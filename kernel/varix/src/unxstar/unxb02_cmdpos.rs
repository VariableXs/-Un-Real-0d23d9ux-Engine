/// 段位守卫：全部诊断码必须落在本段 [0x4a10, 0x4a1f]。
pub const fn tb02_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < tb02Code::ALL.len() {
        let c = tb02Code::ALL[i].code();
        if c < 0x4a10 || c > 0x4a1f {
            ok = false;
        }
        i += 1;
    }
    ok
}

