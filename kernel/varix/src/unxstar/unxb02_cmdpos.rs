// --------------------------------------------------------------------------
// 诊断码（tb02 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 长度守卫诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum tb02Code {
    /// 0x4a10 位置越界（≥512）。
    PosOob,
    /// 0x4a11 边界类非法。
    ClassBad,
    /// 0x4a12 位置重复。
    DupPos,
    /// 0x4a13 边界漏检（256 边界未标）。
    BoundaryMiss,
    /// 0x4a14 守卫账破缺。
    LedgerBreak,
    /// 0x4a15 位序断档。
    OrderBreak,
    /// 0x4a16 报告陈旧。
    ReportStale,
    /// 0x4a17 守卫触发。
    GuardTripped,
    /// 0x4a18 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4a19 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x4a1a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x4a1b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x4a1c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x4a1d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x4a1e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

