/// 段位守卫：全部诊断码必须落在本段 [0xa800, 0xa80f]。
pub const fn u2601_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2601Code::ALL.len() {
        let c = u2601Code::ALL[i].code();
        if c < 0xa800 || c > 0xa80f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u2601_guard_seg() -> bool {
    u2601_segment_guard()
}

/// UNX-F2601 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u2601_grid_count() -> bool {
    let mut ok = u2601grid_COUNT == 1024;
    if ok { ok = u2601grid_get("PF0000") == Some(0) && u2601grid_get("GS1023") == Some(10); }
    if ok { ok = u2601grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2601 grid 累计守恒（理论值 49061）。
fn check_u2601_grid_sum() -> bool {
    u2601grid_sum() == 49061
}

/// UNX-F2601 grid 逐行守卫与唯一性全绿。
fn check_u2601_grid_guard() -> bool {
    u2601grid_scan() == 0 && u2601grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2601_checks() -> CheckSet {
    let mut set = CheckSet::new("U2601");
    set.add(
        "u2601-seg-guard",
        u2601_guard_seg(),
        if u2601_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2601-grid-count",
        check_u2601_grid_count(),
        if check_u2601_grid_count() { "" } else { "UNX-F2601 grid count mismatch" },
    );
    set.add(
        "u2601-grid-sum",
        check_u2601_grid_sum(),
        if check_u2601_grid_sum() { "" } else { "UNX-F2601 grid sum mismatch" },
    );
    set.add(
        "u2601-grid-guard",
        check_u2601_grid_guard(),
        if check_u2601_grid_guard() { "" } else { "UNX-F2601 grid guard mismatch" },
    );
    set
}

