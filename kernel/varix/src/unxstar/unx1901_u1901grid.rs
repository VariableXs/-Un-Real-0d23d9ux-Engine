/// 段位守卫：全部诊断码必须落在本段 [0x60c0, 0x60cf]。
pub const fn u1901_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1901Code::ALL.len() {
        let c = u1901Code::ALL[i].code();
        if c < 0x60c0 || c > 0x60cf {
            ok = false;
        }
        i += 1;
    }
    ok
}

