/// UNX-F3441 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u3441_mx_count() -> bool {
    let mut ok = u3441mx_COUNT == 512;
    if ok { ok = u3441mx_get("EX0000") == Some(0) && u3441mx_get("STAGE0511") == Some(47); }
    if ok { ok = u3441mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3441 mx 累计守恒（理论值 24448）。
fn check_u3441_mx_sum() -> bool {
    u3441mx_sum() == 24448
}

/// UNX-F3441 mx 逐行守卫与唯一性全绿。
fn check_u3441_mx_guard() -> bool {
    u3441mx_scan() == 0 && u3441mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3441_checks() -> CheckSet {
    let mut set = CheckSet::new("U3441");
    set.add(
        "u3441-seg-guard",
        u3441_guard_seg(),
        if u3441_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3441-mx-count",
        check_u3441_mx_count(),
        if check_u3441_mx_count() { "" } else { "UNX-F3441 mx count mismatch" },
    );
    set.add(
        "u3441-mx-sum",
        check_u3441_mx_sum(),
        if check_u3441_mx_sum() { "" } else { "UNX-F3441 mx sum mismatch" },
    );
    set.add(
        "u3441-mx-guard",
        check_u3441_mx_guard(),
        if check_u3441_mx_guard() { "" } else { "UNX-F3441 mx guard mismatch" },
    );
    set
}

