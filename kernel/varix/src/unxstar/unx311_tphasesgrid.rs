// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x3d80, 0x3d8f]。
pub const fn t311_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t311Code::ALL.len() {
        let c = t311Code::ALL[i].code();
        if c < 0x3d80 || c > 0x3d8f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t311_guard_seg() -> bool {
    t311_segment_guard()
}

/// 大表 tramp_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t311_grid() -> bool {
    let mut ok = tramp_cell_COUNT == 1024;
    if ok {
        ok = tramp_cell_get("TR0000") == Some(0) && tramp_cell_get("TR1023") == Some(1023);
    }
    if ok {
        ok = tramp_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t311_sum() -> bool {
    tramp_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t311_checks() -> CheckSet {
    let mut set = CheckSet::new("T311");
    set.add(
        "t311-seg-guard",
        t311_guard_seg(),
        if t311_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t311-c1-grid",
        check_c1_t311_grid(),
        if check_c1_t311_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t311-c2-grid-sum",
        check_c2_t311_sum(),
        if check_c2_t311_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

