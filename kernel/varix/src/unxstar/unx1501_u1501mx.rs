/// 段位守卫：全部诊断码必须落在本段 [0x5290, 0x529f]。
pub const fn u1501_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1501Code::ALL.len() {
        let c = u1501Code::ALL[i].code();
        if c < 0x5290 || c > 0x529f {
            ok = false;
        }
        i += 1;
    }
    ok
}

