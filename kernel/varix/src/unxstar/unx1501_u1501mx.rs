/// UNX-F1501 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u1501_mx_count() -> bool {
    let mut ok = u1501mx_COUNT == 512;
    if ok { ok = u1501mx_get("SC0000") == Some(0) && u1501mx_get("ZL0511") == Some(47); }
    if ok { ok = u1501mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F1501 mx 累计守恒（理论值 24448）。
fn check_u1501_mx_sum() -> bool {
    u1501mx_sum() == 24448
}

/// UNX-F1501 mx 逐行守卫与唯一性全绿。
fn check_u1501_mx_guard() -> bool {
    u1501mx_scan() == 0 && u1501mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u1501_checks() -> CheckSet {
    let mut set = CheckSet::new("U1501");
    set.add(
        "u1501-seg-guard",
        u1501_guard_seg(),
        if u1501_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u1501-mx-count",
        check_u1501_mx_count(),
        if check_u1501_mx_count() { "" } else { "UNX-F1501 mx count mismatch" },
    );
    set.add(
        "u1501-mx-sum",
        check_u1501_mx_sum(),
        if check_u1501_mx_sum() { "" } else { "UNX-F1501 mx sum mismatch" },
    );
    set.add(
        "u1501-mx-guard",
        check_u1501_mx_guard(),
        if check_u1501_mx_guard() { "" } else { "UNX-F1501 mx guard mismatch" },
    );
    set
}

