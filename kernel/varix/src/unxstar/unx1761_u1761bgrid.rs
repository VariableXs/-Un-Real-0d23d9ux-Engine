/// U1761_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1761Code {
    /// 0x5ba0 单元格重复（职责越界 同键双占）。
    CellDup = 0x5ba0,
    /// 0x5ba1 单元格断档（汇聚漏登 序号不连续）。
    CellGap = 0x5ba1,
    /// 0x5ba2 索引越界（层间穿透）。
    IndexOob = 0x5ba2,
    /// 0x5ba3 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5ba3,
    /// 0x5ba4 表序断档。
    OrderBreak = 0x5ba4,
    /// 0x5ba5 累计漂移（求和≠理论值）。
    SumDrift = 0x5ba5,
    /// 0x5ba6 掩码非法。
    MaskBad = 0x5ba6,
    /// 0x5ba7 守卫触发。
    GuardTripped = 0x5ba7,
    /// 0x5ba8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5ba8,
    /// 0x5ba9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5ba9,
    /// 0x5baa 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5baa,
    /// 0x5bab 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5bab,
}

