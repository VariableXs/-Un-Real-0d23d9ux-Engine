/// UNX-F3501 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u3501_grid_count() -> bool {
    let mut ok = u3501grid_COUNT == 1024;
    if ok { ok = u3501grid_get("TP0000") == Some(0) && u3501grid_get("SW1023") == Some(10); }
    if ok { ok = u3501grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3501 grid 累计守恒（理论值 49061）。
fn check_u3501_grid_sum() -> bool {
    u3501grid_sum() == 49061
}

/// UNX-F3501 grid 逐行守卫与唯一性全绿。
fn check_u3501_grid_guard() -> bool {
    u3501grid_scan() == 0 && u3501grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3501_checks() -> CheckSet {
    let mut set = CheckSet::new("U3501");
    set.add(
        "u3501-seg-guard",
        u3501_guard_seg(),
        if u3501_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3501-grid-count",
        check_u3501_grid_count(),
        if check_u3501_grid_count() { "" } else { "UNX-F3501 grid count mismatch" },
    );
    set.add(
        "u3501-grid-sum",
        check_u3501_grid_sum(),
        if check_u3501_grid_sum() { "" } else { "UNX-F3501 grid sum mismatch" },
    );
    set.add(
        "u3501-grid-guard",
        check_u3501_grid_guard(),
        if check_u3501_grid_guard() { "" } else { "UNX-F3501 grid guard mismatch" },
    );
    set
}

