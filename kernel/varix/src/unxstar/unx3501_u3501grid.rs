/// 段位守卫：全部诊断码必须落在本段 [0xe140, 0xe14f]。
pub const fn u3501_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u3501Code::ALL.len() {
        let c = u3501Code::ALL[i].code();
        if c < 0xe140 || c > 0xe14f {
            ok = false;
        }
        i += 1;
    }
    ok
}

