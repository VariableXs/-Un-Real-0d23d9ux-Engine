pub const TA02_VERSION: &str = "ta02-pmregs-v1";

/// 诊断段基址。
pub const TA02_SEG_BASE: u16 = 0x4910;

// --------------------------------------------------------------------------
// 诊断码（ta02 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// PM1 位域诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ta02Code {
    /// 0x4910 寄存器非法（五块之外）。
    RegBad,
    /// 0x4911 位号越界（≥32/块）。
    BitOob,
    /// 0x4912 位语义重复。
    BitSemDup,
    /// 0x4913 写保护位违例。
    WriteProtectBad,
    /// 0x4914 S4 睡眠类型非法。
    S4Bad,
    /// 0x4915 S5 睡眠类型非法。
    S5Bad,
    /// 0x4916 复位值非法。
    ResetBad,
    /// 0x4917 守卫触发。
    GuardTripped,
    /// 0x4918 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4919 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x491a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x491b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x491c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x491d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x491e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

