/// 段位守卫：全部诊断码必须落在本段 [0x4910, 0x491f]。
pub const fn ta02_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < ta02Code::ALL.len() {
        let c = ta02Code::ALL[i].code();
        if c < 0x4910 || c > 0x491f {
            ok = false;
        }
        i += 1;
    }
    ok
}

