// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn ta02_guard_seg() -> bool {
    ta02_segment_guard()
}

/// 表 pmregs 逐行守卫全绿（行数/守卫/唯一性）。
fn check_ta02_pmregs_guard() -> bool {
    let mut ok = pmregs_COUNT == 256;
    if ok {
        ok = pmregs_scan() == 0;
    }
    if ok {
        ok = pmregs_unique();
    }
    ok
}

/// 位号求和守恒（0..255 = 32640）。
fn check_c2_bit_sum() -> bool {
    let mut ok = pmregs_sum() == 32640;
    if ok {
        ok = pmregs_get("BIT_0_00") == Some(0) && pmregs_get("BIT_7_31") == Some(255);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_ta02_checks() -> CheckSet {
    let mut set = CheckSet::new("TA02");
    set.add(
        "ta02-seg-guard",
        ta02_guard_seg(),
        if ta02_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "ta02-c1-bit-guard",
        check_ta02_pmregs_guard(),
        if check_ta02_pmregs_guard() { "" } else { "table pmregs guard mismatch" },
    );
    set.add(
        "ta02-c2-bit-sum",
        check_c2_bit_sum(),
        if check_c2_bit_sum() { "" } else { "pm bit table sum mismatch" },
    );
    set
}

