/// U1801 u1801grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u1801grid_count() -> bool {
    let mut ok = u1801grid_COUNT == 1024;
    if ok { ok = u1801grid_get("ZW0000") == Some(0) && u1801grid_get("QR1023") == Some(10); }
    if ok { ok = u1801grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// U1801 u1801grid 累计守恒（理论值 49061）。
fn check_u1801grid_sum() -> bool {
    u1801grid_sum() == 49061
}

/// U1801 u1801grid 逐行守卫与唯一性全绿。
fn check_u1801grid_guard() -> bool {
    u1801grid_scan() == 0 && u1801grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u1801_checks() -> CheckSet {
    let mut set = CheckSet::new("U1801");
    set.add(
        "u1801-seg-guard",
        u1801_guard_seg(),
        if u1801_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u1801-grid-count",
        check_u1801grid_count(),
        if check_u1801grid_count() { "" } else { "UNX-F1801 grid count mismatch" },
    );
    set.add(
        "u1801-grid-sum",
        check_u1801grid_sum(),
        if check_u1801grid_sum() { "" } else { "UNX-F1801 grid sum mismatch" },
    );
    set.add(
        "u1801-grid-guard",
        check_u1801grid_guard(),
        if check_u1801grid_guard() { "" } else { "UNX-F1801 grid guard mismatch" },
    );
    set
}

