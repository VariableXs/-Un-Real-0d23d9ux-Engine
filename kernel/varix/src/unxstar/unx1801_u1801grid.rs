pub const U1801_SEG_BASE: u16 = 0x5d00;

// --------------------------------------------------------------------------

// 诊断码（U1801_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U1801_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1801Code {
    /// 0x5d00 单元格重复（跳段 同键双占）。
    CellDup = 0x5d00,
    /// 0x5d01 单元格断档（签名缺位 序号不连续）。
    CellGap = 0x5d01,
    /// 0x5d02 索引越界（切换丢账）。
    IndexOob = 0x5d02,
    /// 0x5d03 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5d03,
    /// 0x5d04 表序断档。
    OrderBreak = 0x5d04,
    /// 0x5d05 累计漂移（求和≠理论值）。
    SumDrift = 0x5d05,
    /// 0x5d06 掩码非法。
    MaskBad = 0x5d06,
    /// 0x5d07 守卫触发。
    GuardTripped = 0x5d07,
    /// 0x5d08 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5d08,
    /// 0x5d09 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5d09,
    /// 0x5d0a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5d0a,
    /// 0x5d0b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5d0b,
}

impl u1801Code {
    /// 全量闭集。
    pub const ALL: [u1801Code; 12] = [
        u1801Code::CellDup,
        u1801Code::CellGap,
        u1801Code::IndexOob,
        u1801Code::LedgerBreak,
        u1801Code::OrderBreak,
        u1801Code::SumDrift,
        u1801Code::MaskBad,
        u1801Code::GuardTripped,
        u1801Code::LedgerBroken,
        u1801Code::SnapshotFingerprint,
        u1801Code::TableBroken,
        u1801Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U1801CODE_NAMES[(self.code() - U1801_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U1801CODE_SUGGESTIONS[(self.code() - U1801_SEG_BASE) as usize]
    }
}

