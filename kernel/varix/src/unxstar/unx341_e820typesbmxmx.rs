// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t341_guard_seg() -> bool {
    t341_segment_guard()
}

/// 表 mem_matrixb 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t341_mem_matrixb_guard() -> bool {
    let mut ok = mem_matrixb_COUNT == 512;
    if ok {
        ok = mem_matrixb_scan() == 0;
    }
    if ok {
        ok = mem_matrixb_unique();
    }
    ok
}

/// 矩阵累计守恒（1..512 = 130816）。
fn check_c2_t341_mxsum() -> bool {
    mem_matrixb_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t341_checks() -> CheckSet {
    let mut set = CheckSet::new("T341");
    set.add(
        "t341-seg-guard",
        t341_guard_seg(),
        if t341_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t341-c1-mx-guard",
        check_t341_mem_matrixb_guard(),
        if check_t341_mem_matrixb_guard() { "" } else { "table mem_matrixb guard mismatch" },
    );
    set.add(
        "t341-c2-mx-sum",
        check_c2_t341_mxsum(),
        if check_c2_t341_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

