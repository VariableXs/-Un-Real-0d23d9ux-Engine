// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x3fb0, 0x3fbf]。
pub const fn t341_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t341Code::ALL.len() {
        let c = t341Code::ALL[i].code();
        if c < 0x3fb0 || c > 0x3fbf {
            ok = false;
        }
        i += 1;
    }
    ok
}

