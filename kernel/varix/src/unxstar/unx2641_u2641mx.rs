// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0xa990, 0xa99f]。
pub const fn u2641_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2641Code::ALL.len() {
        let c = u2641Code::ALL[i].code();
        if c < 0xa990 || c > 0xa99f {
            ok = false;
        }
        i += 1;
    }
    ok
}

