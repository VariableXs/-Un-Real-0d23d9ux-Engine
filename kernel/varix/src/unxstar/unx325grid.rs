/// 段位守卫：全部诊断码必须落在本段 [0x6280, 0x628f]。
pub const fn t325_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t325Code::ALL.len() {
        let c = t325Code::ALL[i].code();
        if c < 0x6280 || c > 0x628f {
            ok = false;
        }
        i += 1;
    }
    ok
}

