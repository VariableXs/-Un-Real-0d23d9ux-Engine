pub fn unx325grid_get(key: &'static str) -> Option<u64> {
    let mut i = 0usize;
    while i < unx325grid_COUNT {
        if unx325grid[i].0 == key {
            return Some(unx325grid[i].1);
        }
        i += 1;
    }
    None
}

/// 累计求和（用于守恒对账）。
pub fn unx325grid_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < unx325grid_COUNT {
        s = s.wrapping_add(unx325grid[i].1 as u64);
        i += 1;
    }
    s
}

