/// UNX-F3421 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u3421_bmx_count() -> bool {
    let mut ok = u3421bmx_COUNT == 256;
    if ok { ok = u3421bmx_get("BE0000") == Some(0) && u3421bmx_get("ABI0255") == Some(5); }
    if ok { ok = u3421bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3421 bmx 累计守恒（理论值 11231）。
fn check_u3421_bmx_sum() -> bool {
    u3421bmx_sum() == 11231
}

/// UNX-F3421 bmx 逐行守卫与唯一性全绿。
fn check_u3421_bmx_guard() -> bool {
    u3421bmx_scan() == 0 && u3421bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3421_checks() -> CheckSet {
    let mut set = CheckSet::new("U3421");
    set.add(
        "u3421-seg-guard",
        u3421_guard_seg(),
        if u3421_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3421-bmx-count",
        check_u3421_bmx_count(),
        if check_u3421_bmx_count() { "" } else { "UNX-F3421 bmx count mismatch" },
    );
    set.add(
        "u3421-bmx-sum",
        check_u3421_bmx_sum(),
        if check_u3421_bmx_sum() { "" } else { "UNX-F3421 bmx sum mismatch" },
    );
    set.add(
        "u3421-bmx-guard",
        check_u3421_bmx_guard(),
        if check_u3421_bmx_guard() { "" } else { "UNX-F3421 bmx guard mismatch" },
    );
    set
}

