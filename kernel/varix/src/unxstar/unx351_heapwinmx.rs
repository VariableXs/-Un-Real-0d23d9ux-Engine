/// 段位守卫：全部诊断码必须落在本段 [0x4090, 0x409f]。
pub const fn t351_segment_guard() -> bool {
    // 不变量：14 枚诊断码连续十六进制、与声明序恒等；
    // 判据失败路径：任一码越出段界即整体判红（防诊断串段）。
    let mut ok = true;
    let mut i = 0usize;
    while i < t351Code::ALL.len() {
        let c = t351Code::ALL[i].code();
        if c < 0x4090 || c > 0x409f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t351_guard_seg() -> bool {
    t351_segment_guard()
}

/// 表 heap_matrix 逐行守卫全绿（行数/守卫/唯一性）。
/// 卫语句+提前返回：任一判据失败立即判红；三重判据依次为
/// 行数恒等 1024 → 逐行守卫零违例 → 键唯一。
fn check_t351_heap_matrix_guard() -> bool {
    // 判据 1：行数不变量（1024 行守卫矩阵，与主表同源对拍）。
    if heap_matrix_COUNT != 1024 {
        return false;
    }
    // 判据 2：逐行守卫扫描零违例（违例即行守卫破缺）。
    if heap_matrix_scan() != 0 {
        return false;
    }
    // 判据 3：键唯一（同键双写即判红）。
    heap_matrix_unique()
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t351_mxsum() -> bool {
    heap_matrix_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t351_checks() -> CheckSet {
    let mut set = CheckSet::new("T351");
    // 判据均为纯函数：先缓存求值结果与 detail（消除 bool/detail 双重求值），再逐条注入。
    let seg_ok = t351_guard_seg();
    let seg_detail = if seg_ok { "" } else { "diagnostic code outside segment" };
    set.add("t351-seg-guard", seg_ok, seg_detail);
    let c1_ok = check_t351_heap_matrix_guard();
    let c1_detail = if c1_ok { "" } else { "table heap_matrix guard mismatch" };
    set.add("t351-c1-mx-guard", c1_ok, c1_detail);
    let c2_ok = check_c2_t351_mxsum();
    let c2_detail = if c2_ok { "" } else { "matrix sum mismatch" };
    set.add("t351-c2-mx-sum", c2_ok, c2_detail);
    set
}

