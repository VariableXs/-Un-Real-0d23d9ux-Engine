/// 【内核 1·键解析】heap_matrix_parse_index：仅接受 "HX" + 4 位十进制（键形态闭空间），
/// 且序号 n < 1024（表定长）才返回 Some。
/// get（查找路径）与 scan（逐行守卫路径）共用本内核，键解析逻辑只此一份，
/// 杜绝双写漂移。解析结果即表内行号——序号限幅后等价于键在表闭集内；
/// 长度/前缀/非数字/越界任一不符返回 None，与原全枚举未命中分支等价。
fn heap_matrix_parse_index(key: &str) -> Option<usize> {
    let b = key.as_bytes();
    if b.len() != 6 || b[0] != b'H' || b[1] != b'X' {
        return None;
    }
    let mut n = 0usize;
    let mut j = 2usize;
    while j < 6 {
        if !b[j].is_ascii_digit() {
            return None;
        }
        n = n * 10 + (b[j] - b'0') as usize;
        j += 1;
    }
    if n < heap_matrix_COUNT { Some(n) } else { None }
}

/// 【内核 2·行守卫】行 i 守卫判定：行键解析序号恰为 i（键严格递增无断档）
/// 且行值==行序号。scan 逐行复用本判定；对编译期冻结表逐行断言恒真
/// （违例行计数口径不变，冻结表上恒为 0），与原逐行守卫 match 逐条等价。
fn heap_matrix_row_guard_ok(i: usize) -> bool {
    let (k, v) = heap_matrix[i];
    match heap_matrix_parse_index(k) {
        Some(n) => n == i && v == n as u64,
        None => false,
    }
}

/// O(1) 语义查找：从键解析序号 i，命中即返回表内第 i 行的值。
/// 消重归并说明：键解析走内核 1（heap_matrix_parse_index），
/// 本函数仅保留路径编排职责（无臂编排，取值经 .get 限幅单点化）。
/// 规律（与 unx261/unx301 同源对拍核实）：1024 键 HX0000..HX1023 严格递增，
/// 且每行值==键序号（自检判据 sum==523776 佐证），故
/// get(k) == parse(k) 限幅后取 heap_matrix[i].1，与原全枚举语义等价；
/// 命中率 100% 由 heap_matrix_scan / heap_matrix_unique 守卫保证。
pub fn heap_matrix_get(key: &str) -> Option<u64> {
    // 显式 let 绑定查找结果：先解析序号，再经 .get 限幅取表行值；
    // 解析已保证 i < 1024（表定长），越界不可达，无 panic 路径；
    // 解析 None 与越界 None 两失败路径与原 Some/None match 逐路恒等。
    let hit = heap_matrix_parse_index(key).and_then(|i| {
        let row = heap_matrix.get(i);
        row.map(|entry| entry.1)
    });
    hit
}

/// 逐行守卫扫描（返回违例行数；0 = 全绿）。
/// 消重归并说明：逐行判定走内核 2（heap_matrix_row_guard_ok），
/// 本函数仅保留「计数外循环」职责（消重后单一职责，判定逻辑不再内联）。
pub fn heap_matrix_scan() -> usize {
    let mut bad = 0usize;
    // 不变量：heap_matrix 为编译期冻结表（键唯一、值与键号恒等），逐行核对违例。
    // for 直驱行号（0..COUNT），省去手写步进，步进不变量由迭代器承担。
    for i in 0..heap_matrix_COUNT {
        if !heap_matrix_row_guard_ok(i) {
            bad += 1;
        }
    }
    bad
}

/// 累计求和（守恒对账用）。
pub fn heap_matrix_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    // 守恒口径：全表逐行 wrapping 累加，理论值 523776；偏差即矩阵累计漂移判红。
    while i < heap_matrix_COUNT {
        s = s.wrapping_add(heap_matrix[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn heap_matrix_unique() -> bool {
    // 判据失败路径：任一 i<j 对同键（同键双写）立即返回 false。
    let mut i = 0usize;
    while i < heap_matrix_COUNT {
        let mut j = i + 1;
        while j < heap_matrix_COUNT {
            if heap_matrix[i].0 == heap_matrix[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

