// --------------------------------------------------------------------------
// 诊断码（t351 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 早年堆域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t351Code {
    /// 0x4090 矩阵行重复。
    RowDup = 0x4090,
    /// 0x4091 矩阵断档。
    RowGap = 0x4091,
    /// 0x4092 行守卫破缺（逐行校验失败）。
    GuardBreak = 0x4092,
    /// 0x4093 矩阵累计漂移。
    SumDrift = 0x4093,
    /// 0x4094 索引错位。
    IndexMisaligned = 0x4094,
    /// 0x4095 矩阵账破缺。
    LedgerBreak = 0x4095,
    /// 0x4096 矩阵序断档。
    OrderBreak = 0x4096,
    /// 0x4097 守卫触发。
    GuardTripped = 0x4097,
    /// 0x4098 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x4098,
    /// 0x4099 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x4099,
    /// 0x409a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x409a,
    /// 0x409b 条目重复（同键双写）。
    DuplicateEntry = 0x409b,
    /// 0x409c 次序违例（依赖序/时序破缺）。
    OrderViolated = 0x409c,
    /// 0x409d 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x409d,
}

impl t351Code {
    /// 全量闭集。
    pub const ALL: [t351Code; 14] = [
        t351Code::RowDup,
        t351Code::RowGap,
        t351Code::GuardBreak,
        t351Code::SumDrift,
        t351Code::IndexMisaligned,
        t351Code::LedgerBreak,
        t351Code::OrderBreak,
        t351Code::GuardTripped,
        t351Code::LedgerBroken,
        t351Code::SnapshotFingerprint,
        t351Code::TableBroken,
        t351Code::DuplicateEntry,
        t351Code::OrderViolated,
        t351Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值，0x4090..0x409d 连续且与声明序恒等；
    /// as 直达与原 14 臂 match 逐变体码值对拍全等，零分支零 panic 路径）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：14 臂派发单点归并于 code()，名称表序与 ALL/码值连续段恒等）。
    pub const fn name(self) -> &'static str {
        T351_NAMES[(self.code() - T351_SEG_BASE) as usize]
    }

    /// 可操作修复建议（每条诊断都必须带下一步动作；查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        T351_SUGGESTIONS[(self.code() - T351_SEG_BASE) as usize]
    }
}

