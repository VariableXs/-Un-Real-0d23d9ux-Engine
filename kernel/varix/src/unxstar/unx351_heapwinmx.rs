// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4090, 0x409f]。
pub const fn t351_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t351Code::ALL.len() {
        let c = t351Code::ALL[i].code();
        if c < 0x4090 || c > 0x409f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t351_guard_seg() -> bool {
    t351_segment_guard()
}

/// 表 heap_matrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t351_heap_matrix_guard() -> bool {
    let mut ok = heap_matrix_COUNT == 1024;
    if ok {
        ok = heap_matrix_scan() == 0;
    }
    if ok {
        ok = heap_matrix_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t351_mxsum() -> bool {
    heap_matrix_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t351_checks() -> CheckSet {
    let mut set = CheckSet::new("T351");
    set.add(
        "t351-seg-guard",
        t351_guard_seg(),
        if t351_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t351-c1-mx-guard",
        check_t351_heap_matrix_guard(),
        if check_t351_heap_matrix_guard() { "" } else { "table heap_matrix guard mismatch" },
    );
    set.add(
        "t351-c2-mx-sum",
        check_c2_t351_mxsum(),
        if check_c2_t351_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

