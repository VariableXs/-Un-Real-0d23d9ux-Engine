/// UNX-F2501 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u2501_mx_count() -> bool {
    let mut ok = u2501mx_COUNT == 512;
    if ok { ok = u2501mx_get("IF0000") == Some(0) && u2501mx_get("HD0511") == Some(47); }
    if ok { ok = u2501mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2501 mx 累计守恒（理论值 24448）。
fn check_u2501_mx_sum() -> bool {
    u2501mx_sum() == 24448
}

/// UNX-F2501 mx 逐行守卫与唯一性全绿。
fn check_u2501_mx_guard() -> bool {
    u2501mx_scan() == 0 && u2501mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2501_checks() -> CheckSet {
    let mut set = CheckSet::new("U2501");
    set.add(
        "u2501-seg-guard",
        u2501_guard_seg(),
        if u2501_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2501-mx-count",
        check_u2501_mx_count(),
        if check_u2501_mx_count() { "" } else { "UNX-F2501 mx count mismatch" },
    );
    set.add(
        "u2501-mx-sum",
        check_u2501_mx_sum(),
        if check_u2501_mx_sum() { "" } else { "UNX-F2501 mx sum mismatch" },
    );
    set.add(
        "u2501-mx-guard",
        check_u2501_mx_guard(),
        if check_u2501_mx_guard() { "" } else { "UNX-F2501 mx guard mismatch" },
    );
    set
}

