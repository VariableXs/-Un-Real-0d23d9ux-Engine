/// 段位守卫：全部诊断码落在本模块段内。
fn u2841_guard_seg() -> bool {
    u2841_segment_guard()
}

/// UNX-F2841 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u2841_grid_count() -> bool {
    let mut ok = u2841grid_COUNT == 1024;
    if ok { ok = u2841grid_get("HP0000") == Some(0) && u2841grid_get("MATRIX1023") == Some(10); }
    if ok { ok = u2841grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2841 grid 累计守恒（理论值 49061）。
fn check_u2841_grid_sum() -> bool {
    u2841grid_sum() == 49061
}

/// UNX-F2841 grid 逐行守卫与唯一性全绿。
fn check_u2841_grid_guard() -> bool {
    u2841grid_scan() == 0 && u2841grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2841_checks() -> CheckSet {
    let mut set = CheckSet::new("U2841");
    set.add(
        "u2841-seg-guard",
        u2841_guard_seg(),
        if u2841_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2841-grid-count",
        check_u2841_grid_count(),
        if check_u2841_grid_count() { "" } else { "UNX-F2841 grid count mismatch" },
    );
    set.add(
        "u2841-grid-sum",
        check_u2841_grid_sum(),
        if check_u2841_grid_sum() { "" } else { "UNX-F2841 grid sum mismatch" },
    );
    set.add(
        "u2841-grid-guard",
        check_u2841_grid_guard(),
        if check_u2841_grid_guard() { "" } else { "UNX-F2841 grid guard mismatch" },
    );
    set
}

