/// 表 cf8bdf 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t442_cf8bdf_guard() -> bool {
    let mut ok = cf8bdf_COUNT == 256;
    if ok {
        ok = cf8bdf_scan() == 0;
    }
    if ok {
        ok = cf8bdf_unique();
    }
    ok
}

/// CF8 编解码往返 + 非法拒收（reg 8 位字段口径）。
fn check_c2_cf8_codec() -> bool {
    let mut ok = cf8_roundtrip(0, 0, 0, 0);
    if ok {
        ok = cf8_roundtrip(255, 31, 7, 252);
    }
    if ok {
        ok = cf8_addr(256, 0, 0, 0).is_none() && cf8_addr(0, 32, 0, 0).is_none() && cf8_addr(0, 0, 0, 256).is_none();
    }
    if ok {
        ok = cf8_decode(0).is_none() && cf8_decode(0x8000_0000).is_some();
    }
    if ok {
        ok = cf8_addr(0, 0, 0, 0x10).map_or(false, |a| a == 0x8000_0010);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t442_checks() -> CheckSet {
    let mut set = CheckSet::new("T442");
    set.add(
        "t442-seg-guard",
        t442_guard_seg(),
        if t442_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t442-c1-bdf-guard",
        check_t442_cf8bdf_guard(),
        if check_t442_cf8bdf_guard() { "" } else { "table cf8bdf guard mismatch" },
    );
    set.add(
        "t442-c2-cf8-codec",
        check_c2_cf8_codec(),
        if check_c2_cf8_codec() { "" } else { "cf8 codec roundtrip mismatch" },
    );
    set
}

