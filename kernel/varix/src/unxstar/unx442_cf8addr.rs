// ---------------------------------------------------------------------------
// CF8 地址编码引擎（Type1: bus16 + dev5 + fn3 + reg12 + enable）
// ---------------------------------------------------------------------------

/// CF8 使能位（bit31）。
pub const CF8_ENABLE: u32 = 1 << 31;

/// 设备字段宽度（5 位）。
pub const DEV_BITS: u32 = 5;

/// 功能字段宽度（3 位）。
pub const FN_BITS: u32 = 3;

/// 寄存器字段宽度（12 位，双字对齐低 2 位为 0）。
pub const REG_BITS: u32 = 12;

/// CF8 地址编码（Type1：寄存器字段 8 位 + 双字对齐掩码）。
pub const fn cf8_addr(bus: u32, dev: u32, func: u32, reg: u32) -> Option<u32> {
    if bus >= 256 || dev >= 32 || func >= 8 || reg >= 256 {
        return None;
    }
    Some(CF8_ENABLE | (bus << 16) | (dev << 11) | (func << 8) | (reg & 0xFC))
}

/// 地址解码（CF8 → BDF + reg；enable 位清零后按位段拆）。
pub const fn cf8_decode(addr: u32) -> Option<(u32, u32, u32, u32)> {
    if addr & CF8_ENABLE == 0 {
        return None;
    }
    let raw = addr & !CF8_ENABLE;
    Some(((raw >> 16) & 0xFF, (raw >> 11) & 0x1F, (raw >> 8) & 0x7, raw & 0xFF))
}

/// 编码往返恒等（编码→解码必须还原）。
pub const fn cf8_roundtrip(bus: u32, dev: u32, func: u32, reg: u32) -> bool {
    match cf8_addr(bus, dev, func, reg) {
        Some(a) => match cf8_decode(a) {
            Some((b, d, f, r)) => b == bus && d == dev && f == func && r == (reg & 0xFC),
            None => false,
        },
        None => false,
    }
}

