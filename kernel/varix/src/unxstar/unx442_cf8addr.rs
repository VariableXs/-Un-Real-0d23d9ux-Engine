/// 段位守卫：全部诊断码必须落在本段 [0x4410, 0x441f]。
pub const fn t442_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t442Code::ALL.len() {
        let c = t442Code::ALL[i].code();
        if c < 0x4410 || c > 0x441f {
            ok = false;
        }
        i += 1;
    }
    ok
}

