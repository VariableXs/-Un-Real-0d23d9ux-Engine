/// 累计求和（守恒对账用）。
pub fn cf8bdf_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < cf8bdf_COUNT {
        s = s.wrapping_add(cf8bdf[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn cf8bdf_unique() -> bool {
    let mut i = 0usize;
    while i < cf8bdf_COUNT {
        let mut j = i + 1;
        while j < cf8bdf_COUNT {
            if cf8bdf[i].0 == cf8bdf[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

