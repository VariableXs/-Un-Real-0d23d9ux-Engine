/// UNX-F1501 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u1501_grid_count() -> bool {
    let mut ok = u1501grid_COUNT == 1024;
    if ok { ok = u1501grid_get("SC0000") == Some(0) && u1501grid_get("MR1023") == Some(10); }
    if ok { ok = u1501grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F1501 grid 累计守恒（理论值 49061）。
fn check_u1501_grid_sum() -> bool {
    u1501grid_sum() == 49061
}

/// UNX-F1501 grid 逐行守卫与唯一性全绿。
fn check_u1501_grid_guard() -> bool {
    u1501grid_scan() == 0 && u1501grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u1501_checks() -> CheckSet {
    let mut set = CheckSet::new("U1501");
    set.add(
        "u1501-seg-guard",
        u1501_guard_seg(),
        if u1501_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u1501-grid-count",
        check_u1501_grid_count(),
        if check_u1501_grid_count() { "" } else { "UNX-F1501 grid count mismatch" },
    );
    set.add(
        "u1501-grid-sum",
        check_u1501_grid_sum(),
        if check_u1501_grid_sum() { "" } else { "UNX-F1501 grid sum mismatch" },
    );
    set.add(
        "u1501-grid-guard",
        check_u1501_grid_guard(),
        if check_u1501_grid_guard() { "" } else { "UNX-F1501 grid guard mismatch" },
    );
    set
}

