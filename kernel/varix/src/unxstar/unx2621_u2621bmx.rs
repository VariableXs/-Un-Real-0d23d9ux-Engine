// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u2621_guard_seg() -> bool {
    u2621_segment_guard()
}

/// UNX-F2621 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u2621_bmx_count() -> bool {
    let mut ok = u2621bmx_COUNT == 256;
    if ok { ok = u2621bmx_get("CR0000") == Some(0) && u2621bmx_get("NF0255") == Some(5); }
    if ok { ok = u2621bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2621 bmx 累计守恒（理论值 11231）。
fn check_u2621_bmx_sum() -> bool {
    u2621bmx_sum() == 11231
}

/// UNX-F2621 bmx 逐行守卫与唯一性全绿。
fn check_u2621_bmx_guard() -> bool {
    u2621bmx_scan() == 0 && u2621bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2621_checks() -> CheckSet {
    let mut set = CheckSet::new("U2621");
    set.add(
        "u2621-seg-guard",
        u2621_guard_seg(),
        if u2621_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2621-bmx-count",
        check_u2621_bmx_count(),
        if check_u2621_bmx_count() { "" } else { "UNX-F2621 bmx count mismatch" },
    );
    set.add(
        "u2621-bmx-sum",
        check_u2621_bmx_sum(),
        if check_u2621_bmx_sum() { "" } else { "UNX-F2621 bmx sum mismatch" },
    );
    set.add(
        "u2621-bmx-guard",
        check_u2621_bmx_guard(),
        if check_u2621_bmx_guard() { "" } else { "UNX-F2621 bmx guard mismatch" },
    );
    set
}

