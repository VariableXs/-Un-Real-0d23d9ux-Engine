// --------------------------------------------------------------------------
/// CR3 切换 grid 面诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u2621Code {
    /// 0xa8c0 单元格重复（切换点漏 同键双占）。
    CellDup,
    /// 0xa8c1 单元格断档（冲刷错配 序号不连续）。
    CellGap,
    /// 0xa8c2 索引越界（联签缺失）。
    IndexOob,
    /// 0xa8c3 大表账破缺（行数≠登记值）。
    LedgerBreak,
    /// 0xa8c4 表序断档。
    OrderBreak,
    /// 0xa8c5 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0xa8c6 掩码非法。
    MaskBad,
    /// 0xa8c7 守卫触发。
    GuardTripped,
    /// 0xa8c8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0xa8c9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0xa8ca 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0xa8cb 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

