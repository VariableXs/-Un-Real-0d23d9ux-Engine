/// 段位守卫：全部诊断码落在本模块段内。
fn u2621_guard_seg() -> bool {
    u2621_segment_guard()
}

/// UNX-F2621 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u2621_grid_count() -> bool {
    let mut ok = u2621grid_COUNT == 1024;
    if ok { ok = u2621grid_get("CR0000") == Some(0) && u2621grid_get("NF1023") == Some(10); }
    if ok { ok = u2621grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2621 grid 累计守恒（理论值 49061）。
fn check_u2621_grid_sum() -> bool {
    u2621grid_sum() == 49061
}

/// UNX-F2621 grid 逐行守卫与唯一性全绿。
fn check_u2621_grid_guard() -> bool {
    u2621grid_scan() == 0 && u2621grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2621_checks() -> CheckSet {
    let mut set = CheckSet::new("U2621");
    set.add(
        "u2621-seg-guard",
        u2621_guard_seg(),
        if u2621_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2621-grid-count",
        check_u2621_grid_count(),
        if check_u2621_grid_count() { "" } else { "UNX-F2621 grid count mismatch" },
    );
    set.add(
        "u2621-grid-sum",
        check_u2621_grid_sum(),
        if check_u2621_grid_sum() { "" } else { "UNX-F2621 grid sum mismatch" },
    );
    set.add(
        "u2621-grid-guard",
        check_u2621_grid_guard(),
        if check_u2621_grid_guard() { "" } else { "UNX-F2621 grid guard mismatch" },
    );
    set
}

