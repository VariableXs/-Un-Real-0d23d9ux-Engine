/// 段位守卫：全部诊断码必须落在本段 [0xa140, 0xa14f]。
pub const fn u2421_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2421Code::ALL.len() {
        let c = u2421Code::ALL[i].code();
        if c < 0xa140 || c > 0xa14f {
            ok = false;
        }
        i += 1;
    }
    ok
}

