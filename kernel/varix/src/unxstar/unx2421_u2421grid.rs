// 键 → 行序号解析（末四位为 1023 补零行序；前缀长度 6~7 不固定，故只校验末四位）
// --------------------------------------------------------------------------
/// 键末四位解析为行序号（越界/非数字一律拒收）。
/// 键形如「语义前缀 + 1023 补零行序」，前缀长度不固定，故只取末四位。
const fn u2421grid_key_index(key: &str) -> Option<usize> {
    let bytes = key.as_bytes();
    let len = bytes.len();
    if len < 4 {
        return None;
    }
    let mut idx = 0usize;
    let mut i = len - 4;
    while i < len {
        let d = bytes[i];
        if d < b'0' || d > b'9' {
            return None;
        }
        idx = idx * 10 + (d - b'0') as usize;
        i += 1;
    }
    if idx < u2421grid_COUNT { Some(idx) } else { None }
}

/// 按序号取表行（键串必须与表行逐字相符，命中才返回值）。
const fn u2421grid_row(key: &str, idx: usize) -> Option<u64> {
    let (k, v) = u2421grid[idx];
    if str_eq(k, key) { Some(v) } else { None }
}

/// 编译期字符串逐字比对（长度先行，逐字节短路）。
const fn str_eq(a: &str, b: &str) -> bool {
    let (x, y) = (a.as_bytes(), b.as_bytes());
    if x.len() != y.len() {
        return false;
    }
    let mut i = 0usize;
    while i < x.len() {
        if x[i] != y[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// O(1) 语义查找（键序号解析 + 表行逐字核验；越界键与异形键一概拒收）。
pub fn u2421grid_get(key: &str) -> Option<u64> {
    match u2421grid_key_index(key) {
        Some(idx) => u2421grid_row(key, idx),
        None => None,
    }
}

/// 逐行守卫扫描（返回违例行数；0 = 全绿；判据与原 1024 臂逐行守卫等价）。
pub fn u2421grid_scan() -> usize {
    let mut bad = 0usize;
    let mut i = 0usize;
    while i < u2421grid_COUNT {
        let (k, v) = u2421grid[i];
        let ok = match u2421grid_key_index(k) {
            Some(idx) => idx == i && v < 97,
            None => false,
        };
        if !ok {
            bad += 1;
        }
        i += 1;
    }
    bad
}

/// 累计求和（守恒对账用）。
