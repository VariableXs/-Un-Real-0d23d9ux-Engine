// --------------------------------------------------------------------------
// 诊断码（u3321 十六码 · 12 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 锁类别选型矩阵 grid 面诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u3321Code {
    /// 0xe0b0 单元格重复（锁 同键双占）。
    CellDup,
    /// 0xe0b1 单元格断档（矩阵 序号不连续）。
    CellGap,
    /// 0xe0b2 索引越界（选型）。
    IndexOob,
    /// 0xe0b3 大表账破缺（行数≠登记值）。
    LedgerBreak,
    /// 0xe0b4 表序断档。
    OrderBreak,
    /// 0xe0b5 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0xe0b6 掩码非法。
    MaskBad,
    /// 0xe0b7 守卫触发。
    GuardTripped,
    /// 0xe0b8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0xe0b9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0xe0ba 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0xe0bb 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

