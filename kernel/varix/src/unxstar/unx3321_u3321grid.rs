// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0xe0b0, 0xe0bf]。
pub const fn u3321_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u3321Code::ALL.len() {
        let c = u3321Code::ALL[i].code();
        if c < 0xe0b0 || c > 0xe0bf {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u3321_guard_seg() -> bool {
    u3321_segment_guard()
}

/// UNX-F3321 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u3321_grid_count() -> bool {
    let mut ok = u3321grid_COUNT == 1024;
    if ok { ok = u3321grid_get("MTX0000") == Some(0) && u3321grid_get("SEQ1023") == Some(10); }
    if ok { ok = u3321grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3321 grid 累计守恒（理论值 49061）。
fn check_u3321_grid_sum() -> bool {
    u3321grid_sum() == 49061
}

/// UNX-F3321 grid 逐行守卫与唯一性全绿。
fn check_u3321_grid_guard() -> bool {
    u3321grid_scan() == 0 && u3321grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3321_checks() -> CheckSet {
    let mut set = CheckSet::new("U3321");
    set.add(
        "u3321-seg-guard",
        u3321_guard_seg(),
        if u3321_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3321-grid-count",
        check_u3321_grid_count(),
        if check_u3321_grid_count() { "" } else { "UNX-F3321 grid count mismatch" },
    );
    set.add(
        "u3321-grid-sum",
        check_u3321_grid_sum(),
        if check_u3321_grid_sum() { "" } else { "UNX-F3321 grid sum mismatch" },
    );
    set.add(
        "u3321-grid-guard",
        check_u3321_grid_guard(),
        if check_u3321_grid_guard() { "" } else { "UNX-F3321 grid guard mismatch" },
    );
    set
}

