/// 段位守卫：全部诊断码落在本模块段内。
fn u1621_guard_seg() -> bool {
    u1621_segment_guard()
}

/// UNX-F1621 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u1621_bmx_count() -> bool {
    let mut ok = u1621bmx_COUNT == 256;
    if ok { ok = u1621bmx_get("ST0000") == Some(0) && u1621bmx_get("SD0255") == Some(5); }
    if ok { ok = u1621bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F1621 bmx 累计守恒（理论值 11231）。
fn check_u1621_bmx_sum() -> bool {
    u1621bmx_sum() == 11231
}

/// UNX-F1621 bmx 逐行守卫与唯一性全绿。
fn check_u1621_bmx_guard() -> bool {
    u1621bmx_scan() == 0 && u1621bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u1621_checks() -> CheckSet {
    let mut set = CheckSet::new("U1621");
    set.add(
        "u1621-seg-guard",
        u1621_guard_seg(),
        if u1621_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u1621-bmx-count",
        check_u1621_bmx_count(),
        if check_u1621_bmx_count() { "" } else { "UNX-F1621 bmx count mismatch" },
    );
    set.add(
        "u1621-bmx-sum",
        check_u1621_bmx_sum(),
        if check_u1621_bmx_sum() { "" } else { "UNX-F1621 bmx sum mismatch" },
    );
    set.add(
        "u1621-bmx-guard",
        check_u1621_bmx_guard(),
        if check_u1621_bmx_guard() { "" } else { "UNX-F1621 bmx guard mismatch" },
    );
    set
}

