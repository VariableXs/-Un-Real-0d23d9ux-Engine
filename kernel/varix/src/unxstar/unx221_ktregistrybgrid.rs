// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t221_guard_seg() -> bool {
    t221_segment_guard()
}

/// 大表 assert_schedb 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t221_grid() -> bool {
    let mut ok = assert_schedb_COUNT == 1024;
    if ok {
        ok = assert_schedb_get("AS0000") == Some(0) && assert_schedb_get("AS1023") == Some(1023);
    }
    if ok {
        ok = assert_schedb_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t221_sum() -> bool {
    assert_schedb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t221_checks() -> CheckSet {
    let mut set = CheckSet::new("T221");
    set.add(
        "t221-seg-guard",
        t221_guard_seg(),
        if t221_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t221-c1-grid",
        check_c1_t221_grid(),
        if check_c1_t221_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t221-c2-grid-sum",
        check_c2_t221_sum(),
        if check_c2_t221_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

