/// 段位守卫：全部诊断码必须落在本段 [0x38a0, 0x38af]。
pub const fn t221_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t221Code::ALL.len() {
        let c = t221Code::ALL[i].code();
        if c < 0x38a0 || c > 0x38af {
            ok = false;
        }
        i += 1;
    }
    ok
}

