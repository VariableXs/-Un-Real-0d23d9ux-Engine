/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u1561grid_unique() -> bool {
    let mut i = 0usize;
    while i < u1561grid_COUNT {
        let mut j = i + 1;
        while j < u1561grid_COUNT {
            if u1561grid[i].0 == u1561grid[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

