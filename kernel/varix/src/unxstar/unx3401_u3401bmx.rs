/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u3401bmx_unique() -> bool {
    let mut i = 0usize;
    while i < u3401bmx_COUNT {
        let mut j = i + 1;
        while j < u3401bmx_COUNT {
            if u3401bmx[i].0 == u3401bmx[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

