/// 线性查找（键唯一性由构造期断言保证，运行时无分支歧义）。
pub fn pg_cell_get(key: &'static str) -> Option<u64> {
    let mut i = 0usize;
    while i < pg_cell_COUNT {
        if pg_cell[i].0 == key {
            return Some(pg_cell[i].1);
        }
        i += 1;
    }
    None
}

/// 累计求和（用于守恒对账）。
pub fn pg_cell_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < pg_cell_COUNT {
        s = s.wrapping_add(pg_cell[i].1 as u64);
        i += 1;
    }
    s
}

// ---------------------------------------------------------------------------
// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x3c80, 0x3c8f]。
pub const fn t301_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t301Code::ALL.len() {
        let c = t301Code::ALL[i].code();
        if c < 0x3c80 || c > 0x3c8f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t301_guard_seg() -> bool {
    t301_segment_guard()
}

/// 大表 pg_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t301_grid() -> bool {
    let mut ok = pg_cell_COUNT == 1024;
    if ok {
        ok = pg_cell_get("GC0000") == Some(0) && pg_cell_get("GC1023") == Some(1023);
    }
    if ok {
        ok = pg_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t301_sum() -> bool {
    pg_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t301_checks() -> CheckSet {
    let mut set = CheckSet::new("T301");
    set.add(
        "t301-seg-guard",
        t301_guard_seg(),
        if t301_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t301-c1-grid",
        check_c1_t301_grid(),
        if check_c1_t301_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t301-c2-grid-sum",
        check_c2_t301_sum(),
        if check_c2_t301_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

