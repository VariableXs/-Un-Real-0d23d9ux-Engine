// --------------------------------------------------------------------------
/// 边沿 EOI 域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t842Code {
    /// 0x5110 格重复（同键双占）。
    CellDup,
    /// 0x5111 格断档（序号不连续）。
    CellGap,
    /// 0x5112 索引越界（≥1024）。
    IndexOob,
    /// 0x5113 大表账破缺。
    LedgerBreak,
    /// 0x5114 表序断档。
    OrderBreak,
    /// 0x5115 累计漂移。
    SumDrift,
    /// 0x5116 掩码非法。
    MaskBad,
    /// 0x5117 守卫触发。
    GuardTripped,
    /// 0x5118 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x5119 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x511a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x511b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x511c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x511d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x511e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

