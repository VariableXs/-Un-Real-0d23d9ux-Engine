/// 段位守卫：全部诊断码必须落在本段 [0x5110, 0x511f]。
pub const fn t842_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t842Code::ALL.len() {
        let c = t842Code::ALL[i].code();
        if c < 0x5110 || c > 0x511f {
            ok = false;
        }
        i += 1;
    }
    ok
}

