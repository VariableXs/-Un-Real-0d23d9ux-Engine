/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u1721bgrid_unique() -> bool {
    let mut i = 0usize;
    while i < u1721bgrid_COUNT {
        let mut j = i + 1;
        while j < u1721bgrid_COUNT {
            if u1721bgrid[i].0 == u1721bgrid[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

