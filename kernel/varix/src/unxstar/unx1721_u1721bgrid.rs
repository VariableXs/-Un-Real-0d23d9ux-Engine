pub const U1721_SEG_BASE: u16 = 0x5a20;

// --------------------------------------------------------------------------

// 诊断码（U1721_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U1721_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1721Code {
    /// 0x5a20 单元格重复（跳段 同键双占）。
    CellDup = 0x5a20,
    /// 0x5a21 单元格断档（签名缺位 序号不连续）。
    CellGap = 0x5a21,
    /// 0x5a22 索引越界（收益误判）。
    IndexOob = 0x5a22,
    /// 0x5a23 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5a23,
    /// 0x5a24 表序断档。
    OrderBreak = 0x5a24,
    /// 0x5a25 累计漂移（求和≠理论值）。
    SumDrift = 0x5a25,
    /// 0x5a26 掩码非法。
    MaskBad = 0x5a26,
    /// 0x5a27 守卫触发。
    GuardTripped = 0x5a27,
    /// 0x5a28 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5a28,
    /// 0x5a29 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5a29,
    /// 0x5a2a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5a2a,
    /// 0x5a2b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5a2b,
}

impl u1721Code {
    /// 全量闭集。
    pub const ALL: [u1721Code; 12] = [
        u1721Code::CellDup,
        u1721Code::CellGap,
        u1721Code::IndexOob,
        u1721Code::LedgerBreak,
        u1721Code::OrderBreak,
        u1721Code::SumDrift,
        u1721Code::MaskBad,
        u1721Code::GuardTripped,
        u1721Code::LedgerBroken,
        u1721Code::SnapshotFingerprint,
        u1721Code::TableBroken,
        u1721Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U1721CODE_NAMES[(self.code() - U1721_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U1721CODE_SUGGESTIONS[(self.code() - U1721_SEG_BASE) as usize]
    }
}

