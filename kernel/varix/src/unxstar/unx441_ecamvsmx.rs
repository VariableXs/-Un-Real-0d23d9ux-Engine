/// 累计求和（守恒对账用）。
pub fn cfg_matrix_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < cfg_matrix_COUNT {
        s = s.wrapping_add(cfg_matrix[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn cfg_matrix_unique() -> bool {
    let mut i = 0usize;
    while i < cfg_matrix_COUNT {
        let mut j = i + 1;
        while j < cfg_matrix_COUNT {
            if cfg_matrix[i].0 == cfg_matrix[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

