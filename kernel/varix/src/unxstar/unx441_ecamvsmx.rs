/// 段位守卫：全部诊断码必须落在本段 [0x4490, 0x449f]。
pub const fn t441_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t441Code::ALL.len() {
        let c = t441Code::ALL[i].code();
        if c < 0x4490 || c > 0x449f {
            ok = false;
        }
        i += 1;
    }
    ok
}

