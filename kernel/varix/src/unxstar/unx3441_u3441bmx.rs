/// UNX-F3441 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u3441_bmx_count() -> bool {
    let mut ok = u3441bmx_COUNT == 256;
    if ok { ok = u3441bmx_get("EX0000") == Some(0) && u3441bmx_get("SORT0255") == Some(5); }
    if ok { ok = u3441bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3441 bmx 累计守恒（理论值 11231）。
fn check_u3441_bmx_sum() -> bool {
    u3441bmx_sum() == 11231
}

/// UNX-F3441 bmx 逐行守卫与唯一性全绿。
fn check_u3441_bmx_guard() -> bool {
    u3441bmx_scan() == 0 && u3441bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3441_checks() -> CheckSet {
    let mut set = CheckSet::new("U3441");
    set.add(
        "u3441-seg-guard",
        u3441_guard_seg(),
        if u3441_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3441-bmx-count",
        check_u3441_bmx_count(),
        if check_u3441_bmx_count() { "" } else { "UNX-F3441 bmx count mismatch" },
    );
    set.add(
        "u3441-bmx-sum",
        check_u3441_bmx_sum(),
        if check_u3441_bmx_sum() { "" } else { "UNX-F3441 bmx sum mismatch" },
    );
    set.add(
        "u3441-bmx-guard",
        check_u3441_bmx_guard(),
        if check_u3441_bmx_guard() { "" } else { "UNX-F3441 bmx guard mismatch" },
    );
    set
}

