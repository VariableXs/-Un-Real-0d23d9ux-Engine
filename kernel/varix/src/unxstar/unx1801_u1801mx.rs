/// 段位守卫：全部诊断码必须落在本段 [0x5d10, 0x5d1f]。
pub const fn u1801_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1801Code::ALL.len() {
        let c = u1801Code::ALL[i].code();
        if c < 0x5d10 || c > 0x5d1f {
            ok = false;
        }
        i += 1;
    }
    ok
}

