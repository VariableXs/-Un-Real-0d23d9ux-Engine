/// UNX-F1841 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u1841_bmx_count() -> bool {
    let mut ok = u1841bmx_COUNT == 256;
    if ok { ok = u1841bmx_get("XL0000") == Some(0) && u1841bmx_get("EOI0255") == Some(5); }
    if ok { ok = u1841bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F1841 bmx 累计守恒（理论值 11231）。
fn check_u1841_bmx_sum() -> bool {
    u1841bmx_sum() == 11231
}

/// UNX-F1841 bmx 逐行守卫与唯一性全绿。
fn check_u1841_bmx_guard() -> bool {
    u1841bmx_scan() == 0 && u1841bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u1841_checks() -> CheckSet {
    let mut set = CheckSet::new("U1841");
    set.add(
        "u1841-seg-guard",
        u1841_guard_seg(),
        if u1841_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u1841-bmx-count",
        check_u1841_bmx_count(),
        if check_u1841_bmx_count() { "" } else { "UNX-F1841 bmx count mismatch" },
    );
    set.add(
        "u1841-bmx-sum",
        check_u1841_bmx_sum(),
        if check_u1841_bmx_sum() { "" } else { "UNX-F1841 bmx sum mismatch" },
    );
    set.add(
        "u1841-bmx-guard",
        check_u1841_bmx_guard(),
        if check_u1841_bmx_guard() { "" } else { "UNX-F1841 bmx guard mismatch" },
    );
    set
}

