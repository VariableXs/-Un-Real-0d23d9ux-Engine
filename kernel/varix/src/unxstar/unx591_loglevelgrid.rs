/// 段位守卫：全部诊断码必须落在本段 [0x4880, 0x488f]。
pub const fn t591_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t591Code::ALL.len() {
        let c = t591Code::ALL[i].code();
        if c < 0x4880 || c > 0x488f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t591_guard_seg() -> bool {
    t591_segment_guard()
}

/// 大表 log_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t591_grid() -> bool {
    let mut ok = log_cell_COUNT == 1024;
    if ok {
        ok = log_cell_get("LC0000") == Some(0) && log_cell_get("LC1023") == Some(1023);
    }
    if ok {
        ok = log_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t591_sum() -> bool {
    log_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t591_checks() -> CheckSet {
    let mut set = CheckSet::new("T591");
    set.add(
        "t591-seg-guard",
        t591_guard_seg(),
        if t591_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t591-c1-grid",
        check_c1_t591_grid(),
        if check_c1_t591_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t591-c2-grid-sum",
        check_c2_t591_sum(),
        if check_c2_t591_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

