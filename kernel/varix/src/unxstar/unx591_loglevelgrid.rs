// --------------------------------------------------------------------------
// 诊断码（t591 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 日志域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t591Code {
    /// 0x4880 单元格重复（同键双占）。
    CellDup,
    /// 0x4881 单元格断档（序号不连续）。
    CellGap,
    /// 0x4882 索引越界（≥1024）。
    IndexOob,
    /// 0x4883 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x4884 表序断档。
    OrderBreak,
    /// 0x4885 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0x4886 掩码非法。
    MaskBad,
    /// 0x4887 守卫触发。
    GuardTripped,
    /// 0x4888 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4889 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x488a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x488b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x488c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x488d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x488e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

