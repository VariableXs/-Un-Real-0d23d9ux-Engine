/// 段位守卫：全部诊断码落在本模块段内。
fn ta01_guard_seg() -> bool {
    ta01_segment_guard()
}

/// 表 pm_matrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_ta01_pm_matrix_guard() -> bool {
    let mut ok = pm_matrix_COUNT == 1024;
    if ok {
        ok = pm_matrix_scan() == 0;
    }
    if ok {
        ok = pm_matrix_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_ta01_mxsum() -> bool {
    pm_matrix_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_ta01_checks() -> CheckSet {
    let mut set = CheckSet::new("TA01");
    set.add(
        "ta01-seg-guard",
        ta01_guard_seg(),
        if ta01_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "ta01-c1-mx-guard",
        check_ta01_pm_matrix_guard(),
        if check_ta01_pm_matrix_guard() { "" } else { "table pm_matrix guard mismatch" },
    );
    set.add(
        "ta01-c2-mx-sum",
        check_c2_ta01_mxsum(),
        if check_c2_ta01_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

