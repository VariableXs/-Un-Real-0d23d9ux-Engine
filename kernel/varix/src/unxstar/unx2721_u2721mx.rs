/// 段位守卫：全部诊断码必须落在本段 [0xac90, 0xac9f]。
pub const fn u2721_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2721Code::ALL.len() {
        let c = u2721Code::ALL[i].code();
        if c < 0xac90 || c > 0xac9f {
            ok = false;
        }
        i += 1;
    }
    ok
}

