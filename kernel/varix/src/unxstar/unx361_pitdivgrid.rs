/// 段位守卫：全部诊断码必须落在本段 [0x4180, 0x418f]。
pub const fn t361_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t361Code::ALL.len() {
        let c = t361Code::ALL[i].code();
        if c < 0x4180 || c > 0x418f {
            ok = false;
        }
        i += 1;
    }
    ok
}

