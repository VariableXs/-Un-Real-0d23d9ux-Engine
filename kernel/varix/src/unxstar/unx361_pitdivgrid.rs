// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t361_guard_seg() -> bool {
    t361_segment_guard()
}

/// 大表 pit_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t361_grid() -> bool {
    let mut ok = pit_cell_COUNT == 1024;
    if ok {
        ok = pit_cell_get("PC0000") == Some(0) && pit_cell_get("PC1023") == Some(1023);
    }
    if ok {
        ok = pit_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t361_sum() -> bool {
    pit_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t361_checks() -> CheckSet {
    let mut set = CheckSet::new("T361");
    set.add(
        "t361-seg-guard",
        t361_guard_seg(),
        if t361_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t361-c1-grid",
        check_c1_t361_grid(),
        if check_c1_t361_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t361-c2-grid-sum",
        check_c2_t361_sum(),
        if check_c2_t361_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

