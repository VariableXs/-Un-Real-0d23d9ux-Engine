// --------------------------------------------------------------------------
// 诊断码（t361 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// PIT 域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t361Code {
    /// 0x4180 单元格重复（同键双占）。
    CellDup,
    /// 0x4181 单元格断档（序号不连续）。
    CellGap,
    /// 0x4182 索引越界（≥1024）。
    IndexOob,
    /// 0x4183 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x4184 表序断档。
    OrderBreak,
    /// 0x4185 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0x4186 掩码非法。
    MaskBad,
    /// 0x4187 守卫触发。
    GuardTripped,
    /// 0x4188 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4189 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x418a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x418b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x418c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x418d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x418e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

