// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0xe0e0, 0xe0ef]。
pub const fn u3321_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u3321Code::ALL.len() {
        let c = u3321Code::ALL[i].code();
        if c < 0xe0e0 || c > 0xe0ef {
            ok = false;
        }
        i += 1;
    }
    ok
}

