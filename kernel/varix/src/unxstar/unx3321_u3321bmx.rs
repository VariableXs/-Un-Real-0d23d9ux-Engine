// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u3321_guard_seg() -> bool {
    u3321_segment_guard()
}

/// UNX-F3321 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u3321_bmx_count() -> bool {
    let mut ok = u3321bmx_COUNT == 256;
    if ok { ok = u3321bmx_get("MTX0000") == Some(0) && u3321bmx_get("SEQ0255") == Some(5); }
    if ok { ok = u3321bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3321 bmx 累计守恒（理论值 11231）。
fn check_u3321_bmx_sum() -> bool {
    u3321bmx_sum() == 11231
}

/// UNX-F3321 bmx 逐行守卫与唯一性全绿。
fn check_u3321_bmx_guard() -> bool {
    u3321bmx_scan() == 0 && u3321bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3321_checks() -> CheckSet {
    let mut set = CheckSet::new("U3321");
    set.add(
        "u3321-seg-guard",
        u3321_guard_seg(),
        if u3321_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3321-bmx-count",
        check_u3321_bmx_count(),
        if check_u3321_bmx_count() { "" } else { "UNX-F3321 bmx count mismatch" },
    );
    set.add(
        "u3321-bmx-sum",
        check_u3321_bmx_sum(),
        if check_u3321_bmx_sum() { "" } else { "UNX-F3321 bmx sum mismatch" },
    );
    set.add(
        "u3321-bmx-guard",
        check_u3321_bmx_guard(),
        if check_u3321_bmx_guard() { "" } else { "UNX-F3321 bmx guard mismatch" },
    );
    set
}

