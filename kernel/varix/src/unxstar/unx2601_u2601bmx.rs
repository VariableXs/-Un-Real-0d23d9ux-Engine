/// 段位守卫：全部诊断码必须落在本段 [0xa830, 0xa83f]。
pub const fn u2601_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2601Code::ALL.len() {
        let c = u2601Code::ALL[i].code();
        if c < 0xa830 || c > 0xa83f {
            ok = false;
        }
        i += 1;
    }
    ok
}

