/// 段位守卫：全部诊断码必须落在本段 [0xad20, 0xad2f]。
pub const fn u2741_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2741Code::ALL.len() {
        let c = u2741Code::ALL[i].code();
        if c < 0xad20 || c > 0xad2f {
            ok = false;
        }
        i += 1;
    }
    ok
}

