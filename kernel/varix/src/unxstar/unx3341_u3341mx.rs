pub fn run_u3341_checks() -> CheckSet {
    let mut set = CheckSet::new("U3341");
    set.add(
        "u3341-seg-guard",
        u3341_guard_seg(),
        if u3341_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3341-mx-count",
        check_u3341_mx_count(),
        if check_u3341_mx_count() { "" } else { "UNX-F3341 mx count mismatch" },
    );
    set.add(
        "u3341-mx-sum",
        check_u3341_mx_sum(),
        if check_u3341_mx_sum() { "" } else { "UNX-F3341 mx sum mismatch" },
    );
    set.add(
        "u3341-mx-guard",
        check_u3341_mx_guard(),
        if check_u3341_mx_guard() { "" } else { "UNX-F3341 mx guard mismatch" },
    );
    set
}

