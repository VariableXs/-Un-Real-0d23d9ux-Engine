/// 段位守卫：全部诊断码必须落在本段 [0xab10, 0xab1f]。
pub const fn u2681_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2681Code::ALL.len() {
        let c = u2681Code::ALL[i].code();
        if c < 0xab10 || c > 0xab1f {
            ok = false;
        }
        i += 1;
    }
    ok
}

