// --------------------------------------------------------------------------
// 诊断码（t301 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 页表域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t301Code {
    /// 0x3cb0 矩阵行重复。
    RowDup,
    /// 0x3cb1 矩阵断档。
    RowGap,
    /// 0x3cb2 行守卫破缺（逐行校验失败）。
    GuardBreak,
    /// 0x3cb3 矩阵累计漂移。
    SumDrift,
    /// 0x3cb4 索引错位。
    IndexMisaligned,
    /// 0x3cb5 矩阵账破缺。
    LedgerBreak,
    /// 0x3cb6 矩阵序断档。
    OrderBreak,
    /// 0x3cb7 守卫触发。
    GuardTripped,
    /// 0x3cb8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x3cb9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x3cba 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x3cbb 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x3cbc 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x3cbd 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

