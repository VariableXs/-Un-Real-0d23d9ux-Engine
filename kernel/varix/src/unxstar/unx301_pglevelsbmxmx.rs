/// 从键字符串解析序号：键形如 "GM" + 4 位零填充十进制，序号即深度值。
/// 解析成功 ⇔ 键落在 1024 键空间内；长度/前缀/非数字/越界任一破缺判 None。
fn parse_key_index(key: &str) -> Option<usize> {
    let b = key.as_bytes();
    if b.len() != 6 || b[0] != b'G' || b[1] != b'M' {
        return None;
    }
    let mut idx = 0usize;
    for &d in &b[2..6] {
        if !d.is_ascii_digit() {
            return None;
        }
        idx = idx * 10 + (d - b'0') as usize;
    }
    if idx < pg_matrixb_COUNT { Some(idx) } else { None }
}

/// O(1) 语义查找（解析序号直达表行；键空间闭集，未知键判 None）。
pub fn pg_matrixb_get(key: &str) -> Option<u64> {
    // 显式 let 绑定查找结果：先解析序号，再取表行值；解析已保证 i < 1024，越界不可达。
    let hit = parse_key_index(key).and_then(|i| {
        let row = pg_matrixb.get(i);
        row.map(|entry| entry.1)
    });
    hit
}

/// 逐行守卫扫描（返回违例行数；0 = 全绿）。
/// 守卫口径：行键可解析出序号 i、序号==行序号（严格递增无断档）且 行值==行序号。
pub fn pg_matrixb_scan() -> usize {
    let mut bad = 0usize;
    let mut i = 0usize;
    while i < pg_matrixb_COUNT {
        let (k, v) = pg_matrixb[i];
        let ok = match parse_key_index(k) {
            Some(idx) => idx == i && v == i as u64,
            None => false,
        };
        if !ok {
            bad += 1;
        }
        i += 1;
    }
    bad
}

/// 累计求和（守恒对账用）。
pub fn pg_matrixb_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < pg_matrixb_COUNT {
        s = s.wrapping_add(pg_matrixb[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn pg_matrixb_unique() -> bool {
    let mut i = 0usize;
    while i < pg_matrixb_COUNT {
        let mut j = i + 1;
        while j < pg_matrixb_COUNT {
            if pg_matrixb[i].0 == pg_matrixb[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

