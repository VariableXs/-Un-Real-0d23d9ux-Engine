pub const T301_SEG_BASE: u16 = 0x3cb0;

// --------------------------------------------------------------------------
// 诊断码（t301 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 页表域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t301Code {
    /// 0x3cb0 矩阵行重复。
    RowDup = 0x3cb0,
    /// 0x3cb1 矩阵断档。
    RowGap = 0x3cb1,
    /// 0x3cb2 行守卫破缺（逐行校验失败）。
    GuardBreak = 0x3cb2,
    /// 0x3cb3 矩阵累计漂移。
    SumDrift = 0x3cb3,
    /// 0x3cb4 索引错位。
    IndexMisaligned = 0x3cb4,
    /// 0x3cb5 矩阵账破缺。
    LedgerBreak = 0x3cb5,
    /// 0x3cb6 矩阵序断档。
    OrderBreak = 0x3cb6,
    /// 0x3cb7 守卫触发。
    GuardTripped = 0x3cb7,
    /// 0x3cb8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x3cb8,
    /// 0x3cb9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x3cb9,
    /// 0x3cba 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x3cba,
    /// 0x3cbb 条目重复（同键双写）。
    DuplicateEntry = 0x3cbb,
    /// 0x3cbc 次序违例（依赖序/时序破缺）。
    OrderViolated = 0x3cbc,
    /// 0x3cbd 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x3cbd,
}

impl t301Code {
    /// 全量闭集。
    pub const ALL: [t301Code; 14] = [
        t301Code::RowDup,
        t301Code::RowGap,
        t301Code::GuardBreak,
        t301Code::SumDrift,
        t301Code::IndexMisaligned,
        t301Code::LedgerBreak,
        t301Code::OrderBreak,
        t301Code::GuardTripped,
        t301Code::LedgerBroken,
        t301Code::SnapshotFingerprint,
        t301Code::TableBroken,
        t301Code::DuplicateEntry,
        t301Code::OrderViolated,
        t301Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值，0x3cb0..0x3cbd 连续且与声明序恒等；
    /// as 直达与原 14 臂 match 逐变体码值对拍全等，零分支零 panic 路径）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：14 臂派发单点归并于 code()，名称表序与 ALL/码值连续段恒等）。
    pub const fn name(self) -> &'static str {
        T301_NAMES[(self.code() - T301_SEG_BASE) as usize]
    }

    /// 可操作修复建议（每条诊断都必须带下一步动作；查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        T301_SUGGESTIONS[(self.code() - T301_SEG_BASE) as usize]
    }
}

