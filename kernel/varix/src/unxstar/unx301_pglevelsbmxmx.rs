/// 段位守卫：全部诊断码必须落在本段 [0x3cb0, 0x3cbf]。
pub const fn t301_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t301Code::ALL.len() {
        let c = t301Code::ALL[i].code();
        if c < 0x3cb0 || c > 0x3cbf {
            ok = false;
        }
        i += 1;
    }
    ok
}

