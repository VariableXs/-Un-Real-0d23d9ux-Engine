/// 段位守卫：全部诊断码落在本模块段内。
fn t301_guard_seg() -> bool {
    t301_segment_guard()
}

/// 表 pg_matrixb 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t301_pg_matrixb_guard() -> bool {
    let mut ok = pg_matrixb_COUNT == 1024;
    if ok {
        ok = pg_matrixb_scan() == 0;
    }
    if ok {
        ok = pg_matrixb_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t301_mxsum() -> bool {
    pg_matrixb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t301_checks() -> CheckSet {
    let mut set = CheckSet::new("T301");
    set.add(
        "t301-seg-guard",
        t301_guard_seg(),
        if t301_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t301-c1-mx-guard",
        check_t301_pg_matrixb_guard(),
        if check_t301_pg_matrixb_guard() { "" } else { "table pg_matrixb guard mismatch" },
    );
    set.add(
        "t301-c2-mx-sum",
        check_c2_t301_mxsum(),
        if check_c2_t301_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

