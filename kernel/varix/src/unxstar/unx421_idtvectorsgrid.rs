// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4280, 0x428f]。
pub const fn t421_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t421Code::ALL.len() {
        let c = t421Code::ALL[i].code();
        if c < 0x4280 || c > 0x428f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t421_guard_seg() -> bool {
    t421_segment_guard()
}

/// 大表 idt_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t421_grid() -> bool {
    let mut ok = idt_cell_COUNT == 1024;
    if ok {
        ok = idt_cell_get("IC0000") == Some(0) && idt_cell_get("IC1023") == Some(1023);
    }
    if ok {
        ok = idt_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t421_sum() -> bool {
    idt_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t421_checks() -> CheckSet {
    let mut set = CheckSet::new("T421");
    set.add(
        "t421-seg-guard",
        t421_guard_seg(),
        if t421_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t421-c1-grid",
        check_c1_t421_grid(),
        if check_c1_t421_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t421-c2-grid-sum",
        check_c2_t421_sum(),
        if check_c2_t421_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

