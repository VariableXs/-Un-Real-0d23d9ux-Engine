// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x3f80, 0x3f8f]。
pub const fn t341_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t341Code::ALL.len() {
        let c = t341Code::ALL[i].code();
        if c < 0x3f80 || c > 0x3f8f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t341_guard_seg() -> bool {
    t341_segment_guard()
}

/// 大表 mem_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t341_grid() -> bool {
    let mut ok = mem_cell_COUNT == 1024;
    if ok {
        ok = mem_cell_get("ME0000") == Some(0) && mem_cell_get("ME1023") == Some(1023);
    }
    if ok {
        ok = mem_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t341_sum() -> bool {
    mem_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t341_checks() -> CheckSet {
    let mut set = CheckSet::new("T341");
    set.add(
        "t341-seg-guard",
        t341_guard_seg(),
        if t341_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t341-c1-grid",
        check_c1_t341_grid(),
        if check_c1_t341_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t341-c2-grid-sum",
        check_c2_t341_sum(),
        if check_c2_t341_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

