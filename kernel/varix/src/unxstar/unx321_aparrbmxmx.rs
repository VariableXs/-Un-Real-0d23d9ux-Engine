/// 段位守卫：全部诊断码必须落在本段 [0x3eb0, 0x3ebf]。
pub const fn t321_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t321Code::ALL.len() {
        let c = t321Code::ALL[i].code();
        if c < 0x3eb0 || c > 0x3ebf {
            ok = false;
        }
        i += 1;
    }
    ok
}

