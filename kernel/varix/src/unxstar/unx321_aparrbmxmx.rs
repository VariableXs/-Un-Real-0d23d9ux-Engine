/// 段位守卫：全部诊断码落在本模块段内。
fn t321_guard_seg() -> bool {
    t321_segment_guard()
}

/// 表 ap_matrixb 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t321_ap_matrixb_guard() -> bool {
    let mut ok = ap_matrixb_COUNT == 256;
    if ok {
        ok = ap_matrixb_scan() == 0;
    }
    if ok {
        ok = ap_matrixb_unique();
    }
    ok
}

/// 矩阵累计守恒（1..256 = 32640）。
fn check_c2_t321_mxsum() -> bool {
    ap_matrixb_sum() == 32640
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t321_checks() -> CheckSet {
    let mut set = CheckSet::new("T321");
    set.add(
        "t321-seg-guard",
        t321_guard_seg(),
        if t321_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t321-c1-mx-guard",
        check_t321_ap_matrixb_guard(),
        if check_t321_ap_matrixb_guard() { "" } else { "table ap_matrixb guard mismatch" },
    );
    set.add(
        "t321-c2-mx-sum",
        check_c2_t321_mxsum(),
        if check_c2_t321_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

