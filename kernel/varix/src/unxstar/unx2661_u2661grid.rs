/// UNX-F2661 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u2661_grid_count() -> bool {
    let mut ok = u2661grid_COUNT == 1024;
    if ok { ok = u2661grid_get("PC0000") == Some(0) && u2661grid_get("FO1023") == Some(10); }
    if ok { ok = u2661grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2661 grid 累计守恒（理论值 49061）。
fn check_u2661_grid_sum() -> bool {
    u2661grid_sum() == 49061
}

/// UNX-F2661 grid 逐行守卫与唯一性全绿。
fn check_u2661_grid_guard() -> bool {
    u2661grid_scan() == 0 && u2661grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2661_checks() -> CheckSet {
    let mut set = CheckSet::new("U2661");
    set.add(
        "u2661-seg-guard",
        u2661_guard_seg(),
        if u2661_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2661-grid-count",
        check_u2661_grid_count(),
        if check_u2661_grid_count() { "" } else { "UNX-F2661 grid count mismatch" },
    );
    set.add(
        "u2661-grid-sum",
        check_u2661_grid_sum(),
        if check_u2661_grid_sum() { "" } else { "UNX-F2661 grid sum mismatch" },
    );
    set.add(
        "u2661-grid-guard",
        check_u2661_grid_guard(),
        if check_u2661_grid_guard() { "" } else { "UNX-F2661 grid guard mismatch" },
    );
    set
}

