/// UNX-F3521 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u3521_mx_count() -> bool {
    let mut ok = u3521mx_COUNT == 512;
    if ok { ok = u3521mx_get("PROBE0000") == Some(0) && u3521mx_get("BUD0511") == Some(47); }
    if ok { ok = u3521mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3521 mx 累计守恒（理论值 24448）。
fn check_u3521_mx_sum() -> bool {
    u3521mx_sum() == 24448
}

/// UNX-F3521 mx 逐行守卫与唯一性全绿。
fn check_u3521_mx_guard() -> bool {
    u3521mx_scan() == 0 && u3521mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3521_checks() -> CheckSet {
    let mut set = CheckSet::new("U3521");
    set.add(
        "u3521-seg-guard",
        u3521_guard_seg(),
        if u3521_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3521-mx-count",
        check_u3521_mx_count(),
        if check_u3521_mx_count() { "" } else { "UNX-F3521 mx count mismatch" },
    );
    set.add(
        "u3521-mx-sum",
        check_u3521_mx_sum(),
        if check_u3521_mx_sum() { "" } else { "UNX-F3521 mx sum mismatch" },
    );
    set.add(
        "u3521-mx-guard",
        check_u3521_mx_guard(),
        if check_u3521_mx_guard() { "" } else { "UNX-F3521 mx guard mismatch" },
    );
    set
}

