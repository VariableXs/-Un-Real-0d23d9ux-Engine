// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4690, 0x469f]。
pub const fn t571_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t571Code::ALL.len() {
        let c = t571Code::ALL[i].code();
        if c < 0x4690 || c > 0x469f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t571_guard_seg() -> bool {
    t571_segment_guard()
}

/// 表 uart_matrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t571_uart_matrix_guard() -> bool {
    let mut ok = uart_matrix_COUNT == 1024;
    if ok {
        ok = uart_matrix_scan() == 0;
    }
    if ok {
        ok = uart_matrix_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t571_mxsum() -> bool {
    uart_matrix_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t571_checks() -> CheckSet {
    let mut set = CheckSet::new("T571");
    set.add(
        "t571-seg-guard",
        t571_guard_seg(),
        if t571_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t571-c1-mx-guard",
        check_t571_uart_matrix_guard(),
        if check_t571_uart_matrix_guard() { "" } else { "table uart_matrix guard mismatch" },
    );
    set.add(
        "t571-c2-mx-sum",
        check_c2_t571_mxsum(),
        if check_c2_t571_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

