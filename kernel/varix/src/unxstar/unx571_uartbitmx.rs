// --------------------------------------------------------------------------
// 诊断码（t571 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 串口域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t571Code {
    /// 0x4690 矩阵行重复。
    RowDup,
    /// 0x4691 矩阵断档。
    RowGap,
    /// 0x4692 行守卫破缺（逐行校验失败）。
    GuardBreak,
    /// 0x4693 矩阵累计漂移。
    SumDrift,
    /// 0x4694 索引错位。
    IndexMisaligned,
    /// 0x4695 矩阵账破缺。
    LedgerBreak,
    /// 0x4696 矩阵序断档。
    OrderBreak,
    /// 0x4697 守卫触发。
    GuardTripped,
    /// 0x4698 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4699 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x469a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x469b 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x469c 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x469d 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

