/// 段位守卫：全部诊断码必须落在本段 [0x4a80, 0x4a8f]。
pub const fn tb01_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < tb01Code::ALL.len() {
        let c = tb01Code::ALL[i].code();
        if c < 0x4a80 || c > 0x4a8f {
            ok = false;
        }
        i += 1;
    }
    ok
}

