/// 模块版本。
pub const TB01_VERSION: &str = "tb01-cmdlinegrid-v1";

/// 诊断段基址。
pub const TB01_SEG_BASE: u16 = 0x4a80;

// --------------------------------------------------------------------------
// 诊断码（tb01 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 参数行域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum tb01Code {
    /// 0x4a80 单元格重复（同键双占）。
    CellDup,
    /// 0x4a81 单元格断档（序号不连续）。
    CellGap,
    /// 0x4a82 索引越界（≥1024）。
    IndexOob,
    /// 0x4a83 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x4a84 表序断档。
    OrderBreak,
    /// 0x4a85 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0x4a86 掩码非法。
    MaskBad,
    /// 0x4a87 守卫触发。
    GuardTripped,
    /// 0x4a88 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4a89 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x4a8a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x4a8b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x4a8c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x4a8d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x4a8e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

