fn check_c1_tb01_grid() -> bool {
    let mut ok = cmd_cell_COUNT == 1024;
    if ok {
        ok = cmd_cell_get("MC0000") == Some(0) && cmd_cell_get("MC1023") == Some(1023);
    }
    if ok {
        ok = cmd_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_tb01_sum() -> bool {
    cmd_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_tb01_checks() -> CheckSet {
    let mut set = CheckSet::new("TB01");
    set.add(
        "tb01-seg-guard",
        tb01_guard_seg(),
        if tb01_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "tb01-c1-grid",
        check_c1_tb01_grid(),
        if check_c1_tb01_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "tb01-c2-grid-sum",
        check_c2_tb01_sum(),
        if check_c2_tb01_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

