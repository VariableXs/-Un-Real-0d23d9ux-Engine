/// U1881_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1881Code {
    /// 0x6020 单元格重复（矩阵缺位 同键双占）。
    CellDup = 0x6020,
    /// 0x6021 单元格断档（对账破缺 序号不连续）。
    CellGap = 0x6021,
    /// 0x6022 索引越界（覆盖空洞）。
    IndexOob = 0x6022,
    /// 0x6023 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x6023,
    /// 0x6024 表序断档。
    OrderBreak = 0x6024,
    /// 0x6025 累计漂移（求和≠理论值）。
    SumDrift = 0x6025,
    /// 0x6026 掩码非法。
    MaskBad = 0x6026,
    /// 0x6027 守卫触发。
    GuardTripped = 0x6027,
    /// 0x6028 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x6028,
    /// 0x6029 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x6029,
    /// 0x602a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x602a,
    /// 0x602b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x602b,
}

