/// 段位守卫：全部诊断码必须落在本段 [0x5950, 0x595f]。
pub const fn u1701_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1701Code::ALL.len() {
        let c = u1701Code::ALL[i].code();
        if c < 0x5950 || c > 0x595f {
            ok = false;
        }
        i += 1;
    }
    ok
}

