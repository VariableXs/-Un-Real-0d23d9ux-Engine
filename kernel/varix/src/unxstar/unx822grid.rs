/// 段位守卫：全部诊断码落在本模块段内。
fn t822_guard_seg() -> bool {
    t822_segment_guard()
}

/// 大表 unx822grid 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t822_grid() -> bool {
    let mut ok = unx822grid_COUNT == 1024;
    if ok {
        ok = unx822grid_get("8220000") == Some(0) && unx822grid_get("8221023") == Some(1023);
    }
    if ok {
        ok = unx822grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t822_sum() -> bool {
    unx822grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t822_checks() -> CheckSet {
    let mut set = CheckSet::new("T822");
    set.add(
        "t822-seg-guard",
        t822_guard_seg(),
        if t822_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t822-c1-grid",
        check_c1_t822_grid(),
        if check_c1_t822_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t822-c2-grid-sum",
        check_c2_t822_sum(),
        if check_c2_t822_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

