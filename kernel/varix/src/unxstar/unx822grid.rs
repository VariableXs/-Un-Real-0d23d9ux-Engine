/// 段位守卫：全部诊断码必须落在本段 [0x5100, 0x510f]。
pub const fn t822_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t822Code::ALL.len() {
        let c = t822Code::ALL[i].code();
        if c < 0x5100 || c > 0x510f {
            ok = false;
        }
        i += 1;
    }
    ok
}

