/// 段位守卫：全部诊断码必须落在本段 [0x5590, 0x559f]。
pub const fn u1601_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1601Code::ALL.len() {
        let c = u1601Code::ALL[i].code();
        if c < 0x5590 || c > 0x559f {
            ok = false;
        }
        i += 1;
    }
    ok
}

