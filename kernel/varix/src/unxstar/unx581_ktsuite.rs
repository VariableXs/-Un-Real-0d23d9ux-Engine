// --------------------------------------------------------------------------
// 诊断码（t581 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 套件注册诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t581Code {
    /// 0x4700 套件非法（八套件之外）。
    SuiteBad,
    /// 0x4701 断言号越界（≥100/套件）。
    AssertOob,
    /// 0x4702 套件断档。
    SuiteGap,
    /// 0x4703 重复注册。
    DupRegister,
    /// 0x4704 注册账破缺。
    LedgerBreak,
    /// 0x4705 注册序断档。
    OrderBreak,
    /// 0x4706 运行态非法。
    RunBad,
    /// 0x4707 守卫触发。
    GuardTripped,
    /// 0x4708 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4709 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x470a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x470b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x470c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x470d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x470e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

