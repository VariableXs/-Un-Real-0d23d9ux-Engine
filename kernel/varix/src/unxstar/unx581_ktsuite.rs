/// 段位守卫：全部诊断码落在本模块段内。
fn t581_guard_seg() -> bool {
    t581_segment_guard()
}

/// 表 ktsuite 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t581_ktsuite_guard() -> bool {
    let mut ok = ktsuite_COUNT == 600;
    if ok {
        ok = ktsuite_scan() == 0;
    }
    if ok {
        ok = ktsuite_unique();
    }
    ok
}

/// 注册表求和（1..800 = 320400）。
fn check_c2_suite_sum() -> bool {
    let mut ok = ktsuite_sum() == 180300;
    if ok {
        ok = ktsuite_get("B19_000") == Some(1) && ktsuite_get("B24_099") == Some(600);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t581_checks() -> CheckSet {
    let mut set = CheckSet::new("T581");
    set.add(
        "t581-seg-guard",
        t581_guard_seg(),
        if t581_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t581-c1-suite-guard",
        check_t581_ktsuite_guard(),
        if check_t581_ktsuite_guard() { "" } else { "table ktsuite guard mismatch" },
    );
    set.add(
        "t581-c2-suite-sum",
        check_c2_suite_sum(),
        if check_c2_suite_sum() { "" } else { "suite registry sum mismatch" },
    );
    set
}

