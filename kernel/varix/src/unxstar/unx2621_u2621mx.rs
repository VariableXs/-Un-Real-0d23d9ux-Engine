// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u2621_guard_seg() -> bool {
    u2621_segment_guard()
}

/// UNX-F2621 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u2621_mx_count() -> bool {
    let mut ok = u2621mx_COUNT == 512;
    if ok { ok = u2621mx_get("CR0000") == Some(0) && u2621mx_get("CN0511") == Some(47); }
    if ok { ok = u2621mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2621 mx 累计守恒（理论值 24448）。
fn check_u2621_mx_sum() -> bool {
    u2621mx_sum() == 24448
}

/// UNX-F2621 mx 逐行守卫与唯一性全绿。
fn check_u2621_mx_guard() -> bool {
    u2621mx_scan() == 0 && u2621mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2621_checks() -> CheckSet {
    let mut set = CheckSet::new("U2621");
    set.add(
        "u2621-seg-guard",
        u2621_guard_seg(),
        if u2621_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2621-mx-count",
        check_u2621_mx_count(),
        if check_u2621_mx_count() { "" } else { "UNX-F2621 mx count mismatch" },
    );
    set.add(
        "u2621-mx-sum",
        check_u2621_mx_sum(),
        if check_u2621_mx_sum() { "" } else { "UNX-F2621 mx sum mismatch" },
    );
    set.add(
        "u2621-mx-guard",
        check_u2621_mx_guard(),
        if check_u2621_mx_guard() { "" } else { "UNX-F2621 mx guard mismatch" },
    );
    set
}

