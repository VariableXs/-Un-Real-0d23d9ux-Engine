/// 段位守卫：全部诊断码必须落在本段 [0xa8d0, 0xa8df]。
pub const fn u2621_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2621Code::ALL.len() {
        let c = u2621Code::ALL[i].code();
        if c < 0xa8d0 || c > 0xa8df {
            ok = false;
        }
        i += 1;
    }
    ok
}

