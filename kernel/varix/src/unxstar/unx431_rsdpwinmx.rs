/// 段位守卫：全部诊断码必须落在本段 [0x4390, 0x439f]。
pub const fn t431_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t431Code::ALL.len() {
        let c = t431Code::ALL[i].code();
        if c < 0x4390 || c > 0x439f {
            ok = false;
        }
        i += 1;
    }
    ok
}

