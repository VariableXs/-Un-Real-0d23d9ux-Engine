// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t431_guard_seg() -> bool {
    t431_segment_guard()
}

/// 表 rsdp_matrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t431_rsdp_matrix_guard() -> bool {
    let mut ok = rsdp_matrix_COUNT == 1024;
    if ok {
        ok = rsdp_matrix_scan() == 0;
    }
    if ok {
        ok = rsdp_matrix_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t431_mxsum() -> bool {
    rsdp_matrix_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t431_checks() -> CheckSet {
    let mut set = CheckSet::new("T431");
    set.add(
        "t431-seg-guard",
        t431_guard_seg(),
        if t431_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t431-c1-mx-guard",
        check_t431_rsdp_matrix_guard(),
        if check_t431_rsdp_matrix_guard() { "" } else { "table rsdp_matrix guard mismatch" },
    );
    set.add(
        "t431-c2-mx-sum",
        check_c2_t431_mxsum(),
        if check_c2_t431_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

