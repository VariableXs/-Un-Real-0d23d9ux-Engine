/// 键→行号解析：「IX」前缀 + 恰 4 位 ASCII 十进制（定宽无前导歧义），越出表界判 None。
/// 等价性依据（全量实测）：1024 行键恒为 IX%04d(行号)、值恒等于行号，
/// 故解析序号与原 1024 臂全枚举 match 一一对应；非法键一律 None。
fn idt_matrixb_key_index(key: &str) -> Option<usize> {
    let b = key.as_bytes();
    if b.len() != 6 || b[0] != b'I' || b[1] != b'X' {
        return None;
    }
    let mut i = 0usize;
    let mut d = 0usize;
    while d < 4 {
        let c = b[2 + d];
        if !matches!(c, b'0'..=b'9') {
            return None;
        }
        i = i * 10 + (c - b'0') as usize;
        d += 1;
    }
    if i < idt_matrixb_COUNT { Some(i) } else { None }
}

/// 语义查找：键解析为行号 i，返回表内第 i 行值（与原全枚举 match 语义等价）。
pub fn idt_matrixb_get(key: &str) -> Option<u64> {
    // 显式 let 绑定查找结果：先解析序号，再经 .get 限幅取表行值；
    // key_index 已保证 i < 1024（表定长），越界不可达，无 panic 路径。
    let hit = idt_matrixb_key_index(key).and_then(|i| {
        let row = idt_matrixb.get(i);
        row.map(|entry| entry.1)
    });
    hit
}

/// 逐行守卫扫描（返回违例行数；0 = 全绿）。
/// 守卫口径：行值 == 键解析序号（判据唯一入口 key_index）。
pub fn idt_matrixb_scan() -> usize {
    let mut bad = 0usize;
    let mut i = 0usize;
    while i < idt_matrixb_COUNT {
        let (k, v) = idt_matrixb[i];
        // 单行判据内联（与原 row_guard 语义逐字等价）：行值 == 键解析序号，
        // 无法定位序号的键一律判红；共享私有 key_index 即唯一判据入口。
        let ok = match idt_matrixb_key_index(k) {
            Some(idx) => v == idx as u64,
            None => false,
        };
        if !ok {
            bad += 1;
        }
        i += 1;
    }
    bad
}

/// 累计求和（守恒对账用）。
pub fn idt_matrixb_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < idt_matrixb_COUNT {
        s = s.wrapping_add(idt_matrixb[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn idt_matrixb_unique() -> bool {
    let mut i = 0usize;
    while i < idt_matrixb_COUNT {
        let mut j = i + 1;
        while j < idt_matrixb_COUNT {
            if idt_matrixb[i].0 == idt_matrixb[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

