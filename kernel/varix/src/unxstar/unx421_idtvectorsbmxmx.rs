/// 段位守卫：全部诊断码落在本模块段内。
fn t421_guard_seg() -> bool {
    t421_segment_guard()
}

/// 表 idt_matrixb 逐行守卫全绿（行数/守卫/唯一性）。
/// 卫语句化简：任一判据失败即刻判红返回，避免嵌套条件链。
fn check_t421_idt_matrixb_guard() -> bool {
    // 卫语句一：行数恒等判据（表体行数必须恰为 1024）。
    if idt_matrixb_COUNT != 1024 {
        return false;
    }
    // 卫语句二：逐行守卫扫描（违例行数必须为 0）。
    if idt_matrixb_scan() != 0 {
        return false;
    }
    // 终判：键唯一性（同键双写判红）。
    idt_matrixb_unique()
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_t421_mxsum() -> bool {
    idt_matrixb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
/// 判据函数均为纯函数：先求值一次再写入结果与 detail，消除重复求值。
pub fn run_t421_checks() -> CheckSet {
    let mut set = CheckSet::new("T421");
    // 检查一：段位守卫（全部诊断码落在本模块段内）。
    let seg_ok = t421_guard_seg();
    set.add(
        "t421-seg-guard",
        seg_ok,
        if seg_ok { "" } else { "diagnostic code outside segment" },
    );
    // 检查二：表逐行守卫全绿（行数/守卫/唯一性三判据）。
    let guard_ok = check_t421_idt_matrixb_guard();
    set.add(
        "t421-c1-mx-guard",
        guard_ok,
        if guard_ok { "" } else { "table idt_matrixb guard mismatch" },
    );
    // 检查三：矩阵累计守恒（1..1024 = 523776）。
    let sum_ok = check_c2_t421_mxsum();
    set.add(
        "t421-c2-mx-sum",
        sum_ok,
        if sum_ok { "" } else { "matrix sum mismatch" },
    );
    set
}

