/// 段位守卫：全部诊断码必须落在本段 [0x42b0, 0x42bf]。
pub const fn t421_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t421Code::ALL.len() {
        let c = t421Code::ALL[i].code();
        if c < 0x42b0 || c > 0x42bf {
            ok = false;
        }
        i += 1;
    }
    ok
}

