// --------------------------------------------------------------------------
// 诊断码（t421 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// IDT 域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t421Code {
    /// 0x42b0 矩阵行重复。
    RowDup = 0x42b0,
    /// 0x42b1 矩阵断档。
    RowGap = 0x42b1,
    /// 0x42b2 行守卫破缺（逐行校验失败）。
    GuardBreak = 0x42b2,
    /// 0x42b3 矩阵累计漂移。
    SumDrift = 0x42b3,
    /// 0x42b4 索引错位。
    IndexMisaligned = 0x42b4,
    /// 0x42b5 矩阵账破缺。
    LedgerBreak = 0x42b5,
    /// 0x42b6 矩阵序断档。
    OrderBreak = 0x42b6,
    /// 0x42b7 守卫触发。
    GuardTripped = 0x42b7,
    /// 0x42b8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x42b8,
    /// 0x42b9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x42b9,
    /// 0x42ba 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x42ba,
    /// 0x42bb 条目重复（同键双写）。
    DuplicateEntry = 0x42bb,
    /// 0x42bc 次序违例（依赖序/时序破缺）。
    OrderViolated = 0x42bc,
    /// 0x42bd 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x42bd,
}

impl t421Code {
    /// 全量闭集。
    pub const ALL: [t421Code; 14] = [
        t421Code::RowDup,
        t421Code::RowGap,
        t421Code::GuardBreak,
        t421Code::SumDrift,
        t421Code::IndexMisaligned,
        t421Code::LedgerBreak,
        t421Code::OrderBreak,
        t421Code::GuardTripped,
        t421Code::LedgerBroken,
        t421Code::SnapshotFingerprint,
        t421Code::TableBroken,
        t421Code::DuplicateEntry,
        t421Code::OrderViolated,
        t421Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值，0x42b0..0x42bd 连续且与声明序恒等；
    /// as 直达与原 14 臂 match 逐变体码值对拍全等，零分支零 panic 路径）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：14 臂派发单点归并于 code()，名称表序与 ALL/码值连续段恒等）。
    pub const fn name(self) -> &'static str {
        T421_NAMES[(self.code() - T421_SEG_BASE) as usize]
    }

    /// 可操作修复建议（每条诊断都必须带下一步动作；查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        T421_SUGGESTIONS[(self.code() - T421_SEG_BASE) as usize]
    }
}

