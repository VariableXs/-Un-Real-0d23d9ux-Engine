// --------------------------------------------------------------------------
// 诊断码（tb01 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 参数行域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum tb01Code {
    /// 0x4a90 矩阵行重复。
    RowDup,
    /// 0x4a91 矩阵断档。
    RowGap,
    /// 0x4a92 行守卫破缺（逐行校验失败）。
    GuardBreak,
    /// 0x4a93 矩阵累计漂移。
    SumDrift,
    /// 0x4a94 索引错位。
    IndexMisaligned,
    /// 0x4a95 矩阵账破缺。
    LedgerBreak,
    /// 0x4a96 矩阵序断档。
    OrderBreak,
    /// 0x4a97 守卫触发。
    GuardTripped,
    /// 0x4a98 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4a99 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x4a9a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x4a9b 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x4a9c 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x4a9d 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

