// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4a90, 0x4a9f]。
pub const fn tb01_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < tb01Code::ALL.len() {
        let c = tb01Code::ALL[i].code();
        if c < 0x4a90 || c > 0x4a9f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn tb01_guard_seg() -> bool {
    tb01_segment_guard()
}

/// 表 cmd_matrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_tb01_cmd_matrix_guard() -> bool {
    let mut ok = cmd_matrix_COUNT == 1024;
    if ok {
        ok = cmd_matrix_scan() == 0;
    }
    if ok {
        ok = cmd_matrix_unique();
    }
    ok
}

/// 矩阵累计守恒（1..1024 = 523776）。
fn check_c2_tb01_mxsum() -> bool {
    cmd_matrix_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_tb01_checks() -> CheckSet {
    let mut set = CheckSet::new("TB01");
    set.add(
        "tb01-seg-guard",
        tb01_guard_seg(),
        if tb01_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "tb01-c1-mx-guard",
        check_tb01_cmd_matrix_guard(),
        if check_tb01_cmd_matrix_guard() { "" } else { "table cmd_matrix guard mismatch" },
    );
    set.add(
        "tb01-c2-mx-sum",
        check_c2_tb01_mxsum(),
        if check_c2_tb01_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

