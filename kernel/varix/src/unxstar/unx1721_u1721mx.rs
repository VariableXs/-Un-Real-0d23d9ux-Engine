/// 段位守卫：全部诊断码必须落在本段 [0x5a10, 0x5a1f]。
pub const fn u1721_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1721Code::ALL.len() {
        let c = u1721Code::ALL[i].code();
        if c < 0x5a10 || c > 0x5a1f {
            ok = false;
        }
        i += 1;
    }
    ok
}

