/// 段位守卫：全部诊断码必须落在本段 [0xa520, 0xa52f]。
pub const fn u2521_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2521Code::ALL.len() {
        let c = u2521Code::ALL[i].code();
        if c < 0xa520 || c > 0xa52f {
            ok = false;
        }
        i += 1;
    }
    ok
}

