/// 段位守卫：全部诊断码落在本模块段内。
fn u2521_guard_seg() -> bool {
    u2521_segment_guard()
}

/// UNX-F2521 bgrid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u2521_bgrid_count() -> bool {
    let mut ok = u2521bgrid_COUNT == 1024;
    if ok { ok = u2521bgrid_get("FI0000") == Some(0) && u2521bgrid_get("HP1023") == Some(41); }
    if ok { ok = u2521bgrid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2521 bgrid 累计守恒（理论值 44933）。
fn check_u2521_bgrid_sum() -> bool {
    u2521bgrid_sum() == 44933
}

/// UNX-F2521 bgrid 逐行守卫与唯一性全绿。
fn check_u2521_bgrid_guard() -> bool {
    u2521bgrid_scan() == 0 && u2521bgrid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2521_checks() -> CheckSet {
    let mut set = CheckSet::new("U2521");
    set.add(
        "u2521-seg-guard",
        u2521_guard_seg(),
        if u2521_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2521-bgrid-count",
        check_u2521_bgrid_count(),
        if check_u2521_bgrid_count() { "" } else { "UNX-F2521 bgrid count mismatch" },
    );
    set.add(
        "u2521-bgrid-sum",
        check_u2521_bgrid_sum(),
        if check_u2521_bgrid_sum() { "" } else { "UNX-F2521 bgrid sum mismatch" },
    );
    set.add(
        "u2521-bgrid-guard",
        check_u2521_bgrid_guard(),
        if check_u2521_bgrid_guard() { "" } else { "UNX-F2521 bgrid guard mismatch" },
    );
    set
}

