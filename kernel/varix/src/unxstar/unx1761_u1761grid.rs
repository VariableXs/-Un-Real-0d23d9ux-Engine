/// U1761_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1761Code {
    /// 0x5b80 单元格重复（职责越界 同键双占）。
    CellDup = 0x5b80,
    /// 0x5b81 单元格断档（汇聚漏登 序号不连续）。
    CellGap = 0x5b81,
    /// 0x5b82 索引越界（层间穿透）。
    IndexOob = 0x5b82,
    /// 0x5b83 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5b83,
    /// 0x5b84 表序断档。
    OrderBreak = 0x5b84,
    /// 0x5b85 累计漂移（求和≠理论值）。
    SumDrift = 0x5b85,
    /// 0x5b86 掩码非法。
    MaskBad = 0x5b86,
    /// 0x5b87 守卫触发。
    GuardTripped = 0x5b87,
    /// 0x5b88 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5b88,
    /// 0x5b89 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5b89,
    /// 0x5b8a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5b8a,
    /// 0x5b8b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5b8b,
}

