/// 键末四位解析为行序号（越界/非数字一律拒收）。
/// 键形如「语义前缀 + 1023 补零行序」，前缀长度不固定，故只取末四位。
const fn u1761grid_key_index(key: &str) -> Option<usize> {
    let bytes = key.as_bytes();
    let len = bytes.len();
    if len < 4 {
        return None;
    }
    let mut idx = 0usize;
    let mut i = len - 4;
    while i < len {
        let d = bytes[i];
        if d < b'0' || d > b'9' {
            return None;
        }
        idx = idx * 10 + (d - b'0') as usize;
        i += 1;
    }
    if idx < u1761grid_COUNT { Some(idx) } else { None }
}

