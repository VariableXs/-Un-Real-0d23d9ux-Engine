/// 段位守卫：全部诊断码必须落在本段 [0x5650, 0x565f]。
pub const fn u1621_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1621Code::ALL.len() {
        let c = u1621Code::ALL[i].code();
        if c < 0x5650 || c > 0x565f {
            ok = false;
        }
        i += 1;
    }
    ok
}

