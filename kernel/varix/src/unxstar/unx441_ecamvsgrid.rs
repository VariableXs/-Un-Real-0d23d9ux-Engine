/// 线性查找（键唯一性由构造期断言保证，运行时无分支歧义）。
pub fn cfg_cell_get(key: &'static str) -> Option<u64> {
    let mut i = 0usize;
    while i < cfg_cell_COUNT {
        if cfg_cell[i].0 == key {
            return Some(cfg_cell[i].1);
        }
        i += 1;
    }
    None
}

/// 累计求和（用于守恒对账）。
pub fn cfg_cell_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < cfg_cell_COUNT {
        s = s.wrapping_add(cfg_cell[i].1 as u64);
        i += 1;
    }
    s
}

