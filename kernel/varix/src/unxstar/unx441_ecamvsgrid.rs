// --------------------------------------------------------------------------
// 诊断码（t441 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 配置域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t441Code {
    /// 0x4480 单元格重复（同键双占）。
    CellDup,
    /// 0x4481 单元格断档（序号不连续）。
    CellGap,
    /// 0x4482 索引越界（≥1024）。
    IndexOob,
    /// 0x4483 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x4484 表序断档。
    OrderBreak,
    /// 0x4485 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0x4486 掩码非法。
    MaskBad,
    /// 0x4487 守卫触发。
    GuardTripped,
    /// 0x4488 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4489 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x448a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x448b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x448c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x448d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x448e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

