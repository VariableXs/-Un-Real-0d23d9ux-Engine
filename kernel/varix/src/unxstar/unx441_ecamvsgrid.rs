// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4480, 0x448f]。
pub const fn t441_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t441Code::ALL.len() {
        let c = t441Code::ALL[i].code();
        if c < 0x4480 || c > 0x448f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t441_guard_seg() -> bool {
    t441_segment_guard()
}

/// 大表 cfg_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t441_grid() -> bool {
    let mut ok = cfg_cell_COUNT == 1024;
    if ok {
        ok = cfg_cell_get("CC0000") == Some(0) && cfg_cell_get("CC1023") == Some(1023);
    }
    if ok {
        ok = cfg_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t441_sum() -> bool {
    cfg_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t441_checks() -> CheckSet {
    let mut set = CheckSet::new("T441");
    set.add(
        "t441-seg-guard",
        t441_guard_seg(),
        if t441_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t441-c1-grid",
        check_c1_t441_grid(),
        if check_c1_t441_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t441-c2-grid-sum",
        check_c2_t441_sum(),
        if check_c2_t441_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

