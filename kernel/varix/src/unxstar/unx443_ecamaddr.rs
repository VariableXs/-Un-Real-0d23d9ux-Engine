// ---------------------------------------------------------------------------
// ECAM 编址引擎（PCIe：基址页对齐 + BDF 偏移 = (bus<<20 | dev<<15 | fn<<12)）
// ---------------------------------------------------------------------------

/// ECAM 每总线 1MB。
pub const ECAM_BUS_SIZE: u64 = 0x10_0000;

/// ECAM 每设备 32KB。
pub const ECAM_DEV_SIZE: u64 = 0x8000;

/// ECAM 每功能 4KB（256 个 reg × 4 字节）。
pub const ECAM_FN_SIZE: u64 = 0x1000;

/// ECAM 总大小（256 总线）。
pub const ECAM_TOTAL: u64 = ECAM_BUS_SIZE * 256;

/// ECAM 偏移编址（BDF → 段内偏移）。
pub const fn ecam_offset(bus: u32, dev: u32, func: u32) -> Option<u64> {
    if bus >= 256 || dev >= 32 || func >= 8 {
        return None;
    }
    Some((bus as u64) * ECAM_BUS_SIZE + (dev as u64) * ECAM_DEV_SIZE + (func as u64) * ECAM_FN_SIZE)
}

/// ECAM 绝对地址（基址 + 偏移 + 寄存器偏移；基址必须页对齐）。
pub const fn ecam_addr(base: u64, bus: u32, dev: u32, func: u32, reg: u32) -> Option<u64> {
    if base % 4096 != 0 || reg >= 4096 {
        return None;
    }
    match ecam_offset(bus, dev, func) {
        Some(off) => {
            let a = base + off + (reg as u64) * 4;
            if a >= base + ECAM_TOTAL {
                None
            } else {
                Some(a)
            }
        }
        None => None,
    }
}

/// 编址与 CF8 同源对拍（BDF 三参数域合法性：两机制共享同一 BDF 域）。
pub const fn ecam_cf8_same_bdf(bus: u32, dev: u32, func: u32) -> bool {
    ecam_offset(bus, dev, func).is_some() == (bus < 256 && dev < 32 && func < 8)
}

