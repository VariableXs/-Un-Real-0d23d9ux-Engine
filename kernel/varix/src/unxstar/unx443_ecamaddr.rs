/// 段位守卫：全部诊断码必须落在本段 [0x4420, 0x442f]。
pub const fn t443_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t443Code::ALL.len() {
        let c = t443Code::ALL[i].code();
        if c < 0x4420 || c > 0x442f {
            ok = false;
        }
        i += 1;
    }
    ok
}

