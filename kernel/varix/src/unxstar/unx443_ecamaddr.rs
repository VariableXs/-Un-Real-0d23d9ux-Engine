/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn ecamoff_unique() -> bool {
    let mut i = 0usize;
    while i < ecamoff_COUNT {
        let mut j = i + 1;
        while j < ecamoff_COUNT {
            if ecamoff[i].0 == ecamoff[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

