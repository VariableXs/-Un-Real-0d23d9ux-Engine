/// 段位守卫：全部诊断码落在本模块段内。
fn t443_guard_seg() -> bool {
    t443_segment_guard()
}

/// 表 ecamoff 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t443_ecamoff_guard() -> bool {
    let mut ok = ecamoff_COUNT == 256;
    if ok {
        ok = ecamoff_scan() == 0;
    }
    if ok {
        ok = ecamoff_unique();
    }
    ok
}

/// ECAM 编址往返 + 基址对齐守卫 + 与 CF8 同源。
fn check_c2_ecam_codec() -> bool {
    let mut ok = ecam_addr(0xE000_0000, 0, 0, 0, 0) == Some(0xE000_0000);
    if ok {
        ok = ecam_addr(0xE000_0000, 255, 31, 7, 0).is_some();
    }
    if ok {
        ok = ecam_addr(0xE000_0001, 0, 0, 0, 0).is_none();
    }
    if ok {
        ok = ecam_offset(256, 0, 0).is_none() && ecam_offset(0, 32, 0).is_none();
    }
    if ok {
        ok = ecam_cf8_same_bdf(0, 0, 0) && ecam_cf8_same_bdf(255, 31, 7);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t443_checks() -> CheckSet {
    let mut set = CheckSet::new("T443");
    set.add(
        "t443-seg-guard",
        t443_guard_seg(),
        if t443_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t443-c1-off-guard",
        check_t443_ecamoff_guard(),
        if check_t443_ecamoff_guard() { "" } else { "table ecamoff guard mismatch" },
    );
    set.add(
        "t443-c2-ecam-codec",
        check_c2_ecam_codec(),
        if check_c2_ecam_codec() { "" } else { "ecam codec mismatch" },
    );
    set
}

