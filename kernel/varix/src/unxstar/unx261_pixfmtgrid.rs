/// 模块版本。
pub const T261_VERSION: &str = "t261-pixfmtgrid-v1";

/// 诊断段基址。
pub const T261_SEG_BASE: u16 = 0x3a80;

// --------------------------------------------------------------------------
// 诊断码（t261 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 帧簿域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t261Code {
    /// 0x3a80 单元格重复（同键双占）。
    CellDup,
    /// 0x3a81 单元格断档（序号不连续）。
    CellGap,
    /// 0x3a82 索引越界（≥1024）。
    IndexOob,
    /// 0x3a83 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x3a84 表序断档。
    OrderBreak,
    /// 0x3a85 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0x3a86 掩码非法。
    MaskBad,
    /// 0x3a87 守卫触发。
    GuardTripped,
    /// 0x3a88 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x3a89 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x3a8a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x3a8b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x3a8c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x3a8d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x3a8e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

