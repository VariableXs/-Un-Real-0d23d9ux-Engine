/// 线性查找（键唯一性由构造期断言保证，运行时无分支歧义）。
pub fn pix_swap_get(key: &'static str) -> Option<u64> {
    let mut i = 0usize;
    while i < pix_swap_COUNT {
        if pix_swap[i].0 == key {
            return Some(pix_swap[i].1);
        }
        i += 1;
    }
    None
}

/// 累计求和（用于守恒对账）。
pub fn pix_swap_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < pix_swap_COUNT {
        s = s.wrapping_add(pix_swap[i].1 as u64);
        i += 1;
    }
    s
}

// ---------------------------------------------------------------------------
// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x3a80, 0x3a8f]。
pub const fn t261_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t261Code::ALL.len() {
        let c = t261Code::ALL[i].code();
        if c < 0x3a80 || c > 0x3a8f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t261_guard_seg() -> bool {
    t261_segment_guard()
}

/// 大表 pix_swap 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t261_grid() -> bool {
    let mut ok = pix_swap_COUNT == 1024;
    if ok {
        ok = pix_swap_get("PS0000") == Some(0) && pix_swap_get("PS1023") == Some(1023);
    }
    if ok {
        ok = pix_swap_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t261_sum() -> bool {
    pix_swap_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t261_checks() -> CheckSet {
    let mut set = CheckSet::new("T261");
    set.add(
        "t261-seg-guard",
        t261_guard_seg(),
        if t261_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t261-c1-grid",
        check_c1_t261_grid(),
        if check_c1_t261_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t261-c2-grid-sum",
        check_c2_t261_sum(),
        if check_c2_t261_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

