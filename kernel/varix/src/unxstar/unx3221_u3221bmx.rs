// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u3221_guard_seg() -> bool {
    u3221_segment_guard()
}

/// UNX-F3221 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u3221_bmx_count() -> bool {
    let mut ok = u3221bmx_COUNT == 256;
    if ok { ok = u3221bmx_get("ND0000") == Some(0) && u3221bmx_get("NX0255") == Some(5); }
    if ok { ok = u3221bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3221 bmx 累计守恒（理论值 11231）。
fn check_u3221_bmx_sum() -> bool {
    u3221bmx_sum() == 11231
}

/// UNX-F3221 bmx 逐行守卫与唯一性全绿。
fn check_u3221_bmx_guard() -> bool {
    u3221bmx_scan() == 0 && u3221bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3221_checks() -> CheckSet {
    let mut set = CheckSet::new("U3221");
    set.add(
        "u3221-seg-guard",
        u3221_guard_seg(),
        if u3221_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3221-bmx-count",
        check_u3221_bmx_count(),
        if check_u3221_bmx_count() { "" } else { "UNX-F3221 bmx count mismatch" },
    );
    set.add(
        "u3221-bmx-sum",
        check_u3221_bmx_sum(),
        if check_u3221_bmx_sum() { "" } else { "UNX-F3221 bmx sum mismatch" },
    );
    set.add(
        "u3221-bmx-guard",
        check_u3221_bmx_guard(),
        if check_u3221_bmx_guard() { "" } else { "UNX-F3221 bmx guard mismatch" },
    );
    set
}

