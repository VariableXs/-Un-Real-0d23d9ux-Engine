/// 段位守卫：全部诊断码落在本模块段内。
fn u1541_guard_seg() -> bool {
    u1541_segment_guard()
}

/// UNX-F1541 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u1541_grid_count() -> bool {
    let mut ok = u1541grid_COUNT == 1024;
    if ok { ok = u1541grid_get("MS0000") == Some(0) && u1541grid_get("IF1023") == Some(10); }
    if ok { ok = u1541grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F1541 grid 累计守恒（理论值 49061）。
fn check_u1541_grid_sum() -> bool {
    u1541grid_sum() == 49061
}

/// UNX-F1541 grid 逐行守卫与唯一性全绿。
fn check_u1541_grid_guard() -> bool {
    u1541grid_scan() == 0 && u1541grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u1541_checks() -> CheckSet {
    let mut set = CheckSet::new("U1541");
    set.add(
        "u1541-seg-guard",
        u1541_guard_seg(),
        if u1541_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u1541-grid-count",
        check_u1541_grid_count(),
        if check_u1541_grid_count() { "" } else { "UNX-F1541 grid count mismatch" },
    );
    set.add(
        "u1541-grid-sum",
        check_u1541_grid_sum(),
        if check_u1541_grid_sum() { "" } else { "UNX-F1541 grid sum mismatch" },
    );
    set.add(
        "u1541-grid-guard",
        check_u1541_grid_guard(),
        if check_u1541_grid_guard() { "" } else { "UNX-F1541 grid guard mismatch" },
    );
    set
}

