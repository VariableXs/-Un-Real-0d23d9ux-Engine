/// 段位守卫：全部诊断码必须落在本段 [0x5340, 0x534f]。
pub const fn u1541_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1541Code::ALL.len() {
        let c = u1541Code::ALL[i].code();
        if c < 0x5340 || c > 0x534f {
            ok = false;
        }
        i += 1;
    }
    ok
}

