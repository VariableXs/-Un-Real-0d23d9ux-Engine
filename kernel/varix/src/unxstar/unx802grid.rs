// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t802_guard_seg() -> bool {
    t802_segment_guard()
}

/// 大表 unx802grid 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t802_grid() -> bool {
    let mut ok = unx802grid_COUNT == 1024;
    if ok {
        ok = unx802grid_get("8020000") == Some(0) && unx802grid_get("8021023") == Some(1023);
    }
    if ok {
        ok = unx802grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t802_sum() -> bool {
    unx802grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t802_checks() -> CheckSet {
    let mut set = CheckSet::new("T802");
    set.add(
        "t802-seg-guard",
        t802_guard_seg(),
        if t802_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t802-c1-grid",
        check_c1_t802_grid(),
        if check_c1_t802_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t802-c2-grid-sum",
        check_c2_t802_sum(),
        if check_c2_t802_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

