// --------------------------------------------------------------------------
// 诊断码（t802 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 异常分型域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t802Code {
    /// 0x50f0 格重复（同键双占）。
    CellDup,
    /// 0x50f1 格断档（序号不连续）。
    CellGap,
    /// 0x50f2 索引越界（≥1024）。
    IndexOob,
    /// 0x50f3 大表账破缺。
    LedgerBreak,
    /// 0x50f4 表序断档。
    OrderBreak,
    /// 0x50f5 累计漂移。
    SumDrift,
    /// 0x50f6 掩码非法。
    MaskBad,
    /// 0x50f7 守卫触发。
    GuardTripped,
    /// 0x50f8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x50f9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x50fa 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x50fb 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x50fc 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x50fd 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x50fe 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

