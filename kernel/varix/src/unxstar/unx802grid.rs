/// 段位守卫：全部诊断码必须落在本段 [0x50f0, 0x50ff]。
pub const fn t802_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t802Code::ALL.len() {
        let c = t802Code::ALL[i].code();
        if c < 0x50f0 || c > 0x50ff {
            ok = false;
        }
        i += 1;
    }
    ok
}

