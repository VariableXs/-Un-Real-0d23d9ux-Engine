/// 线性查找（键唯一性由构造期断言保证，运行时无分支歧义）。
pub fn unx802grid_get(key: &'static str) -> Option<u64> {
    let mut i = 0usize;
    while i < unx802grid_COUNT {
        if unx802grid[i].0 == key {
            return Some(unx802grid[i].1);
        }
        i += 1;
    }
    None
}

/// 累计求和（用于守恒对账）。
pub fn unx802grid_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < unx802grid_COUNT {
        s = s.wrapping_add(unx802grid[i].1 as u64);
        i += 1;
    }
    s
}

