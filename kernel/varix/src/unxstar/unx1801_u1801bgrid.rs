fn check_u1801bgrid_sum() -> bool {
    u1801bgrid_sum() == 44933
}

/// U1801 u1801bgrid 逐行守卫与唯一性全绿。
fn check_u1801bgrid_guard() -> bool {
    u1801bgrid_scan() == 0 && u1801bgrid_unique()
}

