pub const U1841_SEG_BASE: u16 = 0x5ea0;

// --------------------------------------------------------------------------

// 诊断码（U1841_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U1841_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1841Code {
    /// 0x5ea0 单元格重复（未登记向量 同键双占）。
    CellDup = 0x5ea0,
    /// 0x5ea1 单元格断档（EOI 漏发 序号不连续）。
    CellGap = 0x5ea1,
    /// 0x5ea2 索引越界（衔接断裂）。
    IndexOob = 0x5ea2,
    /// 0x5ea3 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5ea3,
    /// 0x5ea4 表序断档。
    OrderBreak = 0x5ea4,
    /// 0x5ea5 累计漂移（求和≠理论值）。
    SumDrift = 0x5ea5,
    /// 0x5ea6 掩码非法。
    MaskBad = 0x5ea6,
    /// 0x5ea7 守卫触发。
    GuardTripped = 0x5ea7,
    /// 0x5ea8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5ea8,
    /// 0x5ea9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5ea9,
    /// 0x5eaa 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5eaa,
    /// 0x5eab 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5eab,
}

impl u1841Code {
    /// 全量闭集。
    pub const ALL: [u1841Code; 12] = [
        u1841Code::CellDup,
        u1841Code::CellGap,
        u1841Code::IndexOob,
        u1841Code::LedgerBreak,
        u1841Code::OrderBreak,
        u1841Code::SumDrift,
        u1841Code::MaskBad,
        u1841Code::GuardTripped,
        u1841Code::LedgerBroken,
        u1841Code::SnapshotFingerprint,
        u1841Code::TableBroken,
        u1841Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U1841CODE_NAMES[(self.code() - U1841_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U1841CODE_SUGGESTIONS[(self.code() - U1841_SEG_BASE) as usize]
    }
}

