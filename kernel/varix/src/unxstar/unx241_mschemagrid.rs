/// 段位守卫：全部诊断码必须落在本段 [0x3980, 0x398f]。
pub const fn t241_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t241Code::ALL.len() {
        let c = t241Code::ALL[i].code();
        if c < 0x3980 || c > 0x398f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t241_guard_seg() -> bool {
    t241_segment_guard()
}

/// 大表 manifest_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t241_grid() -> bool {
    let mut ok = manifest_cell_COUNT == 1024;
    if ok {
        ok = manifest_cell_get("MC0000") == Some(0) && manifest_cell_get("MC1023") == Some(1023);
    }
    if ok {
        ok = manifest_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t241_sum() -> bool {
    manifest_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t241_checks() -> CheckSet {
    let mut set = CheckSet::new("T241");
    set.add(
        "t241-seg-guard",
        t241_guard_seg(),
        if t241_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t241-c1-grid",
        check_c1_t241_grid(),
        if check_c1_t241_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t241-c2-grid-sum",
        check_c2_t241_sum(),
        if check_c2_t241_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

