// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u3221_guard_seg() -> bool {
    u3221_segment_guard()
}

/// UNX-F3221 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u3221_mx_count() -> bool {
    let mut ok = u3221mx_COUNT == 512;
    if ok { ok = u3221mx_get("ND0000") == Some(0) && u3221mx_get("HB0511") == Some(47); }
    if ok { ok = u3221mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3221 mx 累计守恒（理论值 24448）。
fn check_u3221_mx_sum() -> bool {
    u3221mx_sum() == 24448
}

/// UNX-F3221 mx 逐行守卫与唯一性全绿。
fn check_u3221_mx_guard() -> bool {
    u3221mx_scan() == 0 && u3221mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3221_checks() -> CheckSet {
    let mut set = CheckSet::new("U3221");
    set.add(
        "u3221-seg-guard",
        u3221_guard_seg(),
        if u3221_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3221-mx-count",
        check_u3221_mx_count(),
        if check_u3221_mx_count() { "" } else { "UNX-F3221 mx count mismatch" },
    );
    set.add(
        "u3221-mx-sum",
        check_u3221_mx_sum(),
        if check_u3221_mx_sum() { "" } else { "UNX-F3221 mx sum mismatch" },
    );
    set.add(
        "u3221-mx-guard",
        check_u3221_mx_guard(),
        if check_u3221_mx_guard() { "" } else { "UNX-F3221 mx guard mismatch" },
    );
    set
}

