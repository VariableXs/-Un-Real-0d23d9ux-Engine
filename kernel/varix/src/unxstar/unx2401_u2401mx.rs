/// 段位守卫：全部诊断码必须落在本段 [0xa090, 0xa09f]。
pub const fn u2401_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2401Code::ALL.len() {
        let c = u2401Code::ALL[i].code();
        if c < 0xa090 || c > 0xa09f {
            ok = false;
        }
        i += 1;
    }
    ok
}

