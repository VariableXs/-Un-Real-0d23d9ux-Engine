/// UNX-F2401 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u2401_mx_count() -> bool {
    let mut ok = u2401mx_COUNT == 512;
    if ok { ok = u2401mx_get("AV0000") == Some(0) && u2401mx_get("DR0511") == Some(47); }
    if ok { ok = u2401mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2401 mx 累计守恒（理论值 24448）。
fn check_u2401_mx_sum() -> bool {
    u2401mx_sum() == 24448
}

/// UNX-F2401 mx 逐行守卫与唯一性全绿。
fn check_u2401_mx_guard() -> bool {
    u2401mx_scan() == 0 && u2401mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2401_checks() -> CheckSet {
    let mut set = CheckSet::new("U2401");
    set.add(
        "u2401-seg-guard",
        u2401_guard_seg(),
        if u2401_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2401-mx-count",
        check_u2401_mx_count(),
        if check_u2401_mx_count() { "" } else { "UNX-F2401 mx count mismatch" },
    );
    set.add(
        "u2401-mx-sum",
        check_u2401_mx_sum(),
        if check_u2401_mx_sum() { "" } else { "UNX-F2401 mx sum mismatch" },
    );
    set.add(
        "u2401-mx-guard",
        check_u2401_mx_guard(),
        if check_u2401_mx_guard() { "" } else { "UNX-F2401 mx guard mismatch" },
    );
    set
}

