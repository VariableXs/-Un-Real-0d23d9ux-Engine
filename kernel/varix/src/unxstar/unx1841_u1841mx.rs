/// 段位守卫：全部诊断码必须落在本段 [0x5e90, 0x5e9f]。
pub const fn u1841_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1841Code::ALL.len() {
        let c = u1841Code::ALL[i].code();
        if c < 0x5e90 || c > 0x5e9f {
            ok = false;
        }
        i += 1;
    }
    ok
}

