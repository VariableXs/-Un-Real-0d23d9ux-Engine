/// 段位守卫：全部诊断码落在本模块段内。
fn t571_guard_seg() -> bool {
    t571_segment_guard()
}

/// 表 uartbit 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t571_uartbit_guard() -> bool {
    let mut ok = uartbit_COUNT == 512;
    if ok {
        ok = uartbit_scan() == 0;
    }
    if ok {
        ok = uartbit_unique();
    }
    ok
}

/// 位号求和守恒（0..511 = 130816）。
fn check_c2_bit_sum() -> bool {
    let mut ok = uartbit_sum() == 130816;
    if ok {
        ok = uartbit_get("BIT_0_00") == Some(0) && uartbit_get("BIT_7_63") == Some(511);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t571_checks() -> CheckSet {
    let mut set = CheckSet::new("T571");
    set.add(
        "t571-seg-guard",
        t571_guard_seg(),
        if t571_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t571-c1-bit-guard",
        check_t571_uartbit_guard(),
        if check_t571_uartbit_guard() { "" } else { "table uartbit guard mismatch" },
    );
    set.add(
        "t571-c2-bit-sum",
        check_c2_bit_sum(),
        if check_c2_bit_sum() { "" } else { "uart bit table sum mismatch" },
    );
    set
}

