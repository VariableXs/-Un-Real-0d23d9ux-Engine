/// 模块版本。
pub const T571_VERSION: &str = "t571-uartbit-v1";

/// 诊断段基址。
pub const T571_SEG_BASE: u16 = 0x4600;

// --------------------------------------------------------------------------
// 诊断码（t571 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// UART 位域诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t571Code {
    /// 0x4600 寄存器非法（8 个之外）。
    RegBad,
    /// 0x4601 位号越界（≥64）。
    BitOob,
    /// 0x4602 位语义重复（同位双义）。
    BitSemDup,
    /// 0x4603 只读位被写。
    ReadOnlyWrite,
    /// 0x4604 只写位被读。
    WriteOnlyRead,
    /// 0x4605 位域账破缺。
    LedgerBreak,
    /// 0x4606 位序断档。
    OrderBreak,
    /// 0x4607 守卫触发。
    GuardTripped,
    /// 0x4608 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4609 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x460a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x460b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x460c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x460d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x460e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

