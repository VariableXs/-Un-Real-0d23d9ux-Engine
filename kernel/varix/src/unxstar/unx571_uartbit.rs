/// 段位守卫：全部诊断码必须落在本段 [0x4600, 0x460f]。
pub const fn t571_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t571Code::ALL.len() {
        let c = t571Code::ALL[i].code();
        if c < 0x4600 || c > 0x460f {
            ok = false;
        }
        i += 1;
    }
    ok
}

