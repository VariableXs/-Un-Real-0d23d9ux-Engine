pub const U2441_SEG_BASE: u16 = 0xa220;

// --------------------------------------------------------------------------

// 诊断码（U2441_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U2441_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u2441Code {
    /// 0xa220 单元格重复（容量失配 同键双占）。
    CellDup = 0xa220,
    /// 0xa221 单元格断档（恒等破缺 序号不连续）。
    CellGap = 0xa221,
    /// 0xa222 索引越界（抽核漂移）。
    IndexOob = 0xa222,
    /// 0xa223 大表账破缺（行数≠登记值）。
    LedgerBreak = 0xa223,
    /// 0xa224 表序断档。
    OrderBreak = 0xa224,
    /// 0xa225 累计漂移（求和≠理论值）。
    SumDrift = 0xa225,
    /// 0xa226 掩码非法。
    MaskBad = 0xa226,
    /// 0xa227 守卫触发。
    GuardTripped = 0xa227,
    /// 0xa228 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0xa228,
    /// 0xa229 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0xa229,
    /// 0xa22a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0xa22a,
    /// 0xa22b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0xa22b,
}

impl u2441Code {
    /// 全量闭集。
    pub const ALL: [u2441Code; 12] = [
        u2441Code::CellDup,
        u2441Code::CellGap,
        u2441Code::IndexOob,
        u2441Code::LedgerBreak,
        u2441Code::OrderBreak,
        u2441Code::SumDrift,
        u2441Code::MaskBad,
        u2441Code::GuardTripped,
        u2441Code::LedgerBroken,
        u2441Code::SnapshotFingerprint,
        u2441Code::TableBroken,
        u2441Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U2441CODE_NAMES[(self.code() - U2441_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U2441CODE_SUGGESTIONS[(self.code() - U2441_SEG_BASE) as usize]
    }
}

