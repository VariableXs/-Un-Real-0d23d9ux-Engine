/// UNX-F1841 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u1841_grid_count() -> bool {
    let mut ok = u1841grid_COUNT == 1024;
    if ok { ok = u1841grid_get("XL0000") == Some(0) && u1841grid_get("EOI1023") == Some(10); }
    if ok { ok = u1841grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F1841 grid 累计守恒（理论值 49061）。
fn check_u1841_grid_sum() -> bool {
    u1841grid_sum() == 49061
}

/// UNX-F1841 grid 逐行守卫与唯一性全绿。
fn check_u1841_grid_guard() -> bool {
    u1841grid_scan() == 0 && u1841grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u1841_checks() -> CheckSet {
    let mut set = CheckSet::new("U1841");
    set.add(
        "u1841-seg-guard",
        u1841_guard_seg(),
        if u1841_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u1841-grid-count",
        check_u1841_grid_count(),
        if check_u1841_grid_count() { "" } else { "UNX-F1841 grid count mismatch" },
    );
    set.add(
        "u1841-grid-sum",
        check_u1841_grid_sum(),
        if check_u1841_grid_sum() { "" } else { "UNX-F1841 grid sum mismatch" },
    );
    set.add(
        "u1841-grid-guard",
        check_u1841_grid_guard(),
        if check_u1841_grid_guard() { "" } else { "UNX-F1841 grid guard mismatch" },
    );
    set
}

