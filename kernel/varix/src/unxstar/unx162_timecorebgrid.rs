// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t162_guard_seg() -> bool {
    t162_segment_guard()
}

/// 大表 time_sampleb 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t162_grid() -> bool {
    let mut ok = time_sampleb_COUNT == 1024;
    if ok {
        ok = time_sampleb_get("TS0000") == Some(0) && time_sampleb_get("TS1023") == Some(1023);
    }
    if ok {
        ok = time_sampleb_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t162_sum() -> bool {
    time_sampleb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t162_checks() -> CheckSet {
    let mut set = CheckSet::new("T162");
    set.add(
        "t162-seg-guard",
        t162_guard_seg(),
        if t162_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t162-c1-grid",
        check_c1_t162_grid(),
        if check_c1_t162_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t162-c2-grid-sum",
        check_c2_t162_sum(),
        if check_c2_t162_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

