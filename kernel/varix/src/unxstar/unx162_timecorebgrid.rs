// --------------------------------------------------------------------------
// 诊断码（t162 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 时间域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t162Code {
    /// 0x37a0 单元格重复（同键双占）。
    CellDup,
    /// 0x37a1 单元格断档（序号不连续）。
    CellGap,
    /// 0x37a2 索引越界（≥1024）。
    IndexOob,
    /// 0x37a3 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x37a4 表序断档。
    OrderBreak,
    /// 0x37a5 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0x37a6 掩码非法。
    MaskBad,
    /// 0x37a7 守卫触发。
    GuardTripped,
    /// 0x37a8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x37a9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x37aa 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x37ab 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x37ac 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x37ad 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x37ae 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

