/// 段位守卫：全部诊断码必须落在本段 [0x37a0, 0x37af]。
pub const fn t162_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t162Code::ALL.len() {
        let c = t162Code::ALL[i].code();
        if c < 0x37a0 || c > 0x37af {
            ok = false;
        }
        i += 1;
    }
    ok
}

