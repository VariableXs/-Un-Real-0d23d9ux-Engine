/// 段位守卫：全部诊断码必须落在本段 [0xa5d0, 0xa5df]。
pub const fn u2541_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2541Code::ALL.len() {
        let c = u2541Code::ALL[i].code();
        if c < 0xa5d0 || c > 0xa5df {
            ok = false;
        }
        i += 1;
    }
    ok
}

