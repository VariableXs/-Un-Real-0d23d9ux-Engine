// --------------------------------------------------------------------------
// 诊断码（t561 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 帧缓冲域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t561Code {
    /// 0x45b0 矩阵行重复。
    RowDup,
    /// 0x45b1 矩阵断档。
    RowGap,
    /// 0x45b2 行守卫破缺（逐行校验失败）。
    GuardBreak,
    /// 0x45b3 矩阵累计漂移。
    SumDrift,
    /// 0x45b4 索引错位。
    IndexMisaligned,
    /// 0x45b5 矩阵账破缺。
    LedgerBreak,
    /// 0x45b6 矩阵序断档。
    OrderBreak,
    /// 0x45b7 守卫触发。
    GuardTripped,
    /// 0x45b8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x45b9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x45ba 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x45bb 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x45bc 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x45bd 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

