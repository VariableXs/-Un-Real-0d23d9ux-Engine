/// U1721 u1721grid 累计守恒（理论值 49061）。
fn check_u1721grid_sum() -> bool {
    u1721grid_sum() == 49061
}

/// U1721 u1721grid 逐行守卫与唯一性全绿。
fn check_u1721grid_guard() -> bool {
    u1721grid_scan() == 0 && u1721grid_unique()
}

