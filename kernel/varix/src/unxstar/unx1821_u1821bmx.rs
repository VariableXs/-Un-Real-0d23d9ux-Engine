/// 段位守卫：全部诊断码必须落在本段 [0x5df0, 0x5dff]。
pub const fn u1821_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1821Code::ALL.len() {
        let c = u1821Code::ALL[i].code();
        if c < 0x5df0 || c > 0x5dff {
            ok = false;
        }
        i += 1;
    }
    ok
}

