/// 段位守卫：全部诊断码落在本模块段内。
fn t361_guard_seg() -> bool {
    t361_segment_guard()
}

/// 表 pit_matrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t361_pit_matrix_guard() -> bool {
    let mut ok = pit_matrix_COUNT == 500;
    if ok {
        ok = pit_matrix_scan() == 0;
    }
    if ok {
        ok = pit_matrix_unique();
    }
    ok
}

/// 矩阵累计守恒（1..500 = 124750）。
fn check_c2_t361_mxsum() -> bool {
    pit_matrix_sum() == 124750
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t361_checks() -> CheckSet {
    let mut set = CheckSet::new("T361");
    set.add(
        "t361-seg-guard",
        t361_guard_seg(),
        if t361_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t361-c1-mx-guard",
        check_t361_pit_matrix_guard(),
        if check_t361_pit_matrix_guard() { "" } else { "table pit_matrix guard mismatch" },
    );
    set.add(
        "t361-c2-mx-sum",
        check_c2_t361_mxsum(),
        if check_c2_t361_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

