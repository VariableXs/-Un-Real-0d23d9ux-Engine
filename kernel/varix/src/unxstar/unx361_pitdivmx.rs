/// 累计求和（守恒对账用）。
pub fn pit_matrix_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < pit_matrix_COUNT {
        s = s.wrapping_add(pit_matrix[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn pit_matrix_unique() -> bool {
    let mut i = 0usize;
    while i < pit_matrix_COUNT {
        let mut j = i + 1;
        while j < pit_matrix_COUNT {
            if pit_matrix[i].0 == pit_matrix[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

