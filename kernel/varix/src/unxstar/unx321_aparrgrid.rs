pub const T321_SEG_BASE: u16 = 0x3e80;

// --------------------------------------------------------------------------
// 诊断码（t321 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// AP 汇合域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t321Code {
    /// 0x3e80 单元格重复（同键双占）。
    CellDup,
    /// 0x3e81 单元格断档（序号不连续）。
    CellGap,
    /// 0x3e82 索引越界（≥1024）。
    IndexOob,
    /// 0x3e83 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x3e84 表序断档。
    OrderBreak,
    /// 0x3e85 累计漂移（求和≠理论值）。
    SumDrift,
    /// 0x3e86 掩码非法。
    MaskBad,
    /// 0x3e87 守卫触发。
    GuardTripped,
    /// 0x3e88 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x3e89 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x3e8a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x3e8b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x3e8c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x3e8d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x3e8e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

