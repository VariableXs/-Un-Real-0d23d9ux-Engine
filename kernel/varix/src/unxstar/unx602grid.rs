/// 段位守卫：全部诊断码必须落在本段 [0x5080, 0x508f]。
pub const fn t602_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t602Code::ALL.len() {
        let c = t602Code::ALL[i].code();
        if c < 0x5080 || c > 0x508f {
            ok = false;
        }
        i += 1;
    }
    ok
}

