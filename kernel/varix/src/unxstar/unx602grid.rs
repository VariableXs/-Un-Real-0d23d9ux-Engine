/// 段位守卫：全部诊断码落在本模块段内。
fn t602_guard_seg() -> bool {
    t602_segment_guard()
}

/// 大表 unx602grid 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t602_grid() -> bool {
    let mut ok = unx602grid_COUNT == 1024;
    if ok {
        ok = unx602grid_get("6020000") == Some(0) && unx602grid_get("6021023") == Some(1023);
    }
    if ok {
        ok = unx602grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t602_sum() -> bool {
    unx602grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t602_checks() -> CheckSet {
    let mut set = CheckSet::new("T602");
    set.add(
        "t602-seg-guard",
        t602_guard_seg(),
        if t602_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t602-c1-grid",
        check_c1_t602_grid(),
        if check_c1_t602_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t602-c2-grid-sum",
        check_c2_t602_sum(),
        if check_c2_t602_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

