// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u2641_guard_seg() -> bool {
    u2641_segment_guard()
}

/// UNX-F2641 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u2641_grid_count() -> bool {
    let mut ok = u2641grid_COUNT == 1024;
    if ok { ok = u2641grid_get("FK0000") == Some(0) && u2641grid_get("C11023") == Some(10); }
    if ok { ok = u2641grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2641 grid 累计守恒（理论值 49061）。
fn check_u2641_grid_sum() -> bool {
    u2641grid_sum() == 49061
}

/// UNX-F2641 grid 逐行守卫与唯一性全绿。
fn check_u2641_grid_guard() -> bool {
    u2641grid_scan() == 0 && u2641grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2641_checks() -> CheckSet {
    let mut set = CheckSet::new("U2641");
    set.add(
        "u2641-seg-guard",
        u2641_guard_seg(),
        if u2641_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2641-grid-count",
        check_u2641_grid_count(),
        if check_u2641_grid_count() { "" } else { "UNX-F2641 grid count mismatch" },
    );
    set.add(
        "u2641-grid-sum",
        check_u2641_grid_sum(),
        if check_u2641_grid_sum() { "" } else { "UNX-F2641 grid sum mismatch" },
    );
    set.add(
        "u2641-grid-guard",
        check_u2641_grid_guard(),
        if check_u2641_grid_guard() { "" } else { "UNX-F2641 grid guard mismatch" },
    );
    set
}

