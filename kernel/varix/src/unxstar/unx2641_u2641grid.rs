// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0xa980, 0xa98f]。
pub const fn u2641_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2641Code::ALL.len() {
        let c = u2641Code::ALL[i].code();
        if c < 0xa980 || c > 0xa98f {
            ok = false;
        }
        i += 1;
    }
    ok
}

