/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u2401grid_unique() -> bool {
    let mut i = 0usize;
    while i < u2401grid_COUNT {
        let mut j = i + 1;
        while j < u2401grid_COUNT {
            if str_eq(u2401grid[i].0, u2401grid[j].0) {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

