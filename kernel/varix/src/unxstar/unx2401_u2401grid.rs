/// 段位守卫：全部诊断码必须落在本段 [0xa080, 0xa08f]。
pub const fn u2401_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2401Code::ALL.len() {
        let c = u2401Code::ALL[i].code();
        if c < 0xa080 || c > 0xa08f {
            ok = false;
        }
        i += 1;
    }
    ok
}

