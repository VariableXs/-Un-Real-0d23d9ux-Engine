/// UNX-F2401 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u2401_grid_count() -> bool {
    let mut ok = u2401grid_COUNT == 1024;
    if ok { ok = u2401grid_get("AV0000") == Some(0) && u2401grid_get("BD1023") == Some(10); }
    if ok { ok = u2401grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2401 grid 累计守恒（理论值 49061）。
fn check_u2401_grid_sum() -> bool {
    u2401grid_sum() == 49061
}

/// UNX-F2401 grid 逐行守卫与唯一性全绿。
fn check_u2401_grid_guard() -> bool {
    u2401grid_scan() == 0 && u2401grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2401_checks() -> CheckSet {
    let mut set = CheckSet::new("U2401");
    set.add(
        "u2401-seg-guard",
        u2401_guard_seg(),
        if u2401_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2401-grid-count",
        check_u2401_grid_count(),
        if check_u2401_grid_count() { "" } else { "UNX-F2401 grid count mismatch" },
    );
    set.add(
        "u2401-grid-sum",
        check_u2401_grid_sum(),
        if check_u2401_grid_sum() { "" } else { "UNX-F2401 grid sum mismatch" },
    );
    set.add(
        "u2401-grid-guard",
        check_u2401_grid_guard(),
        if check_u2401_grid_guard() { "" } else { "UNX-F2401 grid guard mismatch" },
    );
    set
}

