pub const U2401_SEG_BASE: u16 = 0xa080;

// --------------------------------------------------------------------------

// 诊断码（U2401_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U2401_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u2401Code {
    /// 0xa080 单元格重复（区间数失配 同键双占）。
    CellDup = 0xa080,
    /// 0xa081 单元格断档（字节和偏差 序号不连续）。
    CellGap = 0xa081,
    /// 0xa082 索引越界（四态漏归）。
    IndexOob = 0xa082,
    /// 0xa083 大表账破缺（行数≠登记值）。
    LedgerBreak = 0xa083,
    /// 0xa084 表序断档。
    OrderBreak = 0xa084,
    /// 0xa085 累计漂移（求和≠理论值）。
    SumDrift = 0xa085,
    /// 0xa086 掩码非法。
    MaskBad = 0xa086,
    /// 0xa087 守卫触发。
    GuardTripped = 0xa087,
    /// 0xa088 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0xa088,
    /// 0xa089 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0xa089,
    /// 0xa08a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0xa08a,
    /// 0xa08b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0xa08b,
}

impl u2401Code {
    /// 全量闭集。
    pub const ALL: [u2401Code; 12] = [
        u2401Code::CellDup,
        u2401Code::CellGap,
        u2401Code::IndexOob,
        u2401Code::LedgerBreak,
        u2401Code::OrderBreak,
        u2401Code::SumDrift,
        u2401Code::MaskBad,
        u2401Code::GuardTripped,
        u2401Code::LedgerBroken,
        u2401Code::SnapshotFingerprint,
        u2401Code::TableBroken,
        u2401Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U2401CODE_NAMES[(self.code() - U2401_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U2401CODE_SUGGESTIONS[(self.code() - U2401_SEG_BASE) as usize]
    }
}

