// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t122_guard_seg() -> bool {
    t122_segment_guard()
}

/// 表 wdmx 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t122_wdmx_guard() -> bool {
    let mut ok = wdmx_COUNT == 512;
    if ok {
        ok = wdmx_scan() == 0;
    }
    if ok {
        ok = wdmx_unique();
    }
    ok
}

/// 矩阵累计守恒（0..511 = 130816）。
fn check_c2_t122_mxsum() -> bool {
    wdmx_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t122_checks() -> CheckSet {
    let mut set = CheckSet::new("T122");
    set.add(
        "t122-seg-guard",
        t122_guard_seg(),
        if t122_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t122-c1-mx-guard",
        check_t122_wdmx_guard(),
        if check_t122_wdmx_guard() { "" } else { "table wdmx guard mismatch" },
    );
    set.add(
        "t122-c2-mx-sum",
        check_c2_t122_mxsum(),
        if check_c2_t122_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

