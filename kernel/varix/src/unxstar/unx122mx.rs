/// 累计求和（守恒对账用）。
pub fn wdmx_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < wdmx_COUNT {
        s = s.wrapping_add(wdmx[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn wdmx_unique() -> bool {
    let mut i = 0usize;
    while i < wdmx_COUNT {
        let mut j = i + 1;
        while j < wdmx_COUNT {
            if wdmx[i].0 == wdmx[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

