// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x4b90, 0x4b9f]。
pub const fn t122_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t122Code::ALL.len() {
        let c = t122Code::ALL[i].code();
        if c < 0x4b90 || c > 0x4b9f {
            ok = false;
        }
        i += 1;
    }
    ok
}

