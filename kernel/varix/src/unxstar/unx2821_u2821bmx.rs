/// UNX-F2821 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u2821_bmx_count() -> bool {
    let mut ok = u2821bmx_COUNT == 256;
    if ok { ok = u2821bmx_get("AS0000") == Some(0) && u2821bmx_get("SW0255") == Some(5); }
    if ok { ok = u2821bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2821 bmx 累计守恒（理论值 11231）。
fn check_u2821_bmx_sum() -> bool {
    u2821bmx_sum() == 11231
}

/// UNX-F2821 bmx 逐行守卫与唯一性全绿。
fn check_u2821_bmx_guard() -> bool {
    u2821bmx_scan() == 0 && u2821bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2821_checks() -> CheckSet {
    let mut set = CheckSet::new("U2821");
    set.add(
        "u2821-seg-guard",
        u2821_guard_seg(),
        if u2821_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2821-bmx-count",
        check_u2821_bmx_count(),
        if check_u2821_bmx_count() { "" } else { "UNX-F2821 bmx count mismatch" },
    );
    set.add(
        "u2821-bmx-sum",
        check_u2821_bmx_sum(),
        if check_u2821_bmx_sum() { "" } else { "UNX-F2821 bmx sum mismatch" },
    );
    set.add(
        "u2821-bmx-guard",
        check_u2821_bmx_guard(),
        if check_u2821_bmx_guard() { "" } else { "UNX-F2821 bmx guard mismatch" },
    );
    set
}

