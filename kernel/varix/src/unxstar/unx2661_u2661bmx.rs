/// 段位守卫：全部诊断码落在本模块段内。
fn u2661_guard_seg() -> bool {
    u2661_segment_guard()
}

/// UNX-F2661 bmx 256 行齐备 + 边界锚 + 键外拒收。
fn check_u2661_bmx_count() -> bool {
    let mut ok = u2661bmx_COUNT == 256;
    if ok { ok = u2661bmx_get("PC0000") == Some(0) && u2661bmx_get("FO0255") == Some(5); }
    if ok { ok = u2661bmx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2661 bmx 累计守恒（理论值 11231）。
fn check_u2661_bmx_sum() -> bool {
    u2661bmx_sum() == 11231
}

/// UNX-F2661 bmx 逐行守卫与唯一性全绿。
fn check_u2661_bmx_guard() -> bool {
    u2661bmx_scan() == 0 && u2661bmx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2661_checks() -> CheckSet {
    let mut set = CheckSet::new("U2661");
    set.add(
        "u2661-seg-guard",
        u2661_guard_seg(),
        if u2661_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2661-bmx-count",
        check_u2661_bmx_count(),
        if check_u2661_bmx_count() { "" } else { "UNX-F2661 bmx count mismatch" },
    );
    set.add(
        "u2661-bmx-sum",
        check_u2661_bmx_sum(),
        if check_u2661_bmx_sum() { "" } else { "UNX-F2661 bmx sum mismatch" },
    );
    set.add(
        "u2661-bmx-guard",
        check_u2661_bmx_guard(),
        if check_u2661_bmx_guard() { "" } else { "UNX-F2661 bmx guard mismatch" },
    );
    set
}

