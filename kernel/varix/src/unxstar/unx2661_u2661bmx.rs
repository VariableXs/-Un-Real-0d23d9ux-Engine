/// 段位守卫：全部诊断码必须落在本段 [0xaa70, 0xaa7f]。
pub const fn u2661_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2661Code::ALL.len() {
        let c = u2661Code::ALL[i].code();
        if c < 0xaa70 || c > 0xaa7f {
            ok = false;
        }
        i += 1;
    }
    ok
}

