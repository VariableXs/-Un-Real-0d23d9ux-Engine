/// 段位守卫：全部诊断码必须落在本段 [0x5710, 0x571f]。
pub const fn u1641_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1641Code::ALL.len() {
        let c = u1641Code::ALL[i].code();
        if c < 0x5710 || c > 0x571f {
            ok = false;
        }
        i += 1;
    }
    ok
}

