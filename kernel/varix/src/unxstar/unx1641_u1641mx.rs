/// 累计求和（守恒对账用）。
pub fn u1641mx_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < u1641mx_COUNT {
        s = s.wrapping_add(u1641mx[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u1641mx_unique() -> bool {
    let mut i = 0usize;
    while i < u1641mx_COUNT {
        let mut j = i + 1;
        while j < u1641mx_COUNT {
            if u1641mx[i].0 == u1641mx[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

