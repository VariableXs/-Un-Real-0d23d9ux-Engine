pub const U1901_SEG_BASE: u16 = 0x60e0;

// --------------------------------------------------------------------------

// 诊断码（U1901_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U1901_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1901Code {
    /// 0x60e0 单元格重复（位图裁断错 同键双占）。
    CellDup = 0x60e0,
    /// 0x60e1 单元格断档（尺寸漂移 序号不连续）。
    CellGap = 0x60e1,
    /// 0x60e2 索引越界（对齐破坏）。
    IndexOob = 0x60e2,
    /// 0x60e3 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x60e3,
    /// 0x60e4 表序断档。
    OrderBreak = 0x60e4,
    /// 0x60e5 累计漂移（求和≠理论值）。
    SumDrift = 0x60e5,
    /// 0x60e6 掩码非法。
    MaskBad = 0x60e6,
    /// 0x60e7 守卫触发。
    GuardTripped = 0x60e7,
    /// 0x60e8 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x60e8,
    /// 0x60e9 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x60e9,
    /// 0x60ea 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x60ea,
    /// 0x60eb 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x60eb,
}

impl u1901Code {
    /// 全量闭集。
    pub const ALL: [u1901Code; 12] = [
        u1901Code::CellDup,
        u1901Code::CellGap,
        u1901Code::IndexOob,
        u1901Code::LedgerBreak,
        u1901Code::OrderBreak,
        u1901Code::SumDrift,
        u1901Code::MaskBad,
        u1901Code::GuardTripped,
        u1901Code::LedgerBroken,
        u1901Code::SnapshotFingerprint,
        u1901Code::TableBroken,
        u1901Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U1901CODE_NAMES[(self.code() - U1901_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U1901CODE_SUGGESTIONS[(self.code() - U1901_SEG_BASE) as usize]
    }
}

