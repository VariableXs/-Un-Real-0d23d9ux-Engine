/// 段位守卫：全部诊断码落在本模块段内。
fn u3521_guard_seg() -> bool {
    u3521_segment_guard()
}

/// UNX-F3521 grid 1024 行齐备 + 边界锚 + 键外拒收。
fn check_u3521_grid_count() -> bool {
    let mut ok = u3521grid_COUNT == 1024;
    if ok { ok = u3521grid_get("PROBE0000") == Some(0) && u3521grid_get("INS1023") == Some(10); }
    if ok { ok = u3521grid_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F3521 grid 累计守恒（理论值 49061）。
fn check_u3521_grid_sum() -> bool {
    u3521grid_sum() == 49061
}

/// UNX-F3521 grid 逐行守卫与唯一性全绿。
fn check_u3521_grid_guard() -> bool {
    u3521grid_scan() == 0 && u3521grid_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u3521_checks() -> CheckSet {
    let mut set = CheckSet::new("U3521");
    set.add(
        "u3521-seg-guard",
        u3521_guard_seg(),
        if u3521_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u3521-grid-count",
        check_u3521_grid_count(),
        if check_u3521_grid_count() { "" } else { "UNX-F3521 grid count mismatch" },
    );
    set.add(
        "u3521-grid-sum",
        check_u3521_grid_sum(),
        if check_u3521_grid_sum() { "" } else { "UNX-F3521 grid sum mismatch" },
    );
    set.add(
        "u3521-grid-guard",
        check_u3521_grid_guard(),
        if check_u3521_grid_guard() { "" } else { "UNX-F3521 grid guard mismatch" },
    );
    set
}

