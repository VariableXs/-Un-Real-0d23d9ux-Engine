/// 线性查找（键唯一性由构造期断言保证，运行时无分支歧义）。
pub fn pm_cellb_get(key: &'static str) -> Option<u64> {
    let mut i = 0usize;
    while i < pm_cellb_COUNT {
        if pm_cellb[i].0 == key {
            return Some(pm_cellb[i].1);
        }
        i += 1;
    }
    None
}

/// 累计求和（用于守恒对账）。
pub fn pm_cellb_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < pm_cellb_COUNT {
        s = s.wrapping_add(pm_cellb[i].1 as u64);
        i += 1;
    }
    s
}

