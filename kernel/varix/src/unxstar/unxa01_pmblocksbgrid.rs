/// 段位守卫：全部诊断码必须落在本段 [0x49a0, 0x49af]。
pub const fn ta01_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < ta01Code::ALL.len() {
        let c = ta01Code::ALL[i].code();
        if c < 0x49a0 || c > 0x49af {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn ta01_guard_seg() -> bool {
    ta01_segment_guard()
}

/// 大表 pm_cellb 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_ta01_grid() -> bool {
    let mut ok = pm_cellb_COUNT == 1024;
    if ok {
        ok = pm_cellb_get("PC0000") == Some(0) && pm_cellb_get("PC1023") == Some(1023);
    }
    if ok {
        ok = pm_cellb_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_ta01_sum() -> bool {
    pm_cellb_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_ta01_checks() -> CheckSet {
    let mut set = CheckSet::new("TA01");
    set.add(
        "ta01-seg-guard",
        ta01_guard_seg(),
        if ta01_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "ta01-c1-grid",
        check_c1_ta01_grid(),
        if check_c1_ta01_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "ta01-c2-grid-sum",
        check_c2_ta01_sum(),
        if check_c2_ta01_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

