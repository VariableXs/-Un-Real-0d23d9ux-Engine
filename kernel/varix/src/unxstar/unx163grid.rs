/// 段位守卫：全部诊断码落在本模块段内。
fn t163_guard_seg() -> bool {
    t163_segment_guard()
}

/// 大表 unx163grid 1024 行齐备 + 边界锚点。
fn check_c1_t163_grid() -> bool {
    let mut ok = unx163grid_COUNT == 1024;
    if ok {
        ok = unx163grid_get("UN0000") == Some(0) && unx163grid_get("UN1023") == Some(1023);
    }
    if ok {
        ok = unx163grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t163_sum() -> bool {
    unx163grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t163_checks() -> CheckSet {
    let mut set = CheckSet::new("T163");
    set.add(
        "t163-seg-guard",
        t163_guard_seg(),
        if t163_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t163-c1-grid",
        check_c1_t163_grid(),
        if check_c1_t163_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t163-c2-grid-sum",
        check_c2_t163_sum(),
        if check_c2_t163_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

