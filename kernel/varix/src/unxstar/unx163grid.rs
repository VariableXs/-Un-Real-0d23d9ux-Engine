/// 段位守卫：全部诊断码必须落在本段 [0x4eb0, 0x4ebf]。
pub const fn t163_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t163Code::ALL.len() {
        let c = t163Code::ALL[i].code();
        if c < 0x4eb0 || c > 0x4ebf {
            ok = false;
        }
        i += 1;
    }
    ok
}

