/// 段位守卫：全部诊断码必须落在本段 [0x5ad0, 0x5adf]。
pub const fn u1741_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u1741Code::ALL.len() {
        let c = u1741Code::ALL[i].code();
        if c < 0x5ad0 || c > 0x5adf {
            ok = false;
        }
        i += 1;
    }
    ok
}

