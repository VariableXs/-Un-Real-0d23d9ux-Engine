/// 段位守卫：全部诊断码必须落在本段 [0x4810, 0x481f]。
pub const fn t592_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t592Code::ALL.len() {
        let c = t592Code::ALL[i].code();
        if c < 0x4810 || c > 0x481f {
            ok = false;
        }
        i += 1;
    }
    ok
}

