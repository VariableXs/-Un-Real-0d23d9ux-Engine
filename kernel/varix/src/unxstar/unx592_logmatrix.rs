/// 累计求和（守恒对账用）。
pub fn logmatrix_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < logmatrix_COUNT {
        s = s.wrapping_add(logmatrix[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn logmatrix_unique() -> bool {
    let mut i = 0usize;
    while i < logmatrix_COUNT {
        let mut j = i + 1;
        while j < logmatrix_COUNT {
            if logmatrix[i].0 == logmatrix[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

