// --------------------------------------------------------------------------
// 诊断码（t592 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 日志矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t592Code {
    /// 0x4810 组件非法（20 之外）。
    ComponentBad,
    /// 0x4811 级别非法（四级之外）。
    LevelBad,
    /// 0x4812 矩阵空洞（组合缺行）。
    MatrixHole,
    /// 0x4813 条目重复（同组合双记）。
    DupEntry,
    /// 0x4814 矩阵账破缺。
    LedgerBreak,
    /// 0x4815 矩阵序断档。
    OrderBreak,
    /// 0x4816 报告陈旧。
    ReportStale,
    /// 0x4817 守卫触发。
    GuardTripped,
    /// 0x4818 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4819 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x481a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x481b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x481c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x481d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x481e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

