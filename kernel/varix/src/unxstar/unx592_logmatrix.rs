// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t592_guard_seg() -> bool {
    t592_segment_guard()
}

/// 表 logmatrix 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t592_logmatrix_guard() -> bool {
    let mut ok = logmatrix_COUNT == 320;
    if ok {
        ok = logmatrix_scan() == 0;
    }
    if ok {
        ok = logmatrix_unique();
    }
    ok
}

/// 矩阵求和守恒（1..320 = 51360）。
fn check_c2_matrix_sum() -> bool {
    let mut ok = logmatrix_sum() == 51360;
    if ok {
        ok = logmatrix_get("M00_L0_U0") == Some(1) && logmatrix_get("M19_L3_U3") == Some(320);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t592_checks() -> CheckSet {
    let mut set = CheckSet::new("T592");
    set.add(
        "t592-seg-guard",
        t592_guard_seg(),
        if t592_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t592-c1-matrix-guard",
        check_t592_logmatrix_guard(),
        if check_t592_logmatrix_guard() { "" } else { "table logmatrix guard mismatch" },
    );
    set.add(
        "t592-c2-matrix-sum",
        check_c2_matrix_sum(),
        if check_c2_matrix_sum() { "" } else { "log matrix sum mismatch" },
    );
    set
}

