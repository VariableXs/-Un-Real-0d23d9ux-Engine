pub const U1861_SEG_BASE: u16 = 0x5f40;

// --------------------------------------------------------------------------

// 诊断码（U1861_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U1861_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u1861Code {
    /// 0x5f40 单元格重复（跳段 同键双占）。
    CellDup = 0x5f40,
    /// 0x5f41 单元格断档（应答缺失 序号不连续）。
    CellGap = 0x5f41,
    /// 0x5f42 索引越界（广播漏核）。
    IndexOob = 0x5f42,
    /// 0x5f43 大表账破缺（行数≠登记值）。
    LedgerBreak = 0x5f43,
    /// 0x5f44 表序断档。
    OrderBreak = 0x5f44,
    /// 0x5f45 累计漂移（求和≠理论值）。
    SumDrift = 0x5f45,
    /// 0x5f46 掩码非法。
    MaskBad = 0x5f46,
    /// 0x5f47 守卫触发。
    GuardTripped = 0x5f47,
    /// 0x5f48 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0x5f48,
    /// 0x5f49 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0x5f49,
    /// 0x5f4a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0x5f4a,
    /// 0x5f4b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0x5f4b,
}

impl u1861Code {
    /// 全量闭集。
    pub const ALL: [u1861Code; 12] = [
        u1861Code::CellDup,
        u1861Code::CellGap,
        u1861Code::IndexOob,
        u1861Code::LedgerBreak,
        u1861Code::OrderBreak,
        u1861Code::SumDrift,
        u1861Code::MaskBad,
        u1861Code::GuardTripped,
        u1861Code::LedgerBroken,
        u1861Code::SnapshotFingerprint,
        u1861Code::TableBroken,
        u1861Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U1861CODE_NAMES[(self.code() - U1861_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U1861CODE_SUGGESTIONS[(self.code() - U1861_SEG_BASE) as usize]
    }
}

