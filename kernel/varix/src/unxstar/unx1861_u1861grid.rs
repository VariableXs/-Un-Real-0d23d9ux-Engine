/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn u1861grid_unique() -> bool {
    let mut i = 0usize;
    while i < u1861grid_COUNT {
        let mut j = i + 1;
        while j < u1861grid_COUNT {
            if u1861grid[i].0 == u1861grid[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

