/// 段位守卫：全部诊断码必须落在本段 [0x3810, 0x381f]。
pub const fn t222_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t222Code::ALL.len() {
        let c = t222Code::ALL[i].code();
        if c < 0x3810 || c > 0x381f {
            ok = false;
        }
        i += 1;
    }
    ok
}

