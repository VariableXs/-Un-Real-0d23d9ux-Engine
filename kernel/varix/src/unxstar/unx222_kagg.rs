/// 段位守卫：全部诊断码落在本模块段内。
fn t222_guard_seg() -> bool {
    t222_segment_guard()
}

/// 表 agg_grid 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t222_agg_grid_guard() -> bool {
    let mut ok = agg_grid_COUNT == 300;
    if ok {
        ok = agg_grid_scan() == 0;
    }
    if ok {
        ok = agg_grid_unique();
    }
    ok
}

/// 达成线核算：300 行网格 + 求和 = 45150（1..300 和）。
fn check_c2_total_line() -> bool {
    let mut ok = agg_grid_COUNT == 300 && agg_grid_scan() == 0;
    if ok {
        // 1..300 等差和 = 300*301/2 = 45150。
        ok = agg_grid_sum() == 45150;
    }
    if ok {
        ok = agg_grid_get("B15_20") == Some(300) && agg_grid_get("B01_01") == Some(1);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t222_checks() -> CheckSet {
    let mut set = CheckSet::new("T222");
    set.add(
        "t222-seg-guard",
        t222_guard_seg(),
        if t222_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t222-c1-grid-guard",
        check_t222_agg_grid_guard(),
        if check_t222_agg_grid_guard() { "" } else { "table agg_grid guard mismatch" },
    );
    set.add(
        "t222-c2-total-line",
        check_c2_total_line(),
        if check_c2_total_line() { "" } else { "300-line total mismatch" },
    );
    set
}

