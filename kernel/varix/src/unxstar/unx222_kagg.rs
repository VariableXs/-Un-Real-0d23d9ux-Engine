// --------------------------------------------------------------------------
/// 聚合引擎诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t222Code {
    /// 0x3810 聚合缺口（实际数 < 达成线 300）。
    AggShort,
    /// 0x3811 聚合超员（实际数 > 上限）。
    AggOver,
    /// 0x3812 批次重复聚合（同批双聚）。
    BatchDup,
    /// 0x3813 槽位断档（批内序号不连续）。
    SlotGap,
    /// 0x3814 计数账破缺（声明≠实际）。
    CountLedgerBreak,
    /// 0x3815 波次饿死（等降级超时）。
    WaveStarve,
    /// 0x3816 聚合序折叠（批次序乱）。
    OrderFold,
    /// 0x3817 达成线漏计（跨批号漏算）。
    LineMissed,
    /// 0x3818 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x3819 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x381a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x381b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x381c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x381d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x381e 守卫触发（重入/越限被拒）。
    GuardTripped,
    /// 0x381f 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

