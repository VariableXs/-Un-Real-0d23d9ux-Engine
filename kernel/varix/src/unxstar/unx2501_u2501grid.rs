/// 段位守卫：全部诊断码必须落在本段 [0xa440, 0xa44f]。
pub const fn u2501_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2501Code::ALL.len() {
        let c = u2501Code::ALL[i].code();
        if c < 0xa440 || c > 0xa44f {
            ok = false;
        }
        i += 1;
    }
    ok
}

