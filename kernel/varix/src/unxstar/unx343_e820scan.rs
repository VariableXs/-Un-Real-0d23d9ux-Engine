/// E820 扫描诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t343Code {
    /// 0x3f20 输入段重复。
    InputDup,
    /// 0x3f21 输入断档（基址不连续）。
    InputGap,
    /// 0x3f22 类型与明细账不符。
    TypeMismatch,
    /// 0x3f23 扫描越界（超出 128 段）。
    ScanOob,
    /// 0x3f24 明细账破缺。
    LedgerBreak,
    /// 0x3f25 对齐违例。
    AlignBad,
    /// 0x3f26 段序断档。
    OrderBreak,
    /// 0x3f27 守卫触发。
    GuardTripped,
    /// 0x3f28 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x3f29 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x3f2a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x3f2b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x3f2c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x3f2d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x3f2e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

