/// 段位守卫：全部诊断码落在本模块段内。
fn t343_guard_seg() -> bool {
    t343_segment_guard()
}

/// 表 e820scan 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t343_e820scan_guard() -> bool {
    let mut ok = e820scan_COUNT == 128;
    if ok {
        ok = e820scan_scan() == 0;
    }
    if ok {
        ok = e820scan_unique();
    }
    ok
}

/// 扫描段求和（128 段基址总额）。
fn check_c2_scan_sum() -> bool {
    let mut ok = e820scan_COUNT == 128 && e820scan_unique();
    if ok {
        ok = e820scan_get("IN000") == Some(0x100000);
    }
    ok
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t343_checks() -> CheckSet {
    let mut set = CheckSet::new("T343");
    set.add(
        "t343-seg-guard",
        t343_guard_seg(),
        if t343_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t343-c1-scan-guard",
        check_t343_e820scan_guard(),
        if check_t343_e820scan_guard() { "" } else { "table e820scan guard mismatch" },
    );
    set.add(
        "t343-c2-scan-sum",
        check_c2_scan_sum(),
        if check_c2_scan_sum() { "" } else { "e820 scan table mismatch" },
    );
    set
}

