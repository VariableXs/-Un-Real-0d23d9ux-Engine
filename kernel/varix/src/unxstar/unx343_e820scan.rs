/// 段位守卫：全部诊断码必须落在本段 [0x3f20, 0x3f2f]。
pub const fn t343_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t343Code::ALL.len() {
        let c = t343Code::ALL[i].code();
        if c < 0x3f20 || c > 0x3f2f {
            ok = false;
        }
        i += 1;
    }
    ok
}

