/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn e820scan_unique() -> bool {
    let mut i = 0usize;
    while i < e820scan_COUNT {
        let mut j = i + 1;
        while j < e820scan_COUNT {
            if e820scan[i].0 == e820scan[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

