/// 段位守卫：全部诊断码必须落在本段 [0x4d90, 0x4d9f]。
pub const fn t142_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t142Code::ALL.len() {
        let c = t142Code::ALL[i].code();
        if c < 0x4d90 || c > 0x4d9f {
            ok = false;
        }
        i += 1;
    }
    ok
}

