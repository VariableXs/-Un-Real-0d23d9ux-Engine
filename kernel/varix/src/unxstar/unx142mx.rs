// --------------------------------------------------------------------------
/// GPT/ESP 镜像域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t142Code {
    /// 0x4d90 矩阵行重复。
    RowDup,
    /// 0x4d91 矩阵断档。
    RowGap,
    /// 0x4d92 行守卫破缺。
    GuardBreak,
    /// 0x4d93 矩阵累计漂移。
    SumDrift,
    /// 0x4d94 索引错位。
    IndexMisaligned,
    /// 0x4d95 矩阵账破缺。
    LedgerBreak,
    /// 0x4d96 矩阵序断档。
    OrderBreak,
    /// 0x4d97 守卫触发。
    GuardTripped,
    /// 0x4d98 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x4d99 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x4d9a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x4d9b 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x4d9c 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x4d9d 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

