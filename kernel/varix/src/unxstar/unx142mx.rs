/// 段位守卫：全部诊断码落在本模块段内。
fn t142_guard_seg() -> bool {
    t142_segment_guard()
}

/// 表 imgmx 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t142_imgmx_guard() -> bool {
    let mut ok = imgmx_COUNT == 512;
    if ok {
        ok = imgmx_scan() == 0;
    }
    if ok {
        ok = imgmx_unique();
    }
    ok
}

/// 矩阵累计守恒（0..511 = 130816）。
fn check_c2_t142_mxsum() -> bool {
    imgmx_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t142_checks() -> CheckSet {
    let mut set = CheckSet::new("T142");
    set.add(
        "t142-seg-guard",
        t142_guard_seg(),
        if t142_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t142-c1-mx-guard",
        check_t142_imgmx_guard(),
        if check_t142_imgmx_guard() { "" } else { "table imgmx guard mismatch" },
    );
    set.add(
        "t142-c2-mx-sum",
        check_c2_t142_mxsum(),
        if check_c2_t142_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

