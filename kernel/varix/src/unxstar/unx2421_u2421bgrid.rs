// --------------------------------------------------------------------------

// 诊断码（U2421_SEG_BASE 十六码 · 12 枚互斥 + segment_guard；判别值显式冻结为码值）
// --------------------------------------------------------------------------
/// U2421_SEG_BASE 域诊断码（判别值 = 十六码，与声明序恒等）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u2421Code {
    /// 0xa160 单元格重复（快径旁落 同键双占）。
    CellDup = 0xa160,
    /// 0xa161 单元格断档（时延超标 序号不连续）。
    CellGap = 0xa161,
    /// 0xa162 索引越界（比值越界）。
    IndexOob = 0xa162,
    /// 0xa163 大表账破缺（行数≠登记值）。
    LedgerBreak = 0xa163,
    /// 0xa164 表序断档。
    OrderBreak = 0xa164,
    /// 0xa165 累计漂移（求和≠理论值）。
    SumDrift = 0xa165,
    /// 0xa166 掩码非法。
    MaskBad = 0xa166,
    /// 0xa167 守卫触发。
    GuardTripped = 0xa167,
    /// 0xa168 台账不守恒（守恒恒等式破缺）。
    LedgerBroken = 0xa168,
    /// 0xa169 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint = 0xa169,
    /// 0xa16a 常量表破坏（表项与语义规则矛盾）。
    TableBroken = 0xa16a,
    /// 0xa16b 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard = 0xa16b,
}

impl u2421Code {
    /// 全量闭集。
    pub const ALL: [u2421Code; 12] = [
        u2421Code::CellDup,
        u2421Code::CellGap,
        u2421Code::IndexOob,
        u2421Code::LedgerBreak,
        u2421Code::OrderBreak,
        u2421Code::SumDrift,
        u2421Code::MaskBad,
        u2421Code::GuardTripped,
        u2421Code::LedgerBroken,
        u2421Code::SnapshotFingerprint,
        u2421Code::TableBroken,
        u2421Code::SegmentGuard,
    ];

    /// 码值（判别值显式冻结为码值；as 直达与原 match 逐变体码值对拍全等，零分支零 panic）。
    pub const fn code(self) -> u16 {
        self as u16
    }

    /// 中文诊断名（查表直达：12 臂派发单点归并于 code()，名称表序与 ALL 恒等）。
    pub const fn name(self) -> &'static str {
        U2421CODE_NAMES[(self.code() - U2421_SEG_BASE) as usize]
    }

    /// 可操作修复建议（查表直达，建议表序与 ALL 恒等）。
    pub const fn suggestion(self) -> &'static str {
        U2421CODE_SUGGESTIONS[(self.code() - U2421_SEG_BASE) as usize]
    }
}

