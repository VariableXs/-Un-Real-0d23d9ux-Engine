/// 段位守卫：全部诊断码必须落在本段 [0xe250, 0xe25f]。
pub const fn u2821_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u2821Code::ALL.len() {
        let c = u2821Code::ALL[i].code();
        if c < 0xe250 || c > 0xe25f {
            ok = false;
        }
        i += 1;
    }
    ok
}

