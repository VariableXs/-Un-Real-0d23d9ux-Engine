/// 段位守卫：全部诊断码落在本模块段内。
fn u2821_guard_seg() -> bool {
    u2821_segment_guard()
}

/// UNX-F2821 mx 512 行齐备 + 边界锚 + 键外拒收。
fn check_u2821_mx_count() -> bool {
    let mut ok = u2821mx_COUNT == 512;
    if ok { ok = u2821mx_get("AS0000") == Some(0) && u2821mx_get("HOT0511") == Some(47); }
    if ok { ok = u2821mx_get("ZZZ_NOKEY").is_none(); }
    ok
}

/// UNX-F2821 mx 累计守恒（理论值 24448）。
fn check_u2821_mx_sum() -> bool {
    u2821mx_sum() == 24448
}

/// UNX-F2821 mx 逐行守卫与唯一性全绿。
fn check_u2821_mx_guard() -> bool {
    u2821mx_scan() == 0 && u2821mx_unique()
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u2821_checks() -> CheckSet {
    let mut set = CheckSet::new("U2821");
    set.add(
        "u2821-seg-guard",
        u2821_guard_seg(),
        if u2821_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u2821-mx-count",
        check_u2821_mx_count(),
        if check_u2821_mx_count() { "" } else { "UNX-F2821 mx count mismatch" },
    );
    set.add(
        "u2821-mx-sum",
        check_u2821_mx_sum(),
        if check_u2821_mx_sum() { "" } else { "UNX-F2821 mx sum mismatch" },
    );
    set.add(
        "u2821-mx-guard",
        check_u2821_mx_guard(),
        if check_u2821_mx_guard() { "" } else { "UNX-F2821 mx guard mismatch" },
    );
    set
}

