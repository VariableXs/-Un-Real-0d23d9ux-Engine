/// 段位守卫：全部诊断码必须落在本段 [0x4680, 0x468f]。
pub const fn t571_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t571Code::ALL.len() {
        let c = t571Code::ALL[i].code();
        if c < 0x4680 || c > 0x468f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t571_guard_seg() -> bool {
    t571_segment_guard()
}

/// 大表 uart_cell 1024 行齐备 + 边界锚点 + 键外拒收。
fn check_c1_t571_grid() -> bool {
    let mut ok = uart_cell_COUNT == 1024;
    if ok {
        ok = uart_cell_get("UC0000") == Some(0) && uart_cell_get("UC1023") == Some(1023);
    }
    if ok {
        ok = uart_cell_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_t571_sum() -> bool {
    uart_cell_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t571_checks() -> CheckSet {
    let mut set = CheckSet::new("T571");
    set.add(
        "t571-seg-guard",
        t571_guard_seg(),
        if t571_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t571-c1-grid",
        check_c1_t571_grid(),
        if check_c1_t571_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "t571-c2-grid-sum",
        check_c2_t571_sum(),
        if check_c2_t571_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

