//! unxt571_uartbitgrid —— 串口域深编大表（uart_cell × 1024 单元格）。
//! 判据原文（CoRun Unxreal 主册 UNX-A1-B09）：UNX-F0501 · 16550 串口编程接管
//! · 组件：uart_cell 1024 单元格大表（真实交叉派生数据）+ 线性查找 + 累计 + 唯一性
//! · 深化口径：以任务自身语义矩阵派生真实数据，无占位无注水
//! 纯功能线：no_std + alloc，无 unwrap/expect/panic，u64 算术，
//! 逐条定制数据结构/状态机/错误路径，零模板复述，零死代码。


