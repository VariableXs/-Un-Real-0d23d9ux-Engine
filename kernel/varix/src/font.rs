/// Glyph rows for `c`, or an all-blank glyph for anything below 0x20 / above 0x7E.
pub fn glyph(c: u8) -> &'static [u8; 8] {
    if c < FIRST_CHAR || c as usize >= FIRST_CHAR as usize + FONT.len() {
        return &FONT[0]; // blank cell for control codes / non-ASCII
    }
    &FONT[(c - FIRST_CHAR) as usize]
}

/// Draw `c` into the surface at pixel (x, y), each font row doubled
/// (8x8 → 8x16 cell). Returns the cell width.
pub fn draw_char(
    surf: &crate::fb::Surface,
    x: i64,
    y: i64,
    c: u8,
    color: crate::fb::Color,
) -> u32 {
    let g = glyph(c);
    for row in 0..8usize {
        let bits = g[row];
        for col in 0..8 {
            if (bits >> col) & 1 == 1 {
                surf.set_px(x + col as i64, y + row as i64 * 2, color);
                surf.set_px(x + col as i64, y + row as i64 * 2 + 1, color);
            }
        }
    }
    GLYPH_W
}

/// Draw text (returns pixel width consumed).
pub fn draw_text(
    surf: &crate::fb::Surface,
    x: i64,
    y: i64,
    text: &str,
    color: crate::fb::Color,
) -> i64 {
    let mut cx = x;
    for &b in text.as_bytes() {
        draw_char(surf, cx, y, b, color);
        cx += GLYPH_W as i64;
    }
    cx - x
}

/// Scaled glyph draw for banner/logo text (integer scale, vertically doubled).
pub fn draw_char_scaled(
    surf: &crate::fb::Surface,
    x: i64,
    y: i64,
    c: u8,
    color: crate::fb::Color,
    scale: i64,
) {
    let g = glyph(c);
    for row in 0..8usize {
        let bits = g[row];
        for col in 0..8 {
            if (bits >> col) & 1 == 1 {
                surf.fill_rect(
                    x + col as i64 * scale,
                    y + row as i64 * scale * 2,
                    scale,
                    scale * 2,
                    color,
                );
            }
        }
    }
}

pub fn draw_text_scaled(
    surf: &crate::fb::Surface,
    x: i64,
    y: i64,
    text: &str,
    color: crate::fb::Color,
    scale: i64,
) {
    let mut cx = x;
    for &b in text.as_bytes() {
        draw_char_scaled(surf, cx, y, b, color, scale);
        cx += GLYPH_W as i64 * scale;
    }
}

/// Rendered pixel width of text at `scale`.
pub fn text_width_scaled(text: &str, scale: i64) -> i64 {
    text.len() as i64 * GLYPH_W as i64 * scale
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::fb::{Color, PixelFormat, Surface};
    use std::vec::Vec;

    fn surface(w: u32, h: u32) -> (Surface, Vec<u8>) {
        let mut v: Vec<u8> = std::vec![0u8; (w * h * 4) as usize];
        let s = unsafe { Surface::from_raw(v.as_mut_ptr(), w, h, w * 4, PixelFormat::Bgr32) };
        (s, v)
    }

    #[test]
    fn font_table_size() {
        assert_eq!(FONT.len(), 95);
        // First entry is the blank space glyph.
        assert_eq!(FONT[0], [0; 8]);
    }

    #[test]
    fn glyph_lookup() {
        assert_eq!(glyph(b'A'), &FONT[(b'A' - b' ') as usize]);
        assert_eq!(glyph(b'~'), &FONT[94]);
        // Control codes and 8-bit chars render blank, never panic.
        assert_eq!(glyph(0x00), &FONT[0]);
        assert_eq!(glyph(0x7F), &FONT[0]);
        assert_eq!(glyph(0xFF), &FONT[0]);
    }

    #[test]
    fn letter_a_shape() {
        // Known 'A' rows from the public-domain table.
        assert_eq!(
            glyph(b'A'),
            &[0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00]
        );
    }

    #[test]
    fn draw_char_lights_expected_pixels() {
        let (s, _b) = surface(64, 32);
        let white = Color::rgb(255, 255, 255);
        draw_char(&s, 0, 0, b'!', white);
        // '!' first row is 0x18 → columns 3,4 set; cell rows 0 and 1 doubled.
        assert_eq!(s.get_px(3, 0), Some(0xFFFFFF));
        assert_eq!(s.get_px(4, 0), Some(0xFFFFFF));
        assert_eq!(s.get_px(4, 1), Some(0xFFFFFF));
        assert_eq!(s.get_px(2, 0), Some(0));
        // Row 5 of '!' is blank.
        assert_eq!(s.get_px(3, 10), Some(0));
        assert_eq!(s.get_px(3, 11), Some(0));
    }

    #[test]
    fn draw_text_advances_by_glyph_width() {
        let (s, _b) = surface(256, 32);
        let w = draw_text(&s, 0, 0, "AB", Color::rgb(255, 255, 255));
        assert_eq!(w, 16);
        // 'B' starts at x=8; its first row 0x3F covers columns 0..5 of the glyph.
        assert_eq!(s.get_px(8 + 0, 0), Some(0xFFFFFF));
        assert_eq!(s.get_px(8 + 5, 0), Some(0xFFFFFF));
    }

    #[test]
    fn scaled_text_bounds() {
        assert_eq!(text_width_scaled("VARIX", 4), 5 * 8 * 4);
        let (s, _b) = surface(512, 256);
        draw_text_scaled(&s, 0, 0, "VARIX", Color::rgb(255, 255, 255), 4);
        // First V row 0x33: columns 0,1,4,5 scaled by 4 at 8x vertical.
        assert_eq!(s.get_px(0, 0), Some(0xFFFFFF));
        assert_eq!(s.get_px(5 * 4 - 1, 0), Some(0xFFFFFF));
        assert_eq!(s.get_px(4, 7), Some(0xFFFFFF)); // doubled row band
    }
}
