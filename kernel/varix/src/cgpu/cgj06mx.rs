/// 段位守卫：全部诊断码必须落在本段 [0x7090, 0x709f]。
pub const fn g06a_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < g06aCode::ALL.len() {
        let c = g06aCode::ALL[i].code();
        if c < 0x7090 || c > 0x709f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn g06a_guard_seg() -> bool {
    g06a_segment_guard()
}

/// 表 pwrmx 逐行守卫全绿（行数/守卫/唯一性）。
fn check_g06a_pwrmx_guard() -> bool {
    let mut ok = pwrmx_COUNT == 512;
    if ok {
        ok = pwrmx_scan() == 0;
    }
    if ok {
        ok = pwrmx_unique();
    }
    ok
}

/// 矩阵累计守恒（0..511 = 130816）。
fn check_c2_g06a_mxsum() -> bool {
    pwrmx_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_g06a_checks() -> CheckSet {
    let mut set = CheckSet::new("G06A");
    set.add(
        "g06a-seg-guard",
        g06a_guard_seg(),
        if g06a_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "g06a-c1-mx-guard",
        check_g06a_pwrmx_guard(),
        if check_g06a_pwrmx_guard() { "" } else { "table pwrmx guard mismatch" },
    );
    set.add(
        "g06a-c2-mx-sum",
        check_c2_g06a_mxsum(),
        if check_c2_g06a_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

