// --------------------------------------------------------------------------
// 诊断码（l04a 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 虚拟化探测域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum l04aCode {
    /// 0x7180 格重复（同键双占）。
    CellDup,
    /// 0x7181 格断档（序号不连续）。
    CellGap,
    /// 0x7182 索引越界（≥1024）。
    IndexOob,
    /// 0x7183 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x7184 表序断档。
    OrderBreak,
    /// 0x7185 累计漂移（求和≠523776）。
    SumDrift,
    /// 0x7186 掩码非法。
    MaskBad,
    /// 0x7187 守卫触发。
    GuardTripped,
    /// 0x7188 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x7189 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x718a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x718b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x718c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x718d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x718e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

