// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x7180, 0x718f]。
pub const fn l04a_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < l04aCode::ALL.len() {
        let c = l04aCode::ALL[i].code();
        if c < 0x7180 || c > 0x718f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn l04a_guard_seg() -> bool {
    l04a_segment_guard()
}

/// 大表 probgrid 1024 行齐备 + 边界锚点。
fn check_c1_l04a_grid() -> bool {
    let mut ok = probgrid_COUNT == 1024;
    if ok {
        ok = probgrid_get("PB0000") == Some(0) && probgrid_get("PB1023") == Some(1023);
    }
    if ok {
        ok = probgrid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_l04a_sum() -> bool {
    probgrid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_l04a_checks() -> CheckSet {
    let mut set = CheckSet::new("L04A");
    set.add(
        "l04a-seg-guard",
        l04a_guard_seg(),
        if l04a_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "l04a-c1-grid",
        check_c1_l04a_grid(),
        if check_c1_l04a_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "l04a-c2-grid-sum",
        check_c2_l04a_sum(),
        if check_c2_l04a_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

