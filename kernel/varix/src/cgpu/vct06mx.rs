/// 段位守卫：全部诊断码必须落在本段 [0x7290, 0x729f]。
pub const fn t06a_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < t06aCode::ALL.len() {
        let c = t06aCode::ALL[i].code();
        if c < 0x7290 || c > 0x729f {
            ok = false;
        }
        i += 1;
    }
    ok
}

