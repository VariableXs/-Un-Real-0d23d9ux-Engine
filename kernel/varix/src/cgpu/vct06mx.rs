/// 累计求和（守恒对账用）。
pub fn budmx_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < budmx_COUNT {
        s = s.wrapping_add(budmx[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn budmx_unique() -> bool {
    let mut i = 0usize;
    while i < budmx_COUNT {
        let mut j = i + 1;
        while j < budmx_COUNT {
            if budmx[i].0 == budmx[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

