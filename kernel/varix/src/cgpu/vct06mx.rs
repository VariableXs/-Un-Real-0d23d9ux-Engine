// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn t06a_guard_seg() -> bool {
    t06a_segment_guard()
}

/// 表 budmx 逐行守卫全绿（行数/守卫/唯一性）。
fn check_t06a_budmx_guard() -> bool {
    let mut ok = budmx_COUNT == 512;
    if ok {
        ok = budmx_scan() == 0;
    }
    if ok {
        ok = budmx_unique();
    }
    ok
}

/// 矩阵累计守恒（0..511 = 130816）。
fn check_c2_t06a_mxsum() -> bool {
    budmx_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_t06a_checks() -> CheckSet {
    let mut set = CheckSet::new("T06A");
    set.add(
        "t06a-seg-guard",
        t06a_guard_seg(),
        if t06a_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "t06a-c1-mx-guard",
        check_t06a_budmx_guard(),
        if check_t06a_budmx_guard() { "" } else { "table budmx guard mismatch" },
    );
    set.add(
        "t06a-c2-mx-sum",
        check_c2_t06a_mxsum(),
        if check_c2_t06a_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

