// --------------------------------------------------------------------------
// 诊断码（t06a 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 性能预算域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum t06aCode {
    /// 0x7280 格重复（同键双占）。
    CellDup,
    /// 0x7281 格断档（序号不连续）。
    CellGap,
    /// 0x7282 索引越界（≥1024）。
    IndexOob,
    /// 0x7283 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x7284 表序断档。
    OrderBreak,
    /// 0x7285 累计漂移（求和≠523776）。
    SumDrift,
    /// 0x7286 掩码非法。
    MaskBad,
    /// 0x7287 守卫触发。
    GuardTripped,
    /// 0x7288 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x7289 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x728a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x728b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x728c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x728d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x728e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

