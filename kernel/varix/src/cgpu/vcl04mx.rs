// --------------------------------------------------------------------------
// 诊断码（l04a 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 虚拟化探测域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum l04aCode {
    /// 0x7190 矩阵行重复。
    RowDup,
    /// 0x7191 矩阵断档。
    RowGap,
    /// 0x7192 行守卫破缺。
    GuardBreak,
    /// 0x7193 矩阵累计漂移。
    SumDrift,
    /// 0x7194 索引错位。
    IndexMisaligned,
    /// 0x7195 矩阵账破缺。
    LedgerBreak,
    /// 0x7196 矩阵序断档。
    OrderBreak,
    /// 0x7197 守卫触发。
    GuardTripped,
    /// 0x7198 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x7199 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x719a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x719b 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x719c 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x719d 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

