/// 累计求和（守恒对账用）。
pub fn probmx_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < probmx_COUNT {
        s = s.wrapping_add(probmx[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn probmx_unique() -> bool {
    let mut i = 0usize;
    while i < probmx_COUNT {
        let mut j = i + 1;
        while j < probmx_COUNT {
            if probmx[i].0 == probmx[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

