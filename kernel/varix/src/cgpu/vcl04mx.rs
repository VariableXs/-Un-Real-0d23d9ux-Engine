// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x7190, 0x719f]。
pub const fn l04a_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < l04aCode::ALL.len() {
        let c = l04aCode::ALL[i].code();
        if c < 0x7190 || c > 0x719f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn l04a_guard_seg() -> bool {
    l04a_segment_guard()
}

/// 表 probmx 逐行守卫全绿（行数/守卫/唯一性）。
fn check_l04a_probmx_guard() -> bool {
    let mut ok = probmx_COUNT == 512;
    if ok {
        ok = probmx_scan() == 0;
    }
    if ok {
        ok = probmx_unique();
    }
    ok
}

/// 矩阵累计守恒（0..511 = 130816）。
fn check_c2_l04a_mxsum() -> bool {
    probmx_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_l04a_checks() -> CheckSet {
    let mut set = CheckSet::new("L04A");
    set.add(
        "l04a-seg-guard",
        l04a_guard_seg(),
        if l04a_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "l04a-c1-mx-guard",
        check_l04a_probmx_guard(),
        if check_l04a_probmx_guard() { "" } else { "table probmx guard mismatch" },
    );
    set.add(
        "l04a-c2-mx-sum",
        check_c2_l04a_mxsum(),
        if check_c2_l04a_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

