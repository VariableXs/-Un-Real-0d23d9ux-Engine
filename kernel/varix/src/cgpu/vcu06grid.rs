// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x7480, 0x748f]。
pub const fn g06c_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < g06cCode::ALL.len() {
        let c = g06cCode::ALL[i].code();
        if c < 0x7480 || c > 0x748f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn g06c_guard_seg() -> bool {
    g06c_segment_guard()
}

/// 大表 vcu06grid 1024 行齐备 + 边界锚点。
fn check_c1_g06c_grid() -> bool {
    let mut ok = vcu06grid_COUNT == 1024;
    if ok {
        ok = vcu06grid_get("VC0000") == Some(0) && vcu06grid_get("VC1023") == Some(1023);
    }
    if ok {
        ok = vcu06grid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_g06c_sum() -> bool {
    vcu06grid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_g06c_checks() -> CheckSet {
    let mut set = CheckSet::new("G06C");
    set.add(
        "g06c-seg-guard",
        g06c_guard_seg(),
        if g06c_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "g06c-c1-grid",
        check_c1_g06c_grid(),
        if check_c1_g06c_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "g06c-c2-grid-sum",
        check_c2_g06c_sum(),
        if check_c2_g06c_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

