/// 段位守卫：全部诊断码必须落在本段 [0x7390, 0x739f]。
pub const fn u05a_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u05aCode::ALL.len() {
        let c = u05aCode::ALL[i].code();
        if c < 0x7390 || c > 0x739f {
            ok = false;
        }
        i += 1;
    }
    ok
}

