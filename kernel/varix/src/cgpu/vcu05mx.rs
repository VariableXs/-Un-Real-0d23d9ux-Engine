// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u05a_guard_seg() -> bool {
    u05a_segment_guard()
}

/// 表 runmx 逐行守卫全绿（行数/守卫/唯一性）。
fn check_u05a_runmx_guard() -> bool {
    let mut ok = runmx_COUNT == 512;
    if ok {
        ok = runmx_scan() == 0;
    }
    if ok {
        ok = runmx_unique();
    }
    ok
}

/// 矩阵累计守恒（0..511 = 130816）。
fn check_c2_u05a_mxsum() -> bool {
    runmx_sum() == 130816
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u05a_checks() -> CheckSet {
    let mut set = CheckSet::new("U05A");
    set.add(
        "u05a-seg-guard",
        u05a_guard_seg(),
        if u05a_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u05a-c1-mx-guard",
        check_u05a_runmx_guard(),
        if check_u05a_runmx_guard() { "" } else { "table runmx guard mismatch" },
    );
    set.add(
        "u05a-c2-mx-sum",
        check_c2_u05a_mxsum(),
        if check_c2_u05a_mxsum() { "" } else { "matrix sum mismatch" },
    );
    set
}

