// --------------------------------------------------------------------------
// 诊断码（u05a 十六码 · 14 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 基准运行器域矩阵诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u05aCode {
    /// 0x7390 矩阵行重复。
    RowDup,
    /// 0x7391 矩阵断档。
    RowGap,
    /// 0x7392 行守卫破缺。
    GuardBreak,
    /// 0x7393 矩阵累计漂移。
    SumDrift,
    /// 0x7394 索引错位。
    IndexMisaligned,
    /// 0x7395 矩阵账破缺。
    LedgerBreak,
    /// 0x7396 矩阵序断档。
    OrderBreak,
    /// 0x7397 守卫触发。
    GuardTripped,
    /// 0x7398 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x7399 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x739a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x739b 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x739c 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x739d 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

