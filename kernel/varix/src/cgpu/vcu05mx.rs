/// 累计求和（守恒对账用）。
pub fn runmx_sum() -> u64 {
    let mut s = 0u64;
    let mut i = 0usize;
    while i < runmx_COUNT {
        s = s.wrapping_add(runmx[i].1 as u64);
        i += 1;
    }
    s
}

/// 键唯一性（构造期断言等价物：逐对扫描同键）。
pub fn runmx_unique() -> bool {
    let mut i = 0usize;
    while i < runmx_COUNT {
        let mut j = i + 1;
        while j < runmx_COUNT {
            if runmx[i].0 == runmx[j].0 {
                return false;
            }
            j += 1;
        }
        i += 1;
    }
    true
}

