// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x7080, 0x708f]。
pub const fn g06a_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < g06aCode::ALL.len() {
        let c = g06aCode::ALL[i].code();
        if c < 0x7080 || c > 0x708f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn g06a_guard_seg() -> bool {
    g06a_segment_guard()
}

/// 大表 pwrgrid 1024 行齐备 + 边界锚点。
fn check_c1_g06a_grid() -> bool {
    let mut ok = pwrgrid_COUNT == 1024;
    if ok {
        ok = pwrgrid_get("PG0000") == Some(0) && pwrgrid_get("PG1023") == Some(1023);
    }
    if ok {
        ok = pwrgrid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_g06a_sum() -> bool {
    pwrgrid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_g06a_checks() -> CheckSet {
    let mut set = CheckSet::new("G06A");
    set.add(
        "g06a-seg-guard",
        g06a_guard_seg(),
        if g06a_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "g06a-c1-grid",
        check_c1_g06a_grid(),
        if check_c1_g06a_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "g06a-c2-grid-sum",
        check_c2_g06a_sum(),
        if check_c2_g06a_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

