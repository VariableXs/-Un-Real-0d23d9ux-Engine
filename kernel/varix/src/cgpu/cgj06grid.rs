// --------------------------------------------------------------------------
// 诊断码（g06a 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 功耗分账域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum g06aCode {
    /// 0x7080 格重复（同键双占）。
    CellDup,
    /// 0x7081 格断档（序号不连续）。
    CellGap,
    /// 0x7082 索引越界（≥1024）。
    IndexOob,
    /// 0x7083 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x7084 表序断档。
    OrderBreak,
    /// 0x7085 累计漂移（求和≠523776）。
    SumDrift,
    /// 0x7086 掩码非法。
    MaskBad,
    /// 0x7087 守卫触发。
    GuardTripped,
    /// 0x7088 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x7089 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x708a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x708b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x708c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x708d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x708e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

