// --------------------------------------------------------------------------
// 诊断码（u05a 十六码 · 15 枚互斥 + segment_guard）
// --------------------------------------------------------------------------
/// 基准运行器域大表诊断码。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum u05aCode {
    /// 0x7380 格重复（同键双占）。
    CellDup,
    /// 0x7381 格断档（序号不连续）。
    CellGap,
    /// 0x7382 索引越界（≥1024）。
    IndexOob,
    /// 0x7383 大表账破缺（行数≠1024）。
    LedgerBreak,
    /// 0x7384 表序断档。
    OrderBreak,
    /// 0x7385 累计漂移（求和≠523776）。
    SumDrift,
    /// 0x7386 掩码非法。
    MaskBad,
    /// 0x7387 守卫触发。
    GuardTripped,
    /// 0x7388 台账不守恒（守恒恒等式破缺）。
    LedgerBroken,
    /// 0x7389 快照指纹不符（字段被改后重算不一致）。
    SnapshotFingerprint,
    /// 0x738a 常量表破坏（表项与语义规则矛盾）。
    TableBroken,
    /// 0x738b 索引错位（枚举序与矩阵序不一致）。
    IndexMisaligned,
    /// 0x738c 条目重复（同键双写）。
    DuplicateEntry,
    /// 0x738d 次序违例（依赖序/时序破缺）。
    OrderViolated,
    /// 0x738e 段位守卫失败（诊断码越出本模块段）。
    SegmentGuard,
}

