// 段位守卫（本模块独立十六进码前缀防串段；越界即判红）
// ---------------------------------------------------------------------------

/// 段位守卫：全部诊断码必须落在本段 [0x7380, 0x738f]。
pub const fn u05a_segment_guard() -> bool {
    let mut ok = true;
    let mut i = 0usize;
    while i < u05aCode::ALL.len() {
        let c = u05aCode::ALL[i].code();
        if c < 0x7380 || c > 0x738f {
            ok = false;
        }
        i += 1;
    }
    ok
}

// --------------------------------------------------------------------------
// 自检（CheckSet 范式：每检查一带 detail，全绿才出门）
// --------------------------------------------------------------------------
/// 段位守卫：全部诊断码落在本模块段内。
fn u05a_guard_seg() -> bool {
    u05a_segment_guard()
}

/// 大表 rungrid 1024 行齐备 + 边界锚点。
fn check_c1_u05a_grid() -> bool {
    let mut ok = rungrid_COUNT == 1024;
    if ok {
        ok = rungrid_get("RG0000") == Some(0) && rungrid_get("RG1023") == Some(1023);
    }
    if ok {
        ok = rungrid_get("ZZZ_NOKEY").is_none();
    }
    ok
}

/// 大表累计守恒（0..1023 = 523776）。
fn check_c2_u05a_sum() -> bool {
    rungrid_sum() == 523776
}

/// 本模块自检（逐检查带 detail，全绿才出门）。
pub fn run_u05a_checks() -> CheckSet {
    let mut set = CheckSet::new("U05A");
    set.add(
        "u05a-seg-guard",
        u05a_guard_seg(),
        if u05a_guard_seg() { "" } else { "diagnostic code outside segment" },
    );
    set.add(
        "u05a-c1-grid",
        check_c1_u05a_grid(),
        if check_c1_u05a_grid() { "" } else { "big table grid mismatch" },
    );
    set.add(
        "u05a-c2-grid-sum",
        check_c2_u05a_sum(),
        if check_c2_u05a_sum() { "" } else { "big table sum mismatch" },
    );
    set
}

