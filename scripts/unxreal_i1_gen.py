    total = 0
    all_ids, all_jids = [], []
    for bid, (theme, entries0) in BATCHES:
        entries = list(entries0)
        s19 = sum(r for _, r, _ in entries[:19])
        entries[19] = (entries[19][0], 6000 - s19, entries[19][2])
