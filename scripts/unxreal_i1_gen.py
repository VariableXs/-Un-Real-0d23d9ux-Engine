def gen_batch_md(bid, theme, entries):
    entries = list(entries)
    assert len(entries) == 20, f"{bid} 条数 {len(entries)} != 20"
    s19 = sum(r for _, r, _ in entries[:19])
    diff = 6000 - s19
    assert 120 <= diff <= 600, f"{bid} 末条配平 {diff} 越界 [120,600]"
    t, r, c = entries[19]
    if r != diff:
        print(f"配平留痕 {bid}: 末条 {r}→{diff}（批内差额承载位，承 R-A1-004 配平判例）")
        entries[19] = (t, diff, c)
    first_id = 32001 + (int(bid[1:]) - 1) * 20
    last_id = first_id + 19
    rows = []
    rows.append(f"# UNX-I1-{bid} · {theme}（UNX-F{first_id}–F{last_id} · 20 条）\n")
    rows.append("> AI-41 承办（波 16 首产段立账 · 一次对话 300 项新功能明令）｜批主题：" + theme +
        "｜域账累计：" + f"{(int(bid[1:]))*6000:,} / 240,000" +
        "｜判据主轴：iperf 吞吐时延对标（J1/J2 真机随闸门补测）、netfilter 类规则命中（J3 与 AI-50 联签）｜嫁接源：任务书六专题（RFC 系列参照 · 纯自研域无外部嫁接件，引用注明 RFC 编号，防幻觉条款 §40 全程）｜防重：五范围 grep 终报随批收口落盘（TCP/netfilter/conntrack/NAT/分片关键词族——任务书指定），域 ID F32001–F32800 与已收口域零撞号｜上游：AI-02（MSI-X IrqBackend::bind_vector——B08 消费，未收口面 Schema 先行+fake+open_risks R-I1-001）、AI-03（软中断调度与每核队列绑定 R-I1-002）、AI-04（DMA 一致性内存 R-I1-003）｜下游：AI-42（帧递送回调，波 16 Q3 冻结）、AI-43（route_lookup 路由查询钩子）、AI-50（五钩子+conntrack 导出账双向联签）｜红线声明：本批无引导设施红线与硬件数据安全红线触发条目；域内加严红线——「错误路径不停轮询」违例即 P0；接管红线——net.rs 3,908 行升级接管不删除存量文件与测试，退役范围与 AI-98 联签；真机判据随闸门补测（R-I1-004，开发期零 QEMU 零实机写）\n")
    for k, (title, r, crit) in enumerate(entries):
        fid = first_id + k
        rows.append(f"### UNX-F{fid} · {title}")
        rows.append(f"- 域/批：I1/{bid}｜纯功能行数：{r}｜状态：[骨架]｜判据：{crit}")
    return "\n".join(rows) + "\n"

