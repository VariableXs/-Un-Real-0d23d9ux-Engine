def emit_batches():
    os.makedirs(BATCH_DIR, exist_ok=True)
    total = 0
    for bid, theme, entries in BATCHES:
        assert len(entries) == 20, bid
        rows = sum(e[1] for e in entries)
        assert rows == 6000, (bid, rows)
        path = os.path.join(BATCH_DIR, f"UNX-H3-{bid}.md")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(batch_header(bid, theme))
            base = 29601 + (BATCH_NO[bid] - 1) * 20
            for i, (name, r, crit) in enumerate(entries):
                fid = base + i
                f.write(f"### UNX-F{fid} · {name}\n")
                f.write(f"- 域/批：H3/{bid}｜纯功能行数：{r}｜状态：[骨架]｜判据：{crit}\n")
        total += rows
    assert total == 90000
    print(f"batches: 15 files, {total} rows OK")

