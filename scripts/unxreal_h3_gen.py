def _normalize():
    """批内配平（§6.1 步骤 3）：批内求和必须 = 6,000。差额配平到首条（120–600 区间内），
    配平结果打印留痕（收口时随批头登记）。"""
    for bid, theme, entries in BATCHES:
        d = 6000 - sum(r for _, r, _ in entries)
        if d == 0:
            continue
        name, r, crit = entries[0]
        nr = r + d
        assert 120 <= nr <= 600, (bid, nr)
        entries[0] = (name, nr, crit)
        print(f"balance {bid}: first entry {r} -> {nr} ({'+' if d>0 else ''}{d})")

