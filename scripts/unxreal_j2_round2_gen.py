    if "--stdout" in sys.argv:
        sys.stdout.write(build())
        return
    text = "\n" + build()
    # 五断言自检
    t = build()
    ids = [int(x) for x in re.findall(r"### UNX-F(\d+) · ", t)]
    assert ids == list(range(LO, HI + 1)), "断言1 ID 连续"
    assert len(ids) == 500, "断言2 条数 500"
    per = {}
    cur = None
    for line in t.splitlines():
        m = re.match(r"^# UNX-J2-B(\d{2}) · ", line)
        if m: cur = int(m.group(1)); per[cur] = 0
        m2 = re.match(r"^- 域/批：J2/B(\d{2})｜纯功能行数：(\d+)｜", line)
        if m2: per[int(m2.group(1))] += int(m2.group(2))
    assert all(v == 6000 for v in per.values()) and len(per) == 25, "断言3 批批 6,000"
    assert sum(per.values()) == 150000, "断言4 总 150,000"
    cr = re.findall(r"UNX-F(\d+)-J1", t)
    assert len(cr) == 500 and len(set(cr)) == 500, "断言5 判据唯一"
    print("GEN SELF-CHECK: ALL PASS (500 条/F37101–F37600 连续/25×6,000=150,000/判据 500 枚唯一)", file=sys.stderr)
    old = open(MD, encoding="utf-8").read()
    if "## 增补卷 · AI-47 · 二轮立账 J2 域 B16–B40" in old:
        print("SKIP：J2 二轮卷已存在，不重复追加", file=sys.stderr)
        return
    if not old.endswith("\n"):
        text = "\n" + text
    with open(MD, "a", encoding="utf-8", newline="") as f:
        f.write(text)

