def batch_header(n, theme, fid_lo, fid_hi, acc):
    return (f"# UNX-J2-B{n:02d} · {theme}\n"
            f"- 批 ID：UNX-J2-B{n:02d}｜域：J2 凭据与会话｜段：二轮立账（AI-47）\n"
            f"- ID 区间：UNX-F{fid_lo}–UNX-F{fid_hi}（20 条）｜纯功能行数合计：6,000｜累计：{acc:,} 行\n"
            f"- 主题：{theme}\n")

def build():
    out = [TIT, "> 二轮立账卷 · AI-47 · J2 域 B16–B40（F37101–F37600 · 500 条 · 25 批 × 6,000 = 150,000 行）",
           "> 承一卷《首产段 J2 域骨架立账》判例（AI-47）；ID 与一卷相接（F37100→F37101）无空洞无重叠；判据号 UNX-Fxxxx-J1 全域唯一；",
           "> 主题主线：凭据管理器深水→存储引擎→DPAPI 面→主钥深水→会话全景→令牌/UAC/服务/远程/锁屏→漫游→服务账户与 K1 桩退场（B29）→缓存验证器→桩域（卡/生物）→CredUI→审计/性能/fuzz/故障注入→跨域联签→ktest 全量→域闭账 800/800 满账封账（F37600 终钉）。",
           "> 与总纲 §7.3-J2、handoff J2 块、根台账四处对账；四红线（凭据零明文 X5/常数时间 J3 单点/哈希格式冻结/单一引擎）全程生效；真机判据一律随闸门补测（R-J2-002，开发期零 QEMU）。", ""]
    acc = 0
    fid = LO
    for n, (theme, entries) in enumerate(B, 16):
        assert len(entries) == PER, f"B{n} 条数 {len(entries)} != {PER}"
        s = sum(e[1] for e in entries)
        assert s == 6000, f"B{n} 行数 {s} != 6000"
        acc += s
        out.append(batch_header(n, theme, fid, fid + PER - 1, acc))
        out.append("")
        for t, ln, c in entries:
            out.append(entry(fid, n, t, ln, c))
            out.append("")
            fid += 1
    assert fid - 1 == HI, f"终 ID {fid-1} != {HI}"
    return "\n".join(out) + "\n"

