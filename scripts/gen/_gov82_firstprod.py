    diff = 6000 - sum(base)
    # 把差值摊到整批，保持 180–440 带内
    step = 1 if diff > 0 else -1
    j = 0
    while diff != 0:
        k = j % 20
        if 180 <= base[k] + step <= 440:
            base[k] += step
            diff -= step
        j += 1
    assert sum(base) == 6000 and all(180 <= x <= 440 for x in base), base
    return base

