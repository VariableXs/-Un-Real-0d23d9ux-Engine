def rows_for(idx, b):
    base = [200 + ((b * 17 + idx * 31) % 241) for idx in range(20)]
    diff = 6000 - sum(base)
    step = 1 if diff > 0 else -1
    j = 0
    while diff != 0:
        k = j % 20
        if 180 <= base[k] + step <= 440:
            base[k] += step; diff -= step
        j += 1
    assert sum(base) == 6000 and all(180 <= x <= 440 for x in base)
    return base

