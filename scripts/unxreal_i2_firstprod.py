def balance():
    """批内机检配平：差额全为 20 的倍数，从每批末条向前以步长 20 调整，钳位 [240,660]。
    H3 判例：批内配平差额留痕全部区间内。返回 {batch: [(idx, old, new)]}。"""
    led = {}
    global EB
    EB = [list(x) for x in E]
    for bi, (bname, _, start) in enumerate(BATCHES):
        delta = 6000 - sum(x[1] for x in EB[start:start+20])
        adj = []
        i = start + 19
        while delta != 0:
            step = 20 if delta > 0 else -20
            old = EB[i][1]
            new = old + step
            if 240 <= new <= 660:
                EB[i][1] = new
                adj.append((i, old, new))
                delta -= step
            i = i - 1 if i > start else start + 19
        led[bname] = adj
        print(f"balance {bname}: {len(adj)} entries adjusted, all within [240,660]")
    return led


