def build():
    out = io.StringIO()
    out.write(VOL_TITLE)
    out.write(VOL_PROOF)
    fid = 34701
    total_entries = 0
    total_rows = 0
    jset = set()
    for bi, data in BATCHES:
        # 配平收口条
        def remainder():
            return 6000 - sum(r for _, r, _ in data if r is not None)
        r = remainder()
        flex_idx = len(data) - 2
        while r > 680 or r < 190:
            adj = 20 if r > 680 else -20
            t, rr, j = data[flex_idx]
            if rr is None:
                flex_idx -= 1
                if flex_idx < 0:
                    raise SystemExit(f"batch {bi} balance failed")
                continue
            nv = rr + adj
            if nv < 190 or nv > 680:
                flex_idx -= 1
                if flex_idx < 0:
                    raise SystemExit(f"batch {bi} balance failed")
                continue
            data[flex_idx] = (t, nv, j)
            r = remainder()
        closed = []
        for (t, rr, j) in data:
            if rr is None:
                rr = remainder()
            closed.append((t, rr, j))
        data = closed
        out.write(header(bi, THEMES[bi], 6000 * bi))
        for (t, rr, j) in data:
            if t is None:
                t = f"B{bi:02d} 收口：段末端到端对账与配平收口"
            out.write(f"### UNX-F{fid:05d} · {t}\n")
