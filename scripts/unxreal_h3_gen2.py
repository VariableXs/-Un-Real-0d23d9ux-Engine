def first_id(bn):
    return 29901 + (bn - 16) * 20

def rebalance(rows_list):
    delta = 6000 - sum(rows_list)
    out = list(rows_list)
    out[0] += delta
    assert 120 <= out[0] <= 600, f"rebalance out of range: {out[0]} (delta {delta})"
    return out

