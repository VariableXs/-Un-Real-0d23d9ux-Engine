def check(text, ids, total):
    errs = []
    if len(ids) != 300: errs.append(f"条目数 {len(ids)} != 300")
    if ids != list(range(30401, 30701)): errs.append("ID 不连续或越界")
    if total != 90000: errs.append(f"行数合计 {total} != 90000")
    for i, fid in enumerate(ids):
        if f"UNX-F{fid}-J1" not in text: errs.append(f"缺判据号 UNX-F{fid}-J1")
    if text.count("| 增补 |") != 300: errs.append("增补状态行数 != 300")
    if errs:
        for e in errs: print("FAIL:", e)
        sys.exit(1)
    print(f"ALL PASS exit=0：300 条 / F30401–F30700 连续零跳号 / 90,000 行 / 15 批 × 6,000 行批账锁定 / 判据号一一对应")

