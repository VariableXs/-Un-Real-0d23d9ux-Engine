def balance(entries, bid="?"):
    entries = list(entries)
    s19 = sum(r for _, r, _ in entries[:19])
    diff = 6000 - s19
    # 配平：末条承载差额（钳制 120–600），越界部分由前 19 条轮转 ±20 承载（留痕）
    if not (120 <= diff <= 600):
        last = max(120, min(600, diff))
        delta = diff - last
        assert abs(delta) % 20 == 0, f"{bid} 配平差额非 20 倍数"
        entries[19] = (entries[19][0], last, entries[19][2])
        i = 0
        while delta != 0:
            t, r, c = entries[i % 19]
            step = 20 if delta > 0 else -20
            nr = r + step
            if 120 <= nr <= 600:
                entries[i % 19] = (t, nr, c)
                delta -= step
            i += 1
            assert i < 20000, f"{bid} 配平失败（差额 {delta}）"
        print(f"配平留痕 {bid}: 末条 {entries[19][1]}，前 19 条轮转承载 {diff-last}（R-A1-004 判例）")
    else:
        entries[19] = (entries[19][0], diff, entries[19][2])
    s = sum(r for _, r, _ in entries)
    assert s == 6000
    return entries

