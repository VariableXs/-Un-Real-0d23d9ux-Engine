def write_batch(idx, title, desc, entries, rows, cum):
    assert len(entries) == 20 and len(rows) == 20
    assert sum(rows) == 6000, (idx, sum(rows))
    fid0 = 6701 + (idx - 16) * 20
    lines = []
    lines.append('# UNX-B4-B%02d · %s（F%d–F%d · 20 条）' % (idx, title, fid0, fid0+19))
    lines.append('')
    lines.append('> AI-09 承办｜域账累计：%s + 本批 6,000 = %s / 240,000｜%s' % (format(cum-6000, ','), format(cum, ','), desc))
    lines.append('')
    for i, (name, crit) in enumerate(entries):
        fid = fid0 + i
        lines.append('### UNX-F%d · %s' % (fid, name))
        lines.append('- 域/批：B4/B%02d｜纯功能行数：%d｜状态：[骨架]｜判据：UNX-F%d-J1 %s' % (idx, rows[i], fid, crit))
    path = os.path.join(OUT, 'UNX-B4-B%02d.md' % idx)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(NL.join(lines) + NL)
    print('Wrote %s: 20 entries, %d rows' % (path, sum(rows)))

