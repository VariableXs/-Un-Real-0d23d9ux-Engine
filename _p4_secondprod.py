    fid = F0
    total = 0
    seg_rows = 0
    for bno, btype, btopic, items in BATCHES:
        assert len(items) == 20, bno
        bstart = fid
        rows_fixed = sum(r for _, r, _, _ in items if r is not None)
        rows_last = 6000 - rows_fixed
        assert 240 <= rows_last <= 800, (bno, rows_last)
        lines.append(f"## 批 UNX-P4-{bno}（UNX-F{bstart:05d}–UNX-F{bstart+19:05d} · {btype} · {btopic} · 6,000 行）\n")
