        lines.append("|---|---|---|---|---|")
        brows = 0
        for name, rows, judge, anchor in items:
            if rows is None:
                rows = rows_last
            crit = f"UNX-F{fid:05d}-J1 {judge}；判据锚定 {anchor}"
            lines.append(f"| UNX-F{fid:05d} | {name} | {rows} | 增补 | {crit} |")
