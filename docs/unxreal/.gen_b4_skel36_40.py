def auto_fix(es):
    """行数总和≠6000 时自动 ±20 微调（范围 257–337），返回修正后的列表。"""
    es = [list(x) for x in es]
    diff = 6000 - sum(e[2] for e in es)
    step = 20 if diff > 0 else -20
    i = 0
    while diff != 0 and i < len(es) * 50:
        e = es[i % len(es)]
        nr = e[2] + step
        if 257 <= nr <= 337:
            e[2] = nr
            diff -= step
        i += 1
    assert diff == 0, ('auto_fix failed', diff)
    return [tuple(e) for e in es]

def batch(idx, fid0, title, theme, es):
    es = auto_fix(es)
    assert len(es) == 20, (idx, len(es))
    rows = sum(r for _, _, r, _ in es)
    assert rows == 6000, (idx, rows)
    fids = [f for f, _, _, _ in es]
    assert fids == list(range(fid0, fid0 + 20)), (idx, fids[:3])
    cum0, cum1 = 180000 + 6000 * (idx - 31), 180000 + 6000 * (idx - 30)
    L = ['# UNX-B4-B%02d · %s（F%04d–F%04d · 20 条）' % (idx, title, fid0, fid0 + 19),
         '',
         '> AI-09 承办｜域账累计：%s + 本批 6,000 = %s / 240,000｜%s'
             % (format(cum0, ','), format(cum1, ','), theme),
         '']
    for f, name, r, judg in es:
        assert judg.startswith('UNX-F%04d-J1 ' % f), (f, judg[:40])
        L += ['### UNX-F%04d · %s' % (f, name),
              '- 域/批：B4/B%02d｜纯功能行数：%d｜状态：[骨架]｜判据：%s' % (idx, r, judg)]
    p = os.path.join(SK, 'UNX-B4-B%02d.md' % idx)
    io.open(p, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('B%02d OK: %d chars' % (idx, len('\n'.join(L))))

