def entry(book, i, eid, theme):
    if i == 19:
        name = "E%02d 收口：册内守恒与判据注册（%s）" % (book, theme)
        crit = "UNX-J2-E%03d-J1 册内求和 6,000 守恒精确断言；20 条判据注册全绿冒烟 <3min；未竟之账显性移交 E%02d" % (eid, book + 1 if book < BOOKS else BOOKS)
    elif i == 18:
        name = "E%02d 体验日志与异常显性化（%s 面指纹）" % (book, theme.split("：")[0])
        crit = "UNX-J2-E%03d-J1 本册主题面挫败指纹自动标记 ×10 注入全检出；三要素呈现 ×20 全对；异常零静默核（静默 catch 注入 ×10 全检出）；不记明文凭据断言" % eid
    elif i == 17:
        name = "E%02d 锁步回归总矩阵（%s 面剧本库）" % (book, theme.split("：")[-1])
        crit = "UNX-J2-E%03d-J1 锁步剧本 ≥30 个重放一致；差异逐点定位；fuzz 10^4 零崩溃零静默；种子库 ≥50" % eid
    elif i < 8:
        name, crit = TOPICS[book][i]
        crit = "UNX-J2-E%03d-J1 %s" % (eid, crit)
    else:
        base_name, base_crit = TOPICS[book][(i - 8) % 8]
        vn, vc = VARIANTS[(i - 8) // 8]
        name = "%s（%s）" % (base_name, vn)
        crit = "UNX-J2-E%03d-J1 %s：%s" % (eid, base_crit, vc)
    return name, 300, crit

