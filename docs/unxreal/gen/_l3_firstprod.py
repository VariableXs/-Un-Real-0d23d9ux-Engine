def render():
    problems = []
    all_ids, all_crits = [], []
    total_rows = 0
    vols = []
    for b in BATCHES:
        no, theme, adv, bnd, entries = b["no"], b["theme"], b["adv"], b["bnd"], b["entries"]
        assert len(entries) == 20, f"B{no:02d} entries != 20"
        if len(entries[0][1].split("：")[0]) == 0:
            problems.append(f"B{no:02d} crit format")
        lines = []
        batch_rows = 0
        first_id = 45600 + (no - 1) * 20 + 1
        last_id = first_id + 19
        lines.append(f"# UNX-L3-B{no:02d} · {theme}（UNX-F{first_id}–F{last_id} · 20 条）\n")
        lines.append(f"> AI-58 承办｜批主题：{theme}｜批内求和：6,000 行（守恒断言内建）｜状态列：[骨架] 不冒充深化｜判据主轴：包安装/卸载/升级全账+签名验证｜上游：AI-57（PreinstallRegistry 冻结签）+AI-55（K5 PackageSourceFeed 契约先行 fake，R-L3-001）｜横向联签：AI-48（J3 签名原语/信任存储本体零重写）、AI-49（J4 SandboxGrantConsumer 消费）、AI-24（E4 包格式分界联签）、AI-26（F5 商店前端入口分界）、AI-95（许可账逐包）｜红线预申报：空单（无引导设施/硬件数据安全条目）｜对抗面：{adv[:24]}…｜边界面：{bnd[:24]}…｜防重：五范围 grep 零撞号留痕\n")
        for i, (name, crit) in enumerate(entries):
            fid = 45600 + (no - 1) * 20 + i + 1
            if name.startswith(f"B{no:02d} "):
                # 收口类条目不重复判据词
                crit_use = crit
            else:
                crit_use = crit
            j = f"UNX-F{fid}-J1"
            lines.append(f"### UNX-F{fid} · {name}")
            lines.append(f"- 域/批：L3/B{no:02d}｜纯功能行数：300｜状态：[骨架]｜判据：{j} {crit_use}\n")
            all_ids.append(fid)
            all_crits.append(j)
            batch_rows += 300
            total_rows += 300
        # adversarial/boundary header line for items 15/16 already covered in names
        assert batch_rows == 6000, f"B{no:02d} rows {batch_rows}"
        vols.append((no, theme, first_id, last_id, "\n".join(lines)))
    # 断言1 条数
    assert len(all_ids) == 300, f"total items {len(all_ids)}"
    # 断言2 ID 连续
    assert all_ids == list(range(45601, 45901)), "IDs not contiguous"
    # 断言3 行数守恒
    assert total_rows == 90000, f"total rows {total_rows}"
    # 断言4 判据唯一
    assert len(set(all_crits)) == 300, "crits not unique"
    # 断言5 批主题对位（15 批主题全唯一）
    themes = [b["theme"] for b in BATCHES]
    assert len(set(themes)) == 15, "themes not unique"
    if problems:
        print("PROBLEMS:", problems); sys.exit(1)
    print(f"五断言 ALL PASS：300 条 / F45601–F45900 连续 / 90,000 行守恒 / 判据 300 唯一 / 15 批主题对位")
    return vols

def write_files(vols):
    sha = hashlib.sha256()
    for no, theme, fid0, fid1, text in vols:
        path = os.path.join(BATCH_DIR, f"UNX-L3-B{no:02d}.md")
        with io.open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text + "\n")
        sha.update(text.encode("utf-8"))
    print("15 批册已写出:", BATCH_DIR)
    print("SHA-256(卷正文流) 前 16 位:", sha.hexdigest()[:16])

