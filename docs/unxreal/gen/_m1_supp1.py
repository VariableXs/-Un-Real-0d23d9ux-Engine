def normalize():
    """每批行数守恒 6,000：差额均摊到该批前 10 条（域内批内 ±5% 自由口径，附则四）。"""
    for batch in B:
        items = batch[4]
        diff = 6000 - sum(x[1] for x in items)
        per, rem = divmod(diff, 20)
        items = [(n, l + per + (1 if i < rem else 0), e) for i, (n, l, e) in enumerate(items)]
        batch[4][:] = items

