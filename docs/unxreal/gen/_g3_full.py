def validate():
    ids, judges, rows = [], set(), 0
    for bno, theme, blurb, entries in B:
        assert len(entries) == 20
        assert sum(LINES) == 6000
        for i, (t, jd) in enumerate(entries, 1):
            fid = 25900 + (bno-16)*20 + i
            ids.append(fid)
            jid = J(fid)
            assert jid not in judges
            judges.add(jid)
            rows += LINES[i-1]
    assert ids == list(range(25901, 26401)), "ID 不连续"
    assert rows == 150000
    assert len(judges) == 500
    assert len(B) == 25
    return True

