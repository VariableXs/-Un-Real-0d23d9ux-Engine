def check_dupe():
    """断言①/⑤：F81001–F81300 于独立册目录既有文件与主册零命中"""
    pat = re.compile(r"UNX-F(\d{5,6})")
    hits = []
    for fn in os.listdir(FOLDER):
        if fn.endswith(".md") and fn not in (os.path.basename(INDEPENDENT), os.path.basename(MASTER)):
            with io.open(os.path.join(FOLDER, fn), "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()
            for m in pat.finditer(content):
                if 81001 <= int(m.group(1)) <= 81300:
                    hits.append(f"{fn}:F{m.group(1)}")
    assert not hits, f"断言①失败：F81001–F81300 已被占用 {hits[:5]}"
    with io.open(MASTER, "r", encoding="utf-8", errors="ignore") as f:
        assert not any(81001 <= int(m.group(1)) <= 81300 for m in pat.finditer(f.read())) or os.environ.get("A81_RESUME") == "1", "断言⑤失败：主汇编册已含 F81001–F81300"
    print("[1/5] 断言①⑤ PASS：F81001–F81300 全目录零占用")

