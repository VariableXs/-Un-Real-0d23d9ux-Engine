def balance(items):
    total = sum(l for _, l in items)
    diff, guard = 6000 - total, 0
    while diff != 0 and guard < 5000:
        guard += 1
        idx = 1 + (guard - 1) % 17
        name, line = items[idx]
        if diff > 0 and line < 360:
            step = min(20, 360 - line, diff); items[idx] = (name, line + step); diff -= step
        elif diff < 0 and line > 180:
            step = min(20, line - 180, -diff); items[idx] = (name, line - step); diff += step
    assert diff == 0
    return [l for _, l in items]

