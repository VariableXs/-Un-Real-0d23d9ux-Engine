def load_rows():
    text = open(SRC, encoding="utf-8").read()
    batches = {}   # bid -> (theme, countersign)
    rows = []      # (id, name, j1)
    cur = None
    for line in text.splitlines():
        m = re.match(r"^## 批 (GOV98-B\d+)（(.+?) · 6,000 行）", line)
        if m:
            cur = m.group(1); batches[cur] = [m.group(2), ""]
            continue
        m = re.match(r"^\| (UNX-GOV-98\d{3}) \| (.+?) \| \d+ \| 增补 \| (.+?) \|$", line)
        if m and cur:
            rid, name, j1 = m.groups()
            batches[cur][1] = j1  # 每批判据同文，取末次即可
            rows.append((rid, name, j1, cur))
    return batches, rows

