def balance(items):
    """行数守恒到 6,000：None 视为 300，差值按 ±20 档摊到第 2–18 条（下标 1–17）。"""
    items = [(n, 300 if l is None else l) for n, l in items]
    total = sum(l for _, l in items)
    diff = 6000 - total
    assert diff % 20 == 0 or True
    i = 1
    guard = 0
    while diff != 0 and guard < 5000:
        guard += 1
        idx = 1 + (guard - 1) % 17
        name, line = items[idx]
        if diff > 0 and line < 360:
            step = min(20, 360 - line, diff)
            items[idx] = (name, line + step); diff -= step
        elif diff < 0 and line > 180:
            step = min(20, line - 180, -diff)
            items[idx] = (name, line - step); diff += step
        else:
            continue
    if diff != 0:
        raise AssertionError("行数守恒失败")
    return [l for _, l in items]

