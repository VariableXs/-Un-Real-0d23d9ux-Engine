def table_rows(bidx):
    ids = entry_ids(bidx)
    rows = []
    for i, (name, crit) in enumerate(BATCHES[bidx]["entries"]):
        fid = ids[i]
        rows.append(f"| UNX-F{fid} | {name} | {LINES[i]} | 增补 | UNX-F{fid}-J1 {crit}；判据锚定 {BATCHES[bidx]['anchor']} |")
