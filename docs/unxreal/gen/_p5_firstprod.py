def fill_rows(items, anchor_rows):
    """item1=anchor；其余 None 均衡填充，使总和恰为 6000，全部落在 200–440。"""
    named = [(n, r) for n, r in items]
    rows = [anchor_rows]
    free = [(i, n) for i, (n, r) in enumerate(named[1:], start=1) if r is None]
    fixed = [r for _, r in named[1:] if r is not None]
    remaining = 6000 - anchor_rows - sum(fixed)
    n_free = len(free)
    assert n_free > 0, "批内必须有 None 条目用于均衡"
    base = remaining // n_free
    rem = remaining % n_free
    assert 200 <= base <= 440, f"均衡基线越界: {base}"
    fill = {}
    for k, (idx, _) in enumerate(free):
        fill[idx] = base + (1 if k < rem else 0)
    out = []
    for i, (n, r) in enumerate(named):
        out.append((n, rows[0] if i == 0 else (r if r is not None else fill[i])))
    assert sum(r for _, r in out) == 6000
    return out

