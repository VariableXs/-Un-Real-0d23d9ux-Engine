def disp_name(b, name):
    if b["bid"] in ITYPE and name in GENERIC:
        return f"{I_DOMAIN[b['bid']]}向联签 · {name}"
    return name

def entry_ids(bidx):
    start = BASE + bidx*20 + 1
    return [start + i for i in range(20)]

def crit_of(b, i, fid):
    name, crit = b["entries"][i]
    if b["bid"] in ETYPE:
        return f"UNX-F{fid}-J1 {crit}；UNX-F{fid}-J1R 反路径：与「{name}」同型错误注入 ×10 全检出且异常零静默"
    return f"UNX-F{fid}-J1 {crit}"

def table_rows(bidx):
    ids = entry_ids(bidx)
    rows = []
    for i, (name, crit) in enumerate(BATCHES[bidx]["entries"]):
        fid = ids[i]
        name = disp_name(BATCHES[bidx], name)
        rows.append(f"| UNX-F{fid} | {name} | {LINES[i]} | 增补 | {crit_of(BATCHES[bidx], i, fid)}；判据锚定 {BATCHES[bidx]['anchor']} |")
    return rows

def batch_block(bidx, standalone=True):
    b = BATCHES[bidx]
    start = BASE + bidx*20 + 1
    end = start + 19
    tag = "（E 型双判据）" if b["bid"] in ETYPE else ""
    lines = []
    head = f"## 批 UNX-M4-{b['bid']}（F{start}–F{end} · {b['theme']}{tag} · 6,000 行）" if standalone else \
           f"#### 批 UNX-M4-{b['bid']}（F{start}–F{end} · {b['theme']}{tag} · 6,000 行）"
    lines.append(head); lines.append("")
    lines.append("| ID | 深化名（deepen/M4-"+b['bid']+"） | 行数 | 状态 | 证据与判据锚定 |")
    lines.append("|---|---|---|---|---|")
    lines += table_rows(bidx)
    lines.append("")
    note = b["note"]
    dup = f"批 {b['bid']} 防重声明："
    if note.startswith(dup):
        note = note[len(dup):]
    lines.append(f"**批 {b['bid']} 防重声明**：{note}")
    return "\n".join(lines)

