def main():
    rows = build_rows()
    # 断言 1：15 批 × 20 条
    assert len(rows) == 15, "断言1失败：批数 != 15"
    assert all(len(b[2]) == 20 for b in rows), "断言1失败：某批条数 != 20"
    # 断言 2：ID 连续零跳号零重复
    ids = [x[0] for b in rows for x in b[2]]
    assert len(ids) == 300 and len(set(ids)) == 300, "断言2失败：ID 重复"
    nums = [int(x.rsplit("-", 1)[1]) for x in ids]
    assert nums == list(range(98001, 98301)), "断言2失败：ID 非连续 98001–98300"
    # 断言 3：名称唯一
    names = [x[1] for b in rows for x in b[2]]
    assert len(set(names)) == 300, "断言3失败：深化名重复"
    # 断言 4：行数守恒
    sums = [sum(x[2] for x in b[2]) for b in rows]
    assert all(s == 6000 for s in sums), f"断言4失败：批行数 {sums}"
    total = sum(sums)
    assert total == 90000, "断言4失败：全卷行数 != 90,000"
    # 断言 5：判据内嵌 ID 零错位
    for b in rows:
        for fid, name, n, judge in b[2]:
            assert fid + "-J1" in judge, f"断言5失败：{fid} 判据 ID 错位"
    # 断言 6+7：主册防重 + 纯追加
    with open(MASTER, "rb") as f:
        prefix = f.read()
    assert b"UNX-GOV-98" not in prefix, "断言6失败：主册已存在 UNX-GOV-98 段（防重命中）"
    prefix_hash = hashlib.sha256(prefix).hexdigest()
    book_md, _ = render_book(rows)
    with open(BOOK, "w", encoding="utf-8", newline="\n") as f:
        f.write(book_md)
    stamp = "2026-10-01"
    reg = (f"\n\n## 增补卷登记注 · AI-98 · 多会话协调官（{stamp} · 独立编号不占域账）\n\n"
           f"- AI-98 职责域增补卷一立账：**300 项新功能**（UNX-GOV-98001–98300 · 15 批 × 20 条 × 6,000 行 = 90,000 行 · "
           f"状态「增补」· 独立编号不占域账，判例承 AI-50/AI-83/AI-86/AI-91）。"
           f"批主题：B01 排班表引擎与波次窗账 / B02 依赖放行对表与 §37.2 序列表自动化 / B03 等锁仲裁判例库 / "
           f"B04 双活防与 roster 名册一致性 / B05 卡批让位与风险预算调度 / B06 跨组借调与副 AI 增派错峰 / "
           f"B07 回炉批与冻结批调度与补强池 / B08 互审对表出表收单 / B09 晨检 20 项与红项处置 / "
           f"B10 周报五行与月度自检十项 / B11 产能模型 T 季度重算与回炉率预警 / B12 观察名单与健康指标 / "
           f"B13 R-PROC-002 制度化裁定（母本+回播协议）/ B14 挂账排程收口 / B15 收官与移交。\n"
           f"- 全卷正文见独立册《AI-98 · 协调 · 300项新功能增补册卷一（98001–98300）.md》（本主册超 GitHub blobs "
           f"100MB 硬上限，沿 AI-71/AI-86 先例本卷以登记注+独立册双落盘）；生成器 docs/unxreal/gen/_gov98_firstprod.py "
           f"七断言 ALL PASS exit=0。\n")
    with open(MASTER, "ab") as f:
        f.write(reg.encode("utf-8"))
    with open(MASTER, "rb") as f:
        after = f.read()
    assert hashlib.sha256(after[: len(prefix)]).hexdigest() == prefix_hash, "断言7失败：主册前缀被改写"
    print("AI-98 GOV 卷一生成器 · 七断言 ALL PASS exit=0")
