for i, blk in enumerate(blocks):
    m = re.match(r'^### (UNX-F\d{4})', blk)
    if not m or m.group(1) not in FIX:
        continue
    eid = m.group(1)
    nb = blk
    for old, new in FIX[eid]:
        assert old in nb, f'{eid} MISS: {old[:24]}'
        nb = nb.replace(old, new, 1)
    blocks[i] = nb
    applied += 1
