for path, items in JOBS.items():
    t = io.open(path, encoding='utf-8').read()
    for fid, tail, add in items:
        i = t.find('### UNX-F' + fid + ' ')
        assert i != -1, (path, fid, '条目缺失')
        nxt = t.find('\n### UNX-F', i + 1)
        seg = t[i:nxt if nxt != -1 else len(t)]
        m = re.search(r'- 正文：.*$', seg, re.M)
        assert m, (path, fid, '正文行缺失')
        line = m.group(0)
        assert line.endswith(tail), (path, fid, '锚尾不匹配', line[-60:])
        newline = line[:-1] + '，' + add + '。'
        t = t[:i] + seg[:m.start()] + newline + seg[m.end():] + t[nxt if nxt != -1 else len(t):]
    io.open(path, 'w', encoding='utf-8', newline='\n').write(t)
    print(path, '扩写', len(items), '条落盘')
